# The site's one security level (auth_modes.php) and the password mode (passwords.php).
#
#   - each mode offers exactly its methods, on the login page and at auth.php; the old
#     names are aliases; an unknown value signs nobody in rather than opening the wiki;
#   - one method per account in sso+email: an SSO account gets no email code;
#   - raising the level ends sessions that came in by a method the account no longer uses;
#   - passwords: never in users.json nor any response but the one that makes a temporary
#     one; a temporary password only opens the change form; one message for every failure,
#     and an unknown address costs the same time; throttling, also for unknown addresses;
#     reset links built from APP_BASE_URL, never the Host header, single-use and expiring,
#     one mail a minute; a new password ends every other session; the current password is
#     needed to change it; leaving the mode deletes every stored password.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

fixture_start password || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Welcome'
fixture_users '{"users":[
  {"uid":1,"name":"Admin","otpEmail":"admin@example.com","email":"admin@example.com","role":"admin","auth":"otp"},
  {"uid":2,"name":"Pat","otpEmail":"pat@example.com","email":"pat@example.com","role":"editor","auth":"otp"},
  {"uid":3,"name":"Sam","sub":"s-sam","email":"sam@example.com","role":"editor","auth":"oidc"},
  {"uid":4,"name":"Bo","sub":"s-bo","otpEmail":"bo@example.com","email":"bo@corp.example","role":"editor","auth":"both"},
  {"uid":5,"name":"Root","otpEmail":"root@example.com","email":"root@example.com","role":"admin","auth":"otp"}
]}'
BASE='https://wiki.example.test'
MAIL=$WIKI_ROOT/mail.log
cat >> "$WIKI_APP/config.php" <<CFG
define('MAIL_PROVIDER', 'sendgrid');
define('SENDGRID_API_KEY', 'test');
define('SENDGRID_FROM_EMAIL', 'wiki@example.com');
define('APP_BASE_URL', '$BASE');
CFG
python3 - "$WIKI_APP/mailer.php" "$MAIL" <<'PY'
import sys
p, log = sys.argv[1], sys.argv[2]
s = open(p).read()
s = s.replace("function send_email(string $to, string $to_name, string $subject, string $html_body): bool {",
  "function send_email(string $to, string $to_name, string $subject, string $html_body): bool {\n"
  f"    file_put_contents('{log}', json_encode(['to' => $to, 'subject' => $subject, 'body' => $html_body]) . \"\\n\", FILE_APPEND);\n"
  "    return true;", 1)
open(p, 'w').write(s)
PY
printf '<?php if (function_exists("opcache_reset")) opcache_reset(); echo "ok";' > "$WIKI_APP/__test_opcache.php"
curl -s "$WIKI_URL/__test_opcache.php" > /dev/null
cat > "$WIKI_APP/__test_oidc.php" <<'SHIM'
<?php
// GENERATED BY tests/auth_modes.test.sh — the provider's half of an SSO sign-in.
require_once __DIR__ . '/config.php';
require_once __DIR__ . '/accounts.php';
require_once __DIR__ . '/remember_me.php';
session_start();
echo wiki_oidc_complete(['sub' => $_GET['sub'] ?? '', 'email' => $_GET['email'] ?? '', 'name' => $_GET['name'] ?? ''], 'idtok');
SHIM

USERS=$WIKI_SYS/users.json
CREDS=$WIKI_SYS/credentials.json
set_mode() {
    sed -i "s#^define('AUTHENTICATION',.*#define('AUTHENTICATION', '$1');#" "$WIKI_APP/config.php"
    curl -s "$WIKI_URL/__test_opcache.php" > /dev/null
}
mails_to() { python3 -c "import json;print(len([1 for l in open('$MAIL') if l.strip() and json.loads(l)['to']=='$1']))" 2>/dev/null || echo 0; }
last_mail() { python3 -c "
import json
m=[json.loads(l) for l in open('$MAIL') if l.strip()]
m=[x for x in m if x['to']=='$1']
print((m[-1]['subject']+' || '+m[-1]['body']) if m else '')" 2>/dev/null; }
link_in_mail() { last_mail "$1" | grep -o 'href="[^"]*"' | head -1 | sed 's/href="//; s/"$//; s/&amp;/\&/g'; }
whoami() { get_as "$1" 'index.php' | command grep -o 'data-user-uid="[0-9]*"' | command grep -o '[0-9]*'; }
location() { curl -s -o /dev/null -w '%{redirect_url}' -b "$1" -c "$1" --max-time 15 "$WIKI_URL/$2"; }
post_loc() { curl -s -o /dev/null -w '%{redirect_url}' -b "$1" -c "$1" --max-time 15 -X POST -d "$3" "$WIKI_URL/$2"; }
login_page_err() { get_as "$1" 'login.php' | grep -o 'data-i18n="login\.[a-z.-]*"' | head -3 | tr '\n' ' '; }
pw_login() { rm -f "$1"; post_loc "$1" 'auth.php?action=password_login' "email=$2&password=$3"; }
clear_throttle() { rm -f "$WIKI_SYS/login_throttle.json"; }
# The test's admin session is an account whose password never changes: a credential
# change ends every session older than it, and fixture sessions carry no sign-in time.
ADM=$WIKI_ROOT/jar-admin
fixture_login "$ADM" "uid=5&name=Root&role=admin&auth=otp"

# ── the modes ────────────────────────────────────────────────────────────────
section 'each mode offers exactly its methods'
forms() {  # what the login page offers: s(so) e(mail) p(assword) x (config error)
    local h; h=$(curl -s "$WIKI_URL/login.php")
    printf '%s%s%s%s' \
        "$(printf '%s' "$h" | grep -q 'href="auth.php"' && echo s)" \
        "$(printf '%s' "$h" | grep -q 'action=otp_send' && echo e)" \
        "$(printf '%s' "$h" | grep -q 'action=password_login' && echo p)" \
        "$(printf '%s' "$h" | grep -q 'login.err.config' && echo x)"
}
for pair in sso:s sso+email:se email:e password:p oidc:s otp:e both:se pasword:x PASSWORD:p; do
    set_mode "${pair%%:*}"
    assert_eq "${pair%%:*}" "${pair#*:}" "$(forms)"
done
set_mode pasword
assert_eq 'an unknown mode keeps the wiki closed' 302 "$(curl -s -o /dev/null -w '%{http_code}' "$WIKI_URL/index.php")"
assert_contains '…and refuses every way in' 'login.php' "$(post_loc "$WIKI_ROOT/x" 'auth.php?action=password_login' 'email=pat@example.com&password=whatever-it-is')"

section 'a method outside its mode is refused at auth.php'
set_mode password
N=$(mails_to pat@example.com)
curl -s -X POST -d 'email=pat@example.com' "$WIKI_URL/auth.php?action=otp_send" > /dev/null
assert_eq 'password mode sends no email code'              "$N" "$(mails_to pat@example.com)"
assert_eq 'and has no SSO round trip'                      "$WIKI_URL/login.php" "$(location "$WIKI_ROOT/y" 'auth.php')"
set_mode sso
assert_eq 'sso mode takes no password'                     "$WIKI_URL/login.php" "$(post_loc "$WIKI_ROOT/z" 'auth.php?action=password_login' 'email=pat@example.com&password=x')"

# ── one method per account ───────────────────────────────────────────────────
section 'sso+email: an SSO account gets no email code'
set_mode sso+email
curl -s -X POST -d 'email=bo@example.com' "$WIKI_URL/auth.php?action=otp_send" > /dev/null
assert_contains 'Bo is told to use single sign-on'          'with single sign-on' "$(last_mail bo@example.com)"
assert_not_contains 'and gets no code'                      'login code' "$(last_mail bo@example.com)"
B=$WIKI_ROOT/jar-bo; rm -f "$B"
get_as "$B" '__test_oidc.php?sub=s-bo&email=bo@corp.example&name=Bo' > /dev/null
assert_eq 'positive control: Bo signs in with SSO'          4 "$(whoami "$B")"
P=$WIKI_ROOT/jar-pat-code; rm -f "$P"
post_as "$P" 'auth.php?action=otp_send' 'email=pat@example.com' > /dev/null
CODE=$(last_mail pat@example.com | grep -o '>[0-9]\{6\}<' | tr -d '<>')
post_as "$P" 'auth.php?action=otp_verify' "code=$CODE" > /dev/null
assert_eq 'an email-code account signs in by code'          2 "$(whoami "$P")"

section 'raising the level ends sessions that came in the weaker way'
set_mode sso
assert_eq "Pat's email-code session ends"                   "" "$(whoami "$P")"
assert_eq "Bo's SSO session stays"                          4 "$(whoami "$B")"

# ── passwords ────────────────────────────────────────────────────────────────
set_mode password
section 'an admin gives a temporary password'
R=$(post_as "$ADM" 'api.php?action=admin_password_temp' 'uid=2')
TEMP=$(printf '%s' "$R" | python3 -c 'import json,sys;print(json.load(sys.stdin).get("password",""))')
assert_contains 'the server makes one'                      '"success":true' "$R"
assert_eq 'shaped as four groups'                           1 "$(printf '%s' "$TEMP" | grep -cE '^[A-Za-z0-9]{4}(-[A-Za-z0-9]{4}){3}$')"
assert_contains 'a reader cannot'                           'Admin' "$(fixture_login "$WIKI_ROOT/jr" 'uid=3&role=reader&auth=oidc'; post_as "$WIKI_ROOT/jr" 'api.php?action=admin_password_temp' 'uid=1')"
assert_not_contains 'no hash in users.json'                 '$argon' "$(cat "$USERS")"
assert_not_contains '…of either kind'                       '$2y$' "$(cat "$USERS")"
assert_contains 'it is in credentials.json'                 '"mustChange": true' "$(cat "$CREDS")"
assert_not_contains 'the plain password is stored nowhere'  "$TEMP" "$(cat "$CREDS" "$USERS")"
L=$(get_as "$ADM" 'api.php?action=admin_get_users')
assert_not_contains 'the admin list carries no hash'        '$argon' "$L"
assert_contains '…only whether one is set'                  '"password":{"set":true,"mustChange":true}' "$L"
assert_eq 'the file is private'                             600 "$(stat -c %a "$CREDS")"

section 'a temporary password only opens the change form'
PT=$WIKI_ROOT/jar-pat
assert_eq 'signing in with it'                              "$WIKI_URL/login.php?step=change" "$(pw_login "$PT" pat@example.com "$TEMP")"
assert_eq 'is not a session'                                "" "$(whoami "$PT")"
post_loc "$PT" 'auth.php?action=password_change' 'password=short&password2=short' > /dev/null
assert_contains 'too short is refused'                      'login.err.pw-short' "$(login_page_err "$PT")"
post_loc "$PT" 'auth.php?action=password_change' 'password=correct horse battery&password2=correct horse battery!' > /dev/null
assert_contains 'two that differ are refused'               'login.err.pw-mismatch' "$(login_page_err "$PT")"
post_loc "$PT" 'auth.php?action=password_change' 'password=correct horse battery&password2=correct horse battery' > /dev/null
assert_eq 'a good one signs Pat in'                         2 "$(whoami "$PT")"
assert_contains '…and is no longer temporary'               '"mustChange": false' "$(cat "$CREDS")"
assert_eq 'the temporary one is spent'                      "$WIKI_URL/login.php" "$(pw_login "$WIKI_ROOT/old" pat@example.com "$TEMP")"

section 'one message for every failure'
clear_throttle
pw_login "$WIKI_ROOT/w1" pat@example.com 'wrong password here' > /dev/null
assert_contains 'a wrong password'                          'login.err.bad-password' "$(login_page_err "$WIKI_ROOT/w1")"
pw_login "$WIKI_ROOT/w2" nobody@example.com 'wrong password here' > /dev/null
assert_contains 'an unknown address says the same'          'login.err.bad-password' "$(login_page_err "$WIKI_ROOT/w2")"
pw_login "$WIKI_ROOT/w3" sam@example.com 'wrong password here' > /dev/null
assert_contains 'an SSO account says the same'              'login.err.bad-password' "$(login_page_err "$WIKI_ROOT/w3")"
t_of() { curl -s -o /dev/null -w '%{time_total}' -X POST -d "email=$1&password=wrong+password+here" "$WIKI_URL/auth.php?action=password_login"; }
TIMES=$(for i in 1 2 3; do printf '%s %s\n' "$(t_of pat@example.com)" "$(t_of ghost$i@example.com)"; done)
assert_eq 'an unknown address takes as long as a real one' ok "$(printf '%s' "$TIMES" | python3 -c '
import sys, statistics
rows=[l.split() for l in sys.stdin if l.strip()]
real=statistics.median(float(r[0]) for r in rows); ghost=statistics.median(float(r[1]) for r in rows)
print("ok" if ghost >= real*0.5 else f"real {real:.3f}s, unknown {ghost:.3f}s")')"
clear_throttle

section 'throttling'
for i in 1 2 3 4 5; do pw_login "$WIKI_ROOT/t" pat@example.com "wrong guess $i!" > /dev/null; done
pw_login "$WIKI_ROOT/t" pat@example.com 'correct horse battery' > /dev/null
assert_contains 'after five failures even the right password waits' 'login.err.throttled' "$(login_page_err "$WIKI_ROOT/t")"
assert_eq '…and signs nothing in'                           "" "$(whoami "$WIKI_ROOT/t")"
for i in 1 2 3 4 5; do pw_login "$WIKI_ROOT/u" ghost@example.com "wrong guess $i!" > /dev/null; done
pw_login "$WIKI_ROOT/u" ghost@example.com 'anything at all here' > /dev/null
assert_contains 'an unknown address is throttled the same'  'login.err.throttled' "$(login_page_err "$WIKI_ROOT/u")"
R=$(post_as "$ADM" 'api.php?action=admin_password_temp' 'uid=1')
ATEMP=$(printf '%s' "$R" | python3 -c 'import json,sys;print(json.load(sys.stdin).get("password",""))')
assert_eq 'another account from the same address is not' "$WIKI_URL/login.php?step=change" "$(pw_login "$WIKI_ROOT/a" admin@example.com "$ATEMP")"
clear_throttle

section 'forgot password'
N=$(mails_to pat@example.com)
curl -s -H 'Host: evil.example' -X POST -d 'email=pat@example.com' "$WIKI_URL/auth.php?action=password_forgot" > /dev/null
LINK=$(link_in_mail pat@example.com)
assert_eq 'a link is mailed'                                $((N + 1)) "$(mails_to pat@example.com)"
assert_contains 'built from APP_BASE_URL'                   "$BASE/login.php?step=set&t=" "$LINK"
assert_not_contains 'never from the Host header'            'evil.example' "$LINK"
curl -s -X POST -d 'email=pat@example.com' "$WIKI_URL/auth.php?action=password_forgot" > /dev/null
assert_eq 'a second request within a minute mails nothing' $((N + 1)) "$(mails_to pat@example.com)"
F=$WIKI_ROOT/jar-forgot; rm -f "$F"
post_loc "$F" 'auth.php?action=password_forgot' 'email=nobody@example.com' > /dev/null
assert_contains 'an unknown address gets the same answer'   'login.notice.reset-sent' "$(get_as "$F" 'login.php' | grep -o 'login.notice.reset-sent')"
assert_eq '…and no mail'                                    0 "$(mails_to nobody@example.com)"
TOKEN=${LINK##*t=}
assert_not_contains 'the token is not stored as such'       "$TOKEN" "$(cat "$WIKI_SYS/password_tokens.json")"

section 'setting a password from the link'
S=$WIKI_ROOT/jar-set; rm -f "$S"
assert_contains 'the link opens the form'                   'action=password_set' "$(get_as "$S" "login.php?step=set&t=$TOKEN")"
post_loc "$S" 'auth.php?action=password_set' "t=$TOKEN&password=a brand new passphrase&password2=a brand new passphrase" > /dev/null
assert_eq 'and signs Pat in'                                2 "$(whoami "$S")"
assert_eq 'every other session has ended'                   "" "$(whoami "$PT")"
S2=$WIKI_ROOT/jar-set2; rm -f "$S2"
post_loc "$S2" 'auth.php?action=password_set' "t=$TOKEN&password=another new passphrase&password2=another new passphrase" > /dev/null
assert_contains 'the link works once'                       'login.err.link-invalid' "$(login_page_err "$S2")"
assert_eq 'the old password is gone'                        "$WIKI_URL/login.php" "$(pw_login "$WIKI_ROOT/o" pat@example.com 'correct horse battery')"
assert_eq 'the new one works'                               "$WIKI_URL/index.php" "$(pw_login "$WIKI_ROOT/n" pat@example.com 'a brand new passphrase')"
sleep 61   # past the one-mail-a-minute gap
curl -s -X POST -d 'email=pat@example.com' "$WIKI_URL/auth.php?action=password_forgot" > /dev/null
OLD=$(link_in_mail pat@example.com); OLD=${OLD##*t=}
python3 - "$WIKI_SYS/password_tokens.json" <<'PY'
import json, sys
p = sys.argv[1]; d = json.load(open(p))
for v in d.values(): v['expires'] = 1
json.dump(d, open(p, 'w'))
PY
assert_contains 'an expired link is refused'               'login.err.link-invalid' "$(get_as "$WIKI_ROOT/e" "login.php?step=set&t=$OLD" | grep -o 'login.err.link-invalid' | head -1)"

section 'changing your own password'
C=$WIKI_ROOT/n
assert_contains 'the current password is required'         'account.err.pw-current' "$(post_as "$C" 'api.php?action=account_password_change' 'current=not it&password=the next passphrase&password2=the next passphrase')"
assert_contains 'positive control: with it, it changes'    '"success":true' "$(post_as "$C" 'api.php?action=account_password_change' 'current=a brand new passphrase&password=the next passphrase&password2=the next passphrase')"
assert_eq 'this session stays'                              2 "$(whoami "$C")"
assert_eq 'the other one ends'                              "" "$(whoami "$S")"
assert_contains 'an SSO session cannot use it'              'not-offered' "$(fixture_login "$WIKI_ROOT/ss" 'uid=3&role=editor&auth=oidc'; post_as "$WIKI_ROOT/ss" 'api.php?action=account_password_change' 'current=x&password=y&password2=y')"

section 'leaving the password mode deletes every password'
assert_eq '(there are passwords)'                           yes "$([ -s "$CREDS" ] && echo yes)"
set_mode email
curl -s "$WIKI_URL/login.php" > /dev/null
assert_eq 'they are gone'                                   no "$([ -e "$CREDS" ] && echo yes || echo no)"
set_mode password
assert_eq 'switching back does not revive them'             "$WIKI_URL/login.php" "$(pw_login "$WIKI_ROOT/r" pat@example.com 'the next passphrase')"
set_mode pasword
R=$(post_as "$ADM" 'api.php?action=admin_password_temp' 'uid=2'); set_mode password
R=$(post_as "$ADM" 'api.php?action=admin_password_temp' 'uid=2')
set_mode pasword; curl -s "$WIKI_URL/login.php" > /dev/null
assert_eq 'a typo in the mode does not wipe them'          yes "$([ -s "$CREDS" ] && echo yes)"

section 'Admin → Users speaks the mode'
keys() { get_as "$ADM" 'index.php' | grep -o 'data-i18n="admin\.\(users\.add-[a-z-]*-btn\|role-hint[a-z-]*\)"' | sed 's/data-i18n=//; s/"//g' | sort | tr '\n' ' '; }
set_mode password
assert_eq 'password: "Add User" and how to give a password' 'admin.role-hint-password admin.users.add-user-btn ' "$(keys)"
set_mode email
assert_eq 'email: "Add OTP User" and the code hint'      'admin.role-hint-email admin.users.add-otp-btn ' "$(keys)"
set_mode sso+email
assert_eq 'sso+email: the mixed hint'                    'admin.role-hint-mixed admin.users.add-otp-btn ' "$(keys)"
set_mode sso
assert_eq 'sso: the Requests-tab hint'                   'admin.role-hint admin.users.add-otp-btn ' "$(keys)"

section 'the first admin, from the command line'
set_mode password
cli() { ( cd "$WIKI_APP" && php tools/set_password.php "$@" 2>&1 ); }
assert_contains 'an unknown address needs --create'        'Add --create' "$(cli new.admin@example.com)"
OUT=$(cli new.admin@example.com --create 'New Admin')
assert_contains 'with it, the account is made'             'Created admin account' "$OUT"
NEWPW=$(printf '%s' "$OUT" | grep -oE '[A-Za-z0-9]{4}(-[A-Za-z0-9]{4}){3}')
assert_eq 'and its temporary password opens the change form' "$WIKI_URL/login.php?step=change" "$(pw_login "$WIKI_ROOT/na" new.admin@example.com "$NEWPW")"
set_mode email
assert_contains 'it refuses outside the password mode'      "not 'password'" "$(cli pat@example.com)"
assert_eq 'it is not reachable over the web'                404 "$(curl -s -o /dev/null -w '%{http_code}' "$WIKI_URL/tools/set_password.php")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
