# Admin → AI → Agent Jobs in a browser: the schedule part of the job form. Each frequency
# shows its own rows, the preview asks the server for the next runs as the form changes,
# and what is picked on screen is what is stored.
#
# tests/agent_job_schedule.test.sh proves the engine; this proves the form can produce
# every shape it accepts.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_users '{"users":[{"uid":-5,"name":"bot","role":"editor","is_ai":true,"ai_config":{"provider":"openai","model":"m","api_key":"k"}}]}'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/agent_job_schedule_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const set = (sel, v) => { const el = $(sel); if (!el) throw new Error('missing ' + sel); el.value = v; el.dispatchEvent(new Event('change', { bubbles: true })); };
const type = (sel, v) => { const el = $(sel); if (!el) throw new Error('missing ' + sel); el.value = v; el.dispatchEvent(new Event('input', { bubbles: true })); };
const shown = (sel) => { const el = $(sel); return !!el && el.offsetParent !== null; };
const report = (out) => { document.title = 'PROBE' + out; };
const server = async () => (await (await fetch('api.php?action=admin_get_agent_jobs')).json()).jobs;

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  let out = '';
  click($('#admin-btn'));                                     await sleep(800);
  click($('.admin-group[data-group="ai"]'));                  await sleep(500);
  click($('.admin-tab[data-tab="jobs"]'));                    await sleep(1000);
  click($('#admin-jobs-add-btn'));                            await sleep(400);
  out += ' types=' + $$('#job-f-sched-type option').map(o => o.value).join('+');
  out += ' default=' + $('#job-f-sched-type').value + '/' + (shown('#job-f-sched-time') ? 'time' : 'notime');
  await sleep(900);
  out += ' preview=' + ($('#job-f-sched-preview').textContent.includes(':') ? 'dates' : 'empty');

  set('#job-f-sched-type', 'hourly');                        await sleep(900);
  out += ' hourly=' + (shown('#job-f-sched-time') ? 'time' : 'notime') + '/' + (shown('#job-f-sched-from') ? 'window' : 'nowindow')
       + '/' + (shown('.job-f-dow') ? 'days' : 'nodays') + '/' + $('#job-f-sched-unit').textContent;
  out += ' hpreview=' + $('#job-f-sched-preview').textContent.split(' · ').length;

  set('#job-f-sched-type', 'monthly');                       await sleep(200);
  out += ' monthly=' + (shown('#job-f-sched-nth') ? 'nth' : 'nonth') + '/' + (shown('.job-f-dow') ? 'days' : 'nodays');

  set('#job-f-sched-type', 'cron');                          await sleep(200);
  out += ' cronrows=' + (shown('#job-f-sched-cron') ? 'input' : 'noinput') + '/' + (shown('#job-f-sched-interval') ? 'every' : 'noevery');
  type('#job-f-sched-cron', '0 99 * * *');                   await sleep(900);
  out += ' cronerr=' + ($('#job-f-sched-preview').classList.contains('admin-sched-preview-error') ? 'shown' : 'none');
  type('#job-f-sched-cron', '0 9 * * 1-5');                  await sleep(900);
  out += ' cronok=' + ($('#job-f-sched-preview').classList.contains('admin-sched-preview-error') ? 'error' : 'ok');

  $('#job-f-name').value = 'Morning';
  $('#job-f-prompt').value = 'Summarise';
  click($('#job-f-save-btn'));                                await sleep(1500);
  let job = (await server())[0] || {};
  out += ' stored=' + JSON.stringify(job.schedule);
  const row = $('#admin-jobs-list tbody tr');
  out += ' summary=' + (row ? row.children[3].textContent : '?');
  out += ' nextcol=' + (row && row.children[4].textContent.trim() !== '—' ? 'set' : 'empty');

  // Edit: reopens on cron, switch to the second Tuesday of every 2nd month.
  click($$('#admin-jobs-list button').find(b => b.classList.contains('btn-secondary'))); await sleep(500);
  out += ' reopened=' + $('#job-f-sched-type').value + '/' + $('#job-f-sched-cron').value;
  set('#job-f-sched-type', 'monthly');                       await sleep(100);
  type('#job-f-sched-interval', '2');
  click($('input[name="job-f-sched-by"][value="nth"]'));
  set('#job-f-sched-nth', '2');
  set('#job-f-sched-weekday', '2');
  type('#job-f-sched-time', '09:30');
  click($('#job-f-save-btn'));                                await sleep(1500);
  job = (await server())[0] || {};
  out += ' stored2=' + JSON.stringify(job.schedule);
  const row2 = $('#admin-jobs-list tbody tr');
  out += ' summary2=' + (row2 ? row2.children[3].textContent : '?');
  return out;
};

setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -sf --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the frequency picker'
assert_contains "all seven frequencies offered"    'types=minutes+hourly+daily+weekly+monthly+yearly+cron' "$PROBE"
assert_contains "a new job starts daily, at a time" 'default=daily/time' "$PROBE"
assert_contains "the preview shows next runs"      'preview=dates'        "$PROBE"
assert_contains "hourly: a window and day filter, no single time" 'hourly=notime/window/days/hours' "$PROBE"
assert_contains "  …previewing five runs"          'hpreview=5'           "$PROBE"
assert_contains "monthly: the nth-weekday rule, no day boxes" 'monthly=nth/nodays' "$PROBE"
assert_contains "cron: the expression, no Every"   'cronrows=input/noevery' "$PROBE"
assert_contains "a bad cron shows while typed"     'cronerr=shown'        "$PROBE"
assert_contains "  …and clears when fixed"         'cronok=ok'            "$PROBE"

section 'what is stored'
assert_contains "the cron schedule reached the server" 'stored={"type":"cron","cron":"0 9 * * 1-5"}' "$PROBE"
assert_contains "the list summarises it"           'summary=Cron 0 9 * * 1-5' "$PROBE"
assert_contains "  …with a next run"               'nextcol=set'          "$PROBE"
assert_contains "edit reopens on it"               'reopened=cron/0 9 * * 1-5' "$PROBE"
assert_contains "the nth-weekday rule is stored"   'stored2={"type":"monthly","interval":2,"time":"09:30","nth":2,"weekday":2}' "$PROBE"
assert_contains "  …and summarised"                'summary2=The second Tue every 2 months at 09:30' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
