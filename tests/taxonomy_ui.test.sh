#
# The taxonomy in the browser: the tag picker (its size, the tree, headings, filtering,
# adding a new term, Apply), the type-ahead offering terms by any part of their path,
# controlled mode refusing a typed tag, and the Admin → Content → Taxonomy pane.
#
# tests/taxonomy.test.sh holds the server's rules. This is what no HTTP assertion can
# see: that the picker is 80% of the window, that a heading has no checkbox, and that
# what the user ticks is what the page ends up tagged with.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
fixture_page 'Main/Notes.md' '# Notes'
fixture_page 'Main/Other.md' '# Other'
cat > "$WIKI_PAGES/taxonomy.json" <<'JSON'
{"version":1,"nodes":[
  {"name":"Aardvark"},
  {"name":"Department","heading":true,"children":[
     {"name":"Finance","description":"Money matters"},
     {"name":"HR"}]},
  {"name":"Status","heading":true,"children":[{"name":"Draft"},{"name":"Final"}]}
]}
JSON

curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

page_id() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' \
        "$WIKI_PAGES/${2:-Main}/index.json" "$1"
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/taxonomy_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
import { api } from './modules/core/api.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection', e => {
    document.title = 'PROBE fatalRejection=' + (e.reason && e.reason.message || e.reason); });
const type = (el, v) => { el.value = v; el.dispatchEvent(new Event('input')); };
const enter = (el) => el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));

setTimeout(async () => {
  let out = '';
  try {
    out += ' btn=' + !!$('#tag-picker-btn');
    // Same line, same height as the field it belongs to.
    const ri = $('#tag-input').getBoundingClientRect(), rb = $('#tag-picker-btn').getBoundingClientRect();
    out += ' alignTop=' + (Math.abs(ri.top - rb.top) < 1) + ' alignBottom=' + (Math.abs(ri.bottom - rb.bottom) < 1)
        + ' beside=' + (rb.left >= ri.right);
    $('#tag-picker-btn').click();                 await sleep(800);
    const box = $('.tag-picker-content');
    const r = box.getBoundingClientRect();
    out += ' wRatio=' + (r.width / window.innerWidth).toFixed(2) + ' hRatio=' + (r.height / window.innerHeight).toFixed(2);
    out += ' headings=' + $$('.tag-picker-heading').map(h => h.textContent).join(',');
    out += ' boxes=' + $$('.tag-picker-tree input[type=checkbox]').map(c => c.dataset.tag).join(',');
    out += ' desc=' + ($$('.tag-picker-desc').map(d => d.textContent).join(',') || 'none');

    // Filter: a match keeps its ancestors and drops the rest.
    const search = $('.tag-picker-search');
    type(search, 'financ');                          await sleep(100);
    out += ' filtered=' + $$('.tag-picker-tree input[type=checkbox]').map(c => c.dataset.tag).join(',')
        + ' filteredHeadings=' + $$('.tag-picker-heading').map(h => h.textContent).join(',');
    enter(search);                                await sleep(100);   // ticks the first match
    out += ' count=' + $('.tag-picker-count').textContent;
    // A new tag, offered because the mode is free.
    type(search, 'Project / Apollo');             await sleep(100);
    const add = $('.tag-picker-add');
    out += ' addOffered=' + !!add;
    add.click();                                  await sleep(100);
    out += ' extras=' + $$('.tag-picker-extras input').map(c => c.dataset.tag + ':' + c.checked).join(',');
    $$('.tag-picker-footer .btn-blue')[0].click(); await sleep(1500);
    out += ' closed=' + !$('#tag-picker-modal');
    out += ' tags=' + JSON.stringify(state.currentPageTags);
    out += ' shown=' + $$('#tags-display .tag').map(x => x.firstChild.textContent).join(',');
    const tax = await api.call('get_taxonomy', { space: '' });
    out += ' grew=' + JSON.stringify(tax.nodes).includes('Apollo');

    // Type-ahead: by any part of the path, terms not already on the page.
    const input = $('#tag-input');
    input.focus(); type(input, 'dra');            await sleep(500);
    out += ' suggest=' + $$('#tag-suggestions li').map(li => li.textContent).join(',');
    type(input, 'depart');                        await sleep(500);
    out += ' suggestDept=' + $$('#tag-suggestions li').map(li => li.textContent).join(',');

    // Controlled: a typed non-term is refused before the request.
    await api.call('admin_taxonomy_mode', { space: '', mode: 'controlled' }, 'POST');
    $('#tag-picker-btn').click();                 await sleep(800);
    type($('.tag-picker-search'), 'Nope');        await sleep(100);
    out += ' addInControlled=' + !!$('.tag-picker-add');
    $$('.tag-picker-footer .btn-secondary')[0].click(); await sleep(200);
    const before = JSON.stringify(state.currentPageTags);
    type(input, 'Nope'); enter(input);            await sleep(1200);
    out += ' refused=' + (JSON.stringify(state.currentPageTags) === before)
        + ' toast=' + (($('#toast-message') || {}).textContent || '').includes('Nope');

    // Admin pane
    $('#admin-btn').click();                      await sleep(800);
    $('.admin-group[data-group=content]').click(); await sleep(200);
    $('.admin-tab[data-tab=taxonomy]').click();   await sleep(1200);
    $('#tax-launch').click();                      await sleep(500);
    out += ' adminRows=' + $$('#admin-tax-tree .tax-row').length
        + ' adminMode=' + ($('#admin-tax-mode') || {}).value
        + ' adminFolders=' + $$('#admin-tax-tree .tax-row.is-folder').length;
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  document.title = 'PROBE' + out;
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -sf --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

load() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=40000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "page $1"
}

load Notes.md
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the picker'
assert_contains "the tag field has a picker button" 'btn=true'          "$PROBE"
assert_contains "  level with the field's top"      'alignTop=true'     "$PROBE"
assert_contains "  and its bottom"                  'alignBottom=true'  "$PROBE"
assert_contains "  beside it, not below it"         'beside=true'       "$PROBE"
assert_contains "  80% of the window wide"          'wRatio=0.80'       "$PROBE"
assert_contains "  and 80% high"                    'hRatio=0.80'       "$PROBE"
assert_contains "headings are shown"                'headings=Department,Status' "$PROBE"
# Aardvark is first in the file; the picker, like the editor, lists folders first.
assert_contains "  without a checkbox — only terms can be ticked, folders listed first" \
                'boxes=Department/Finance,Department/HR,Status/Draft,Status/Final,Aardvark ' "$PROBE"
assert_contains "a description is shown"            'desc=Money matters' "$PROBE"

section 'filtering'
assert_contains "a filter keeps the match"          'filtered=Department/Finance ' "$PROBE"
assert_contains "  and its heading, nothing else"   'filteredHeadings=Department ' "$PROBE"
assert_contains "Enter ticks the only match"        'count=1 selected'  "$PROBE"
assert_contains "a new tag is offered in free mode" 'addOffered=true'   "$PROBE"
assert_contains "  normalised, and ticked"          'extras=Project/Apollo:true' "$PROBE"

section 'apply'
assert_contains "Apply closes the picker"           'closed=true'       "$PROBE"
assert_contains "  and tags the page"               'tags=["Department/Finance","Project/Apollo"]' "$PROBE"
assert_contains "  which the page shows"            'shown=Department/Finance,Project/Apollo' "$PROBE"
assert_contains "the new tag joined the tree"       'grew=true'         "$PROBE"

section 'type-ahead'
assert_contains "matches any part of a term's path" 'suggest=Status/Draft' "$PROBE"
assert_contains "  offers terms, never the heading, never a tag already on" \
                'suggestDept=Department/HR ' "$PROBE"

section 'controlled mode'
assert_contains "the picker stops offering new tags" 'addInControlled=false' "$PROBE"
assert_contains "a typed non-term is refused"        'refused=true'      "$PROBE"
assert_contains "  and the user is told why"         'toast=true'        "$PROBE"

section 'Admin → Content → Taxonomy'
assert_contains "lists every term"                   'adminRows=9'       "$PROBE"
assert_contains "  shows the mode"                   'adminMode=controlled' "$PROBE"
# Department and Status, plus Project — created as a folder when "Project/Apollo" was typed.
assert_contains "  and marks the folders"           'adminFolders=3'    "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
