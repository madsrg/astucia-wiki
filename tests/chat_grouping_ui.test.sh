# Which chat messages get their own header (avatar, name and time).
#
# Consecutive messages from one author are drawn as a run under the first one's header.
# Author alone used to decide that, so a message posted weeks after the same author's last
# one — a workflow's AI reply landing in a quiet page chat — sat under the old header and
# read as written on the old date. A run now also ends after a five-minute gap, and a
# message whose time cannot be read always starts a new one.
#
# Both presentations of a thread draw their own rows — the thread as a page
# (modules/chat) and as the panel beside its page (modules/page_chat) — so the same thread
# is checked in each. The rule is one helper, continuesChatRun() in modules/core/utils.js;
# this suite is what says both views use it.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Plan.md' '# Plan'
# 1-2: Alice, two minutes apart        → one run, one header
# 3:   Bot, three minutes later         → a different author, a header
# 4:   Bot, three weeks later           → the case reported: a header of its own
# 5:   Bot, a minute after that         → continues 4
# 6:   Bot, a time that cannot be read  → never continues a run
fixture_page 'Main/Plan.chat' '{"topic":"","nextMessageId":7,"messages":[
 {"id":1,"uid":1,"name":"Alice","timestamp":"2026-10-05T10:00:00+00:00","text":"first"},
 {"id":2,"uid":1,"name":"Alice","timestamp":"2026-10-05T10:02:00+00:00","text":"second"},
 {"id":3,"uid":7,"name":"Bot","timestamp":"2026-10-05T10:05:00+00:00","text":"old reply"},
 {"id":4,"uid":7,"name":"Bot","timestamp":"2026-10-28T11:16:00+00:00","text":"workflow reply","workflow":true},
 {"id":5,"uid":7,"name":"Bot","timestamp":"2026-10-28T11:17:00+00:00","text":"follow-up"},
 {"id":6,"uid":7,"name":"Bot","timestamp":"not a date","text":"undated"}]}'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
page_id() { python3 -c 'import json,sys
print(next(k for k,v in json.load(open(sys.argv[1])).items() if v.get("path")==sys.argv[2]))' "$WIKI_PAGES/Main/index.json" "$1"; }

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/chat_grouping_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
// The ids of the rows in a container that carry a header of their own.
const headed = (sel) => Array.from(document.querySelectorAll(sel + ' [data-id]'))
  .filter(r => r.querySelector('.chat-meta')).map(r => r.dataset.id).join(',');
const rows = (sel) => document.querySelectorAll(sel + ' [data-id]').length;

window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection',
    e => { document.title = 'PROBE fatal=' + (e.reason && e.reason.message || e.reason); });

setTimeout(async () => {
  try {
    let out = '';
    if (new URLSearchParams(location.search).get('probe') === 'panel') {
      document.getElementById('page-chat-btn')?.click();
      await sleep(1500);
      out += ' rows=' + rows('#pc-messages') + ' headed=' + headed('#pc-messages');
    } else {
      out += ' rows=' + rows('#chat-messages') + ' headed=' + headed('#chat-messages');
    }
    document.title = 'PROBE' + out;
  } catch (e) {
    document.title = 'PROBE fatal=' + (e && e.message || e);
  }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

load() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=30000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main&probe=$2" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "$1 / $2"
}

for view in thread panel; do
    if [ "$view" = thread ]; then
        section 'the thread opened as a page'; load Plan.chat thread
    else
        section 'the same thread in the panel beside its page'; load Plan.md panel
    fi
    assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"
    assert_contains "all six messages are drawn (control)" 'rows=6' "$PROBE"
    # 1, 3, 4 and 6 start a run; 2 and 5 continue one.
    assert_contains "a run is cut by time, not only by author" 'headed=1,3,4,6' "$PROBE"
done

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
