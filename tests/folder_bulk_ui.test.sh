# Selecting several pages in the main-area folder listing, and moving, deleting or tagging
# them together (modules/files_folder/bulk.js), in the browser.
#
# Every page row has a checkbox; folders do not. The box selects, the row still opens the
# page. The actions are the single-page requests run one at a time, so a page the server
# refuses (here a generated page, which may not be deleted) must be reported and stay
# selected while the rest go through. A move asks about [[wikilinks]] once for the batch.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Main'
for n in Alpha Bravo Charlie Delta Echo Foxtrot; do fixture_page "Main/Docs/$n.md" "# $n"; done
fixture_page 'Main/Docs/Sub/Inner.md' '# Inner'
fixture_page 'Main/Target/Keep.md' '# Keep'
# A generated page: the server refuses to delete it (generated_by names a template).
printf -- '---\ngenerated_by: 999\ngenerated_row: 1\n---\n# Locked\n' > "$WIKI_PAGES/Main/Docs/Locked.md"
fixture_page 'Main/Linker.md' 'See [[Docs/Alpha]] and [[Docs/Bravo]] and [[Docs/Charlie]].'
mkdir -p "$WIKI_PAGES/Main/Big"
for i in $(seq 1 105); do printf '# N %s\n' "$i" > "$WIKI_PAGES/Main/Big/N $i.md"; done
curl -s "$WIKI_URL/api.php?action=list&space=Main" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/folder_bulk_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
import { loadFolderView } from './modules/files_folder/index.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
const boxes = () => $$('#ff-file-list .ff-bulk-check');
const box = (p) => $('#ff-file-list .ff-bulk-check[data-path="' + p + '"]');
const checked = () => boxes().filter(b => b.checked).map(b => b.dataset.path.split('/').pop().replace('.md', '')).join(',');
const count = () => $('#ff-bulk .ff-bulk-count').textContent;
const hidden = (el) => !el || el.classList.contains('hidden') || el.closest('.hidden') !== null;
const click = (el, shift) => el.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, shiftKey: !!shift }));
const modalUp = (id) => !$('#' + id).classList.contains('hidden');
const waitFor = async (fn, ms = 8000) => { for (let i = 0; i < ms / 100; i++) { if (fn()) return true; await sleep(100); } return false; };

setTimeout(async () => {
  let out = ' start=' + state.currentSpace;
  try {
    await loadFolderView('Docs');                             await sleep(800);
    out += ' bar=' + (hidden($('#ff-bulk')) ? 'hidden' : 'shown')
        + ' boxes=' + boxes().length
        + ' subBox=' + !!box('Docs/Sub')
        + ' actionsIdle=' + (hidden($('#ff-bulk .ff-bulk-actions')) ? 'hidden' : 'shown');

    // A box selects, and does not open the page.
    click(box('Docs/Alpha.md'));                              await sleep(200);
    out += ' afterBox=' + state.currentPagePath + ' sel1=[' + checked() + '] count1=[' + count() + ']'
        + ' actions=' + (hidden($('#ff-bulk .ff-bulk-actions')) ? 'hidden' : 'shown');
    // Shift extends a range, in the order shown.
    click(box('Docs/Charlie.md'), true);                      await sleep(200);
    out += ' range=[' + checked() + '] indet=' + $('#ff-bulk .ff-bulk-page').indeterminate;
    // Everything on the page, then nothing.
    click($('#ff-bulk .ff-bulk-page'));                       await sleep(200);
    out += ' all=' + boxes().filter(b => b.checked).length + ' count2=[' + count() + ']'
        + ' offerSmall=' + (hidden($('#ff-bulk .ff-bulk-everything')) ? 'hidden' : 'shown');
    click($('#ff-bulk .ff-bulk-clear'));                      await sleep(200);
    out += ' cleared=[' + checked() + '] count3=[' + count() + ']';

    // Add tag to two pages.
    click(box('Docs/Alpha.md')); click(box('Docs/Bravo.md')); await sleep(200);
    click($('#ff-bulk .ff-bulk-tag'));
    await waitFor(() => modalUp('input-modal'));
    out += ' tagPrompt=[' + $('#input-modal-title').textContent + ']';
    $('#input-modal-input').value = 'bulk-tag';
    click($('#input-modal-ok'));
    await waitFor(() => !boxes().some(b => b.checked));        await sleep(500);
    out += ' afterTag=[' + checked() + ']';

    // Delete two, one of which the server refuses.
    click(box('Docs/Echo.md')); click(box('Docs/Locked.md')); await sleep(200);
    click($('#ff-bulk .ff-bulk-delete'));
    await waitFor(() => modalUp('confirm-modal'));
    out += ' delTitle=[' + $('#confirm-modal-title').textContent + ']'
        + ' delNames=[' + $$('#confirm-modal-message li').map(li => li.textContent).join(',') + ']';
    click($('#confirm-modal-ok'));                            await sleep(300);
    await waitFor(() => modalUp('confirm-modal'));
    out += ' failTitle=[' + $('#confirm-modal-title').textContent + ']'
        + ' failMsg=[' + $('#confirm-modal-message p').textContent + ']'
        + ' failRows=[' + $$('#confirm-modal-message li strong').map(e => e.textContent).join(',') + ']'
        + ' failCancel=' + ($('#confirm-modal-cancel').classList.contains('hidden') ? 'hidden' : 'shown');
    click($('#confirm-modal-ok'));                            await sleep(500);
    out += ' afterDel=[' + checked() + '] echoRow=' + !!box('Docs/Echo.md');
    click($('#ff-bulk .ff-bulk-clear'));                      await sleep(200);

    // Move three into Target, through the Move dialog; one wikilink question for all.
    ['Alpha', 'Bravo', 'Delta'].forEach(n => click(box('Docs/' + n + '.md'))); await sleep(200);
    click($('#ff-bulk .ff-bulk-move'));
    await waitFor(() => !$('#move-lightbox').classList.contains('hidden') && $('#move-file-tree .file-item-content[data-path="Target"]'));
    click($('#move-file-tree .file-item-content[data-path="Target"]'));
    click($('#move-confirm-btn'));
    await waitFor(() => modalUp('confirm-modal'), 10000);
    out += ' retargetMsg=[' + $('#confirm-modal-message').textContent + ']';
    click($('#confirm-modal-ok'));                            await sleep(1500);
    out += ' afterMove=[' + checked() + '] alphaRow=' + !!box('Docs/Alpha.md')
        + ' left=' + boxes().length;

    // The name still opens the page.
    click($('#ff-file-list .fv-row[title="Docs/Foxtrot.md"]'));  await sleep(1500);
    out += ' opened=' + state.currentPagePath;

    // A folder of more than one page: a whole page ticked offers the rest.
    await loadFolderView('Big');                              await sleep(800);
    click($('#ff-bulk .ff-bulk-page'));                       await sleep(200);
    const every = $('#ff-bulk .ff-bulk-everything');
    out += ' bigPage=[' + count() + '] offer=[' + (hidden(every) ? '' : every.textContent) + ']';
    click(every);                                             await sleep(200);
    out += ' bigAll=[' + count() + '] offerDone=[' + every.textContent + '] offerDisabled=' + every.disabled;

    // Somewhere nothing could be changed: no boxes, no bar.
    state.spaceReadOnly = true;
    await loadFolderView('Docs');                             await sleep(800);
    out += ' roBoxes=' + boxes().length + ' roBar=' + (hidden($('#ff-bulk')) ? 'hidden' : 'shown')
        + ' roRows=' + $$('#ff-file-list .fv-row').length;
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=90000 \
    --dump-dom "$WIKI_URL/index.php?space=Main" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "${FOLDER_BULK_DEBUG:-}" ] && echo "$PROBE" >&2
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

tags_of() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(json.dumps(next((v.get("tags", []) for v in ix.values() if v.get("path") == sys.argv[2]), None)))' \
        "$WIKI_PAGES/Main/index.json" "$1"
}

section 'the boxes'
assert_contains "a wiki folder's listing has the bar"       'bar=shown'          "$PROBE"
assert_contains "  a box on each page row, none on the subfolder" 'boxes=7 subBox=false' "$PROBE"
assert_contains "  and no actions until something is selected" 'actionsIdle=hidden' "$PROBE"
assert_contains "a box selects without opening the page"    'afterBox=Docs sel1=[Alpha] count1=[1 selected]' "$PROBE"
assert_contains "  and brings the actions"                  'actions=shown'      "$PROBE"
assert_contains "Shift extends a range"                     'range=[Alpha,Bravo,Charlie] indet=true' "$PROBE"
assert_contains "select-all takes the page"                 'all=7 count2=[7 selected]' "$PROBE"
assert_contains "  and offers no more when the page is the folder" 'offerSmall=hidden' "$PROBE"
assert_contains "Clear selection empties it"                'cleared=[] count3=[]' "$PROBE"

section 'Add tag'
assert_contains "asks once, naming how many"                'tagPrompt=[Tag to add to 2 pages]' "$PROBE"
assert_contains "  and the tagged pages leave the selection" 'afterTag=[]'       "$PROBE"
# (the tags themselves are read below, after the move has taken Alpha and Bravo to Target)


section 'Delete'
assert_contains "asks first, naming the pages"              'delTitle=[Delete 2 pages?] delNames=[Echo,Locked]' "$PROBE"
assert_contains "a refusal is reported"                     'failTitle=[Not everything was done]' "$PROBE"
assert_contains "  with what was done"                      'failMsg=[1 done. These 1 were not, and are still selected:]' "$PROBE"
assert_contains "  naming the page refused"                 'failRows=[Locked]' "$PROBE"
assert_contains "  as a notice, not a question"             'failCancel=hidden' "$PROBE"
assert_contains "the refused page stays selected, the deleted one is gone" 'afterDel=[Locked] echoRow=false' "$PROBE"
[ -f "$WIKI_PAGES/Main/Docs/Echo.md" ]   && _fail "Echo was deleted on disk" "it is still there" || _pass "Echo was deleted on disk"
[ -f "$WIKI_PAGES/Main/Docs/Locked.md" ] && _pass "the generated page was not" || _fail "the generated page was not" "it is gone"

section 'Move'
assert_contains "one wikilink question for the batch"      'retargetMsg=[2 wikilinks on 1 pages still name the 2 moved pages by their old names. Update them?]' "$PROBE"
assert_contains "the moved pages leave the selection and the listing" 'afterMove=[] alphaRow=false left=3' "$PROBE"
for n in Alpha Bravo Delta; do
    [ -f "$WIKI_PAGES/Main/Target/$n.md" ] && _pass "$n is in Target" || _fail "$n is in Target" "missing"
done
assert_eq "Alpha has the tag (and kept it through the move)" '["bulk-tag"]' "$(tags_of 'Target/Alpha.md')"
assert_eq "Bravo has the tag"                         '["bulk-tag"]' "$(tags_of 'Target/Bravo.md')"
assert_eq "Charlie (not selected) has none"           '[]' "$(tags_of 'Docs/Charlie.md')"
assert_eq "the links follow the moved pages, the other one is untouched" \
    'See [[Target/Alpha]] and [[Target/Bravo]] and [[Docs/Charlie]].' "$(cat "$WIKI_PAGES/Main/Linker.md")"

section 'the rest'
assert_contains "a row still opens its page"                'opened=Docs/Foxtrot.md' "$PROBE"
assert_contains "a full page in a larger folder offers the rest" 'bigPage=[100 selected] offer=[Select all 105 in this folder]' "$PROBE"
assert_contains "  which takes them all"                    'bigAll=[105 selected] offerDone=[All 105 in this folder are selected] offerDisabled=true' "$PROBE"
assert_contains "a read-only Space lists without boxes or bar" 'roBoxes=0 roBar=hidden roRows=' "$PROBE"
assert_not_contains "  (and still lists)"                   'roRows=0 ' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
