# Page generators in a browser (modules/generators).
#
# The HTTP suites prove what the server does; this proves a person can see and use it:
# a generated page says where it comes from and has no edit button, and the edit route
# that bypasses the button (the button's own handler, as Ctrl+E uses it) is refused too;
# the template link opens the template, whose banner reports the last render; Preview
# renders a row with data shown as text; Re-render reports what it did; Detach makes the
# page editable; and New → Generated pages writes a template and opens it.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space CRM; fixture_space Customers
fixture_page 'Customers/Main.md' '# Customers'
cat > "$WIKI_PAGES/CRM/Accounts.list" <<'JSON'
{"columns":[{"id":"col_2","name":"Name","type":"text_single","role":"title"},
            {"id":"col_3","name":"Notes","type":"text_single"}],
 "items":[{"id":1,"col_2":"Acme","col_3":"<b>bold?</b>"},{"id":2,"col_2":"Beta","col_3":"plain"}],"nextItemId":3}
JSON
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
for s in CRM Customers; do curl -s "$WIKI_URL/api.php?action=indexfiles&space=$s" > /dev/null; done
id_of() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next((k for k, v in ix.items() if v.get("path") == sys.argv[2]), ""))' "$WIKI_PAGES/$1/index.json" "$2"
}
ACCOUNTS=$(id_of CRM Accounts.list)
mkdir -p "$WIKI_PAGES/Customers/Templates"
printf -- "---\ngenerator_source: CRM:%s\ngenerator_folder: Accounts\n---\n# {{name}}\n\nNotes: {{notes}}\n" "$ACCOUNTS" \
    > "$WIKI_PAGES/Customers/Templates/Account.md"
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Customers" > /dev/null
TPL=$(id_of Customers Templates/Account.md)
curl -s -X POST -d "id=$TPL" "$WIKI_URL/api.php?action=generator_render&space=Customers" > /dev/null
ACME=$(id_of Customers Accounts/Acme.md)
[ -n "$ACME" ] || { _fail "setup: the generator did not render" ""; exit 1; }

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/page_generators_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const shown = (el) => !!el && !el.classList.contains('hidden') && getComputedStyle(el).display !== 'none';
const w = (s) => String(s).trim().replace(/ +/g, '_');

window.addEventListener('error', e => report(out + ' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(out + ' fatal=' + (e.reason && e.reason.message || e.reason)));

const banner = () => $('#generator-banner');
const toast = () => ($('#toast') || {}).textContent || '';

// Kept outside run(): a control that is missing throws, and what was already collected must
// still be reported, so a regression shows as the assertions it breaks rather than all.
let out = '';
const run = async () => {
  // The start URL opened the generated page Acme.
  // The header is folded away; the page-header icon says the page is generated and opens it.
  const gbadge = () => $('#generator-badge');
  out += ' genStart=' + (shown(banner()) ? 'shown' : 'hidden');
  out += ' badge=' + (shown(gbadge()) ? (gbadge().classList.contains('is-muted') ? 'grey' : 'colour') : 'none');
  click(gbadge());                                  await sleep(200);
  out += ' gen=' + (shown(banner()) ? banner().className.replace(/ /g, '.') : 'none');
  // Lined up with the page text: the content's own left edge plus its padding.
  const vc = $('#viewer-content');
  const textLeft = vc.getBoundingClientRect().left + parseFloat(getComputedStyle(vc).paddingLeft);
  out += ' aligned=' + (Math.abs(banner().getBoundingClientRect().left - textLeft) < 1.5 ? 'yes' : 'no');
  click(gbadge());                                  await sleep(200);
  out += ' closes=' + (shown(banner()) ? 'no' : 'yes');
  click(gbadge());                                  await sleep(200);
  // The tree draws a template with the generator icon, and a generated page as a page.
  const treeIcon = (path) => ($('.file-item-content[data-path="' + path + '"]') || document).querySelector('svg path[d="M15 2v5h5"]') ? 'generator' : 'other';
  out += ' treeTpl=' + treeIcon('Templates/Account.md') + ' treePage=' + treeIcon('Accounts/Acme.md');
  out += ' link=' + w(($('#generator-banner .generator-link') || {}).textContent || '');
  out += ' editbtn=' + (shown($('#edit-btn')) ? 'shown' : 'hidden');
  out += ' modebtn=' + (shown($('#editor-mode-group')) ? 'shown' : 'hidden');
  $('#edit-btn').click();                        await sleep(400);
  out += ' editing=' + (shown($('#save-btn')) ? 'yes' : 'no');
  out += ' locked=' + (toast().includes('generated from a template') ? 'said' : 'silent');
  if (shown($('#cancel-btn'))) { $('#cancel-btn').click(); await sleep(300); }

  click($('#generator-banner .generator-link')); await sleep(1500);
  out += ' tplpage=' + w($('#current-page-title').textContent);
  out += ' tplBadge=' + (shown(gbadge()) ? 'shown' : 'none');
  out += ' tpl=' + (shown(banner()) ? banner().className.replace(/ /g, '.') : 'none');
  out += ' status=' + ($('#generator-banner .generator-status.ok') ? 'ok' : 'other');
  out += ' reads=' + w(($('#generator-banner .generator-link') || {}).textContent || '');

  click($('#generator-banner [data-gen=preview]'));  await sleep(1200);
  const dlg = $('.generator-dialog');
  out += ' preview=' + (dlg ? 'open' : 'none');
  const sel = dlg.querySelector('[data-gen-row]');
  out += ' rows=' + sel.options.length;
  const pv = dlg.querySelector('.generator-preview');
  out += ' h1=' + w((pv.querySelector('h1') || {}).textContent || '');
  out += ' asText=' + (pv.querySelector('b') === null && pv.textContent.includes('<b>bold?</b>') ? 'yes' : 'no');
  sel.value = '2'; sel.dispatchEvent(new Event('change')); await sleep(1000);
  out += ' row2=' + w((pv.querySelector('h1') || {}).textContent || '');
  click(dlg.querySelector('[data-gen-close]'));        await sleep(200);
  out += ' dlgclosed=' + ($('.generator-dialog') ? 'no' : 'yes');

  click($('#generator-banner [data-gen=render]'));   await sleep(1500);
  out += ' rendered=' + w(toast());

  const { loadPage } = await import('./modules/page_view/index.js');
  await loadPage('Accounts/Acme.md', window.ACME_ID, []);  await sleep(800);
  click($('#generator-banner [data-gen=detach]'));    await sleep(500);
  click($('#confirm-modal-ok'));                      await sleep(1800);
  out += ' detachedStart=' + (shown(banner()) ? 'shown' : 'hidden');
  out += ' detachedBadge=' + (gbadge().classList.contains('is-muted') ? 'grey' : 'colour');
  click(gbadge());                                    await sleep(200);
  out += ' detached=' + (shown(banner()) ? banner().className.replace(/ /g, '.') : 'none');
  out += ' editbtn2=' + (shown($('#edit-btn')) ? 'shown' : 'hidden');
  out += ' modebtn2=' + (shown($('#editor-mode-group')) ? 'shown' : 'hidden');

  click($('#new-item-btn'));                          await sleep(200);
  const item = $('#dropdown-new-generator');
  out += ' menu=' + w(item ? item.textContent : 'none');
  click(item);                                        await sleep(1200);
  const nd = $('.generator-dialog');
  out += ' sources=' + w(Array.from(nd.querySelectorAll('[data-gen-source] option')).map(o => o.textContent.split(' (')[0]).join('|'));
  out += ' defaults=' + nd.querySelector('[data-gen-path]').value + ',' + nd.querySelector('[data-gen-folder]').value;
  out += ' formatDefault=' + (nd.querySelector('[data-gen-format]:checked') || {}).value;
  nd.querySelector('[data-gen-path]').value = 'Templates/Fresh';
  nd.querySelector('[data-gen-folder]').value = 'Fresh';
  click(nd.querySelector('[data-gen-ok]'));           await sleep(3000);
  out += ' newpage=' + w($('#current-page-title').textContent);
  out += ' newtpl=' + (shown(banner()) ? banner().className.replace(/ /g, '.') : 'none');
  // The HTML starter, shown as HTML and styled by the wk-* classes.
  const card = $('#viewer-content .wk-card');
  out += ' starterCard=' + (card ? 'yes' : 'no');
  out += ' cardStyled=' + (card && parseFloat(getComputedStyle(card).borderTopWidth) > 0 ? 'yes' : 'no');
  const fl = $('#viewer-content .wk-fields');
  out += ' fieldsGrid=' + (fl && getComputedStyle(fl).display === 'grid' ? 'yes' : 'no');

  click($('#admin-btn'));                                       await sleep(800);
  click($('.admin-group[data-group="content"]'));               await sleep(500);
  const tabText = (n) => w($('.admin-tab[data-tab="' + n + '"]').textContent);
  out += ' tabs=' + ['reindex', 'deleted', 'retention', 'metadata', 'generators'].map(tabText).join('|');
  click($('.admin-tab[data-tab="generators"]'));                await sleep(1500);
  const genRows = $$('#admin-generators-list tbody tr');
  out += ' genrows=' + genRows.length;
  out += ' gennames=' + genRows.map(r => w(r.querySelector('.admin-td-name').firstChild.textContent)).join('|');
  out += ' genstatus=' + w(genRows[0].querySelector('.admin-job-status').textContent);
  click(genRows[0].querySelector('.gen-open'));                 await sleep(1800);
  out += ' adminclosed=' + (shown($('#admin-lightbox')) ? 'no' : 'yes');
  out += ' opened=' + w($('#current-page-title').textContent);
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(out + ' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY
# The probe needs Acme's id to reopen it after visiting the template.
python3 - "$WIKI_APP/index.php" "$ACME" <<'PY'
import io, sys
p = sys.argv[1]; s = io.open(p, encoding='utf-8', newline='').read()
s = s.replace('<script type="module">', '<script>window.ACME_ID = ' + str(int(sys.argv[2])) + ';</script><script type="module">', 1)
io.open(p, 'w', encoding='utf-8', newline='').write(s)
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php?space=Customers&pageid=$ACME" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE.*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'a generated page'
assert_contains "its header starts folded away"            'genStart=hidden '                "$PROBE"
assert_contains "  a coloured icon in the page header says it is generated" 'badge=colour '  "$PROBE"
assert_contains "the icon opens the header"                 'gen=generator-banner.is-generated' "$PROBE"
assert_contains "  lined up with the page text"             'aligned=yes '                     "$PROBE"
assert_contains "  and closes it again"                     'closes=yes '                      "$PROBE"
assert_contains "the tree draws a template with the generator icon" 'treeTpl=generator ' "$PROBE"
assert_contains "  and a generated page as a page"          'treePage=other'                   "$PROBE"
assert_contains "  …naming its template"                    'link=Templates/Account '         "$PROBE"
assert_contains "it has no edit button"                     'editbtn=hidden'                   "$PROBE"
assert_contains "  …nor the inline/classic editor switch"    'modebtn=hidden'                   "$PROBE"
assert_contains "the button's own handler does not edit it" 'editing=no'                       "$PROBE"
assert_contains "  …and says why"                           'locked=said'                      "$PROBE"

section 'its template'
assert_contains "the link opens the template"               'tplpage=Account '                 "$PROBE"
assert_contains "  …whose banner is the template's, open from the start" 'tpl=generator-banner.is-template' "$PROBE"
assert_contains "  …and which has the icon too"             'tplBadge=shown '                  "$PROBE"
assert_contains "  …reporting the last render"              'status=ok'                        "$PROBE"
assert_contains "  …and naming its list"                    'reads=CRM_/_Accounts '            "$PROBE"

section 'preview'
assert_contains "Preview opens a dialog"                    'preview=open'                     "$PROBE"
assert_contains "  …offering every row"                     'rows=2'                           "$PROBE"
assert_contains "  …rendering the first"                    'h1=Acme '                         "$PROBE"
assert_contains "  …with data shown as text, not HTML"      'asText=yes'                       "$PROBE"
assert_contains "  …and another row on request"             'row2=Beta '                       "$PROBE"
assert_contains "  …and it closes"                          'dlgclosed=yes'                    "$PROBE"
assert_contains "Re-render says what it did"                'rendered=Rendered:_nothing_changed.' "$PROBE"

section 'detach'
assert_contains "a detached page's header starts folded too" 'detachedStart=hidden '         "$PROBE"
assert_contains "  its icon grey"                           'detachedBadge=grey '              "$PROBE"
assert_contains "  and opens on 'detached'"                 'detached=generator-banner.is-detached' "$PROBE"
assert_contains "  …and the page is editable again"         'editbtn2=shown'                   "$PROBE"
assert_contains "  …with its editor switch back"             'modebtn2=shown'                   "$PROBE"

section 'New → Generated pages'
assert_contains "the New menu offers it"                    'menu=Generated_Pages…'            "$PROBE"
assert_contains "  …listing the lists of every Space"       'sources=CRM_/_Accounts '          "$PROBE"
assert_contains "  …with defaults from the chosen list"     'defaults=templates/Accounts,Accounts' "$PROBE"
assert_contains "  …offering HTML by default"               'formatDefault=html '              "$PROBE"
assert_contains "creating it opens the new template"        'newpage=Fresh '                   "$PROBE"
assert_contains "  …an HTML starter, shown as HTML"          'starterCard=yes '                 "$PROBE"
assert_contains "  …styled as a card"                        'cardStyled=yes '                  "$PROBE"
assert_contains "  …its fields as label/value rows"          'fieldsGrid=yes'                   "$PROBE"
assert_contains "  …and its pages are HTML"                  'format: html'                     "$(cat "$WIKI_PAGES/Customers/Fresh/Acme.md" 2>/dev/null)"
assert_contains "  …as a template"                          'newtpl=generator-banner.is-template' "$PROBE"
assert_file_exists "  …which rendered its pages"            "$WIKI_PAGES/Customers/Fresh/Acme.md"

section 'Admin → Content → Generators'
assert_contains "the Content toolbar's shorter labels"     'tabs=Index|Deleted|Retention|Metadata|Generators ' "$PROBE"
assert_contains "the tab lists every generator"             'genrows=2'                       "$PROBE"
assert_contains "  …by template, sorted"                    'gennames=Templates/Account|Templates/Fresh ' "$PROBE"
assert_contains "  …with its status"                        'genstatus=Running '              "$PROBE"
assert_contains "Open closes the admin panel"               'adminclosed=yes'                 "$PROBE"
assert_contains "  …and opens the template"                 'opened=Account'                  "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
