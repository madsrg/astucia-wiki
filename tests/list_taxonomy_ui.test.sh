# A Choice from a taxonomy folder, in a browser: the item form's dropdown (the folder's items
# under their subfolders' headings, indented; a value no longer in the folder kept and marked;
# several values as a multi-select, saved as a list), the table, a view filter naming a
# subfolder, and List properties — choosing the source and the folder, "Allow several values",
# a folder required, and switching several off refused while items hold more than one.
# tests/list_taxonomy.test.sh holds the server's rules.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
for args in 'op=add&name=Department&heading=1' 'op=add&parent=Department&name=Finance&heading=1' \
            'op=add&parent=Department/Finance&name=Budget' 'op=add&parent=Department/Finance&name=Payroll' \
            'op=add&parent=Department&name=Sales' 'op=add&name=Region&heading=1' 'op=add&parent=Region&name=Nordic'; do
    curl -s -X POST --data "$args" "$WIKI_URL/api.php?action=admin_taxonomy_node" > /dev/null
done
cat > "$WIKI_PAGES/Main/Staff.list" <<'JSON'
{"columns":[{"id":"col_1","name":"ItemId","type":"autoincrement"},
  {"id":"col_2","name":"Name","type":"text_single","role":"title"},
  {"id":"col_3","name":"Dept","type":"choice","taxonomy":"Department"},
  {"id":"col_4","name":"Areas","type":"choice","taxonomy":"Department","multiple":true},
  {"id":"col_5","name":"Post","type":"object","fields":[{"id":"sf_w","name":"Where","type":"choice","taxonomy":"Department","multiple":true}]}],
 "items":[{"id":1,"col_1":1,"col_2":"Ann","col_3":"Sales"},
          {"id":2,"col_1":2,"col_2":"Bo","col_3":"Gone","col_4":["Budget","Sales"]}],
 "nextItemId":3}
JSON
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
LID=$(python3 -c 'import json,sys; ix=json.load(open(sys.argv[1])); print(next(k for k,v in ix.items() if v["path"]=="Staff.list"))' "$WIKI_PAGES/Main/index.json")

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/list_taxonomy_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes and no percent signs in here.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const report = (out) => { document.title = 'PROBE' + out; };
const w = (s) => String(s).trim().replace(/ +/g, '_');
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const shown = (el) => !!el && !el.classList.contains('hidden') && getComputedStyle(el).display !== 'none';
const waitFor = async (fn, ms = 8000) => { for (let i = 0; i < ms / 100; i++) { if (fn()) return true; await sleep(100); } return false; };
const getList = async () => JSON.parse((await (await fetch('api.php?action=get&space=Main&file=Staff.list')).json()).data);
let out = '';
window.addEventListener('error', e => report(out + ' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(out + ' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  await waitFor(() => $$('#list-items-table tbody tr').length > 0);
  const m = await import('./modules/list/modals.js');

  // ── The item form ──
  await m.openItemModal(1);                                  await sleep(500);
  const dept = $('#field-col_3');
  out += ' dd=' + (dept.dataset.dd ? 'yes' : 'no') + ' val=' + dept.value;
  out += ' heads=' + dept.querySelectorAll('option:disabled').length + ':' + Array.from(dept.options).filter(o => o.disabled).map(o => o.textContent + '@' + (o.dataset.depth || 0)).join('|');
  out += ' items=' + Array.from(dept.options).filter(o => !o.disabled && o.value).map(o => o.value + '@' + (o.dataset.depth || 0)).join('|');
  click(dept.closest('.dd').querySelector('.dd-btn'));       await sleep(150);
  out += ' menu=' + $$('.dd-menu .dd-heading').length + ',' + $$('.dd-menu .dd-item').length;
  // A heading is not a value: clicking it chooses nothing.
  $$('.dd-menu .dd-heading')[0].dispatchEvent(new MouseEvent('click', { bubbles: true }));
  await sleep(100);
  out += ' afterHead=' + dept.value;
  click($$('.dd-menu .dd-item').find(i => i.dataset.value === 'Payroll'));  await sleep(100);
  out += ' picked=' + dept.value;
  const areas = $('#field-col_4');
  out += ' multi=' + areas.multiple;
  Array.from(areas.options).forEach(o => { o.selected = ['Budget', 'Nordic', 'Sales'].includes(o.value); });
  // A group's sub-field from the taxonomy, several values.
  const sub = $('.group-editor[data-col-id="col_5"] select[data-sub-id="sf_w"]');
  out += ' sub=' + (sub ? (sub.multiple ? 'multi' : 'single') + ',' + (sub.dataset.dd ? 'dd' : 'plain') : 'none');
  if (sub) Array.from(sub.options).forEach(o => { o.selected = ['Payroll', 'Sales'].includes(o.value); });
  click($('#item-modal-save-btn'));
  await waitFor(() => !shown($('#item-modal')));             await sleep(600);
  let d = await getList();
  out += ' saved=' + JSON.stringify(d.items[0].col_3) + JSON.stringify(d.items[0].col_4);
  out += ' subSaved=' + JSON.stringify(d.items[0].col_5);
  const areasIx = $$('#list-items-table th').findIndex(th => th.textContent === 'Areas');
  out += ' cell=' + w($$('#list-items-table tbody tr')[0].children[areasIx].textContent);

  // A value no longer in the folder is kept, marked.
  await m.openItemModal(2);                                  await sleep(500);
  const note = Array.from($('#field-col_3').options).find(o => o.dataset.note);
  out += ' note=' + w(note ? note.textContent : 'none') + ',' + $('#field-col_3').value;
  click($('#item-modal-cancel-btn'));                        await sleep(200);

  // ── A view filter: a subfolder stands for its items ──
  const f = await import('./modules/list/fields.js');
  const col = d.columns.find(c => c.id === 'col_3');
  out += ' filter=' + ['Finance', 'Sales', 'Pay', 'Department'].map(v => f.filterMatches(col, d.items[0], v, d.columns) ? 1 : 0).join('');

  // ── List properties ──
  click($('#list-props-btn'));                               await sleep(800);
  click($('#list-props-add-btn'));                           await sleep(200);
  const row = $$('#list-props-columns .list-props-row').pop();
  const name = row.querySelector('.list-props-name-input');
  name.value = 'Region'; name.dispatchEvent(new Event('input'));
  const type = row.querySelector('.list-props-type-select');
  type.value = 'choice'; type.dispatchEvent(new Event('change'));   await sleep(100);
  click(row.querySelector('.list-props-choice-src-taxonomy'));
  await waitFor(() => row.querySelectorAll('.list-props-choice-folder option').length > 1);
  const fsel = row.querySelector('.list-props-choice-folder');
  out += ' folders=' + Array.from(fsel.options).filter(o => o.value).map(o => o.value + '@' + (o.dataset.depth || 0)).join('|');
  // Saved without a folder: refused, by name.
  click($('#list-props-save-btn'));                          await sleep(300);
  out += ' needFolder=' + w($('#toast-message').textContent);
  fsel.value = 'Region'; fsel.dispatchEvent(new Event('change'));
  click(row.querySelector('.list-props-choice-multiple'));
  click($('#list-props-save-btn'));                          await sleep(1500);
  d = await getList();
  const nc = d.columns.find(c => c.name === 'Region');
  out += ' newcol=' + (nc ? [nc.type, nc.taxonomy, nc.multiple, 'options' in nc].join(',') : 'none');

  // Several switched off while an item holds two: refused.
  click($('#list-props-btn'));                               await sleep(800);
  const arow = $('#list-props-columns .list-props-row[data-col-id="col_4"]');
  click(arow.querySelector('.list-props-header-row'));        await sleep(200);
  const box = arow.querySelector('.list-props-choice-multiple');
  out += ' multiBox=' + (box ? box.checked : 'none');
  click(box);
  click($('#list-props-save-btn'));                          await sleep(500);
  out += ' severalOff=' + w($('#toast-message').textContent);
  d = await getList();
  out += ' stillMulti=' + d.columns.find(c => c.id === 'col_4').multiple;
  report(out);
};
run();
</script>"""
s = s.replace('</body>', probe + '</body>', 1)
io.open(p, 'w', encoding='utf-8', newline='').write(s)
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php?space=Main&pageid=$LID" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "${LIST_TAX_DEBUG:-}" ] && echo "$PROBE" >&2
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'The item form'
assert_contains 'a taxonomy choice is the wiki dropdown, on its value'   ' dd=yes val=Sales ' "$PROBE"
assert_contains '  subfolders are headings, not values'                  'heads=1:Finance@0 ' "$PROBE"
assert_contains '  items at every depth, indented under them, folders first' 'items=Budget@1|Payroll@1|Sales@0 ' "$PROBE"
assert_contains '  the menu shows the heading and the items'             'menu=1,4 ' "$PROBE"
assert_contains '  clicking a heading picks nothing'                     'afterHead=Sales ' "$PROBE"
assert_contains '  an item is picked'                                    'picked=Payroll ' "$PROBE"
assert_contains 'several values: a multi-select'                         'multi=true ' "$PROBE"
assert_contains '  saved as the tree spells them, as a list'             'saved="Payroll"["Budget","Sales"] ' "$PROBE"
assert_contains "a group's sub-field: the same multi-select"           'sub=multi,dd ' "$PROBE"
assert_contains '  saved as a list in the group'                         'subSaved={"sf_w":["Payroll","Sales"]} ' "$PROBE"
assert_contains '  and the table joins them'                             'cell=Budget;_Sales ' "$PROBE"
assert_contains 'a value no longer in the folder is kept, marked'        'note=Gone_(not_in_the_taxonomy),Gone ' "$PROBE"

section 'A view filter'
assert_contains 'a subfolder matches its items; a term itself; a word is "contains"; the folder itself is text' \
    'filter=1010 ' "$PROBE"

section 'List properties'
assert_contains 'the folders are offered, indented'                      'folders=Department@0|Department/Finance@1|Region@0 ' "$PROBE"
assert_contains 'a folder is required'                                   'needFolder=Choose_a_taxonomy_folder_for_"Region".' "$PROBE"
assert_contains 'a new field from a folder, several values, no typed choices' 'newcol=choice,Region,true,false ' "$PROBE"
assert_contains '"Allow several values" shows as ticked'                 'multiBox=true ' "$PROBE"
assert_contains 'switching it off while an item holds two is refused'    'severalOff="Areas"_has_more_than_one_value_in_2_item(s).' "$PROBE"
assert_contains '  and the field keeps several'                          'stillMulti=true' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
