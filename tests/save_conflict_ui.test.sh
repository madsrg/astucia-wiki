# The save-conflict dialog, driven through the real editor.
#
# tests/save_conflict.test.sh proves the server refuses a stale save. This proves the
# editor actually sends its base — an editor that forgot to would pass every HTTP
# assertion and still overwrite people — and that each of the dialog's three answers does
# what it says: Keep editing leaves the text and writes nothing; Load their version drops
# the edit only after it is on the clipboard; Overwrite writes.
#
# The "other person" is a fetch to `save` with no base, made from inside the page after it
# loaded — exactly what an AI user's write looks like to the editor.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
# One page per answer, so a write that wrongly happens in one run cannot satisfy another.
fixture_page 'Main/Keep.md'   'start keep'
fixture_page 'Main/Theirs.md' 'start theirs'
fixture_page 'Main/Over.md'   'start over'

curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

page_id() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' \
        "$WIKI_PAGES/Main/index.json" "$1"
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/save_conflict_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes below: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const q = new URLSearchParams(location.search);
const mode = q.get('mode'), file = q.get('file');
const modal  = () => document.getElementById('save-conflict-modal');
const open   = () => !!modal() && !modal().classList.contains('hidden');
const editor = () => document.getElementById('editor-container');
const editing = () => !editor().closest('.editor-container-wrapper').classList.contains('hidden');

// The clipboard is a permission prompt in a real browser and unavailable headless; a stub
// records what the dialog put there, which is the thing under test.
window.__clip = null;
Object.defineProperty(navigator, 'clipboard', { configurable: true,
    value: { writeText: async (t) => { window.__clip = t; } } });

window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection',
    e => { document.title = 'PROBE fatal=' + (e.reason && e.reason.message || e.reason); });

const type = async (text) => {
    if (!editing()) { document.getElementById('edit-btn').click(); await sleep(600); }
    editor().value = text;
    editor().dispatchEvent(new Event('input', { bubbles: true }));
    await sleep(200);
};
const save = async () => { document.getElementById('save-btn').click(); await sleep(1500); };
// Somebody else, saving with no base: an AI user's write looks exactly like this.
const otherPerson = (text) => fetch('api.php?action=save&space=Main&file=' + encodeURIComponent(file),
    { method: 'POST', headers: { 'Content-Type': 'text/plain' }, body: text });

setTimeout(async () => {
  try {
    let out = '';
    if (mode === 'keep') {
      // Positive control: with nobody else writing, a save simply saves.
      await type('control text');
      await save();
      out += ' control=' + (open() ? 'dialog' : 'nodialog') + '/editing:' + editing();
    }
    await type('mine ' + mode);
    await otherPerson('theirs ' + mode);
    await sleep(300);
    await save();
    out += ' dialog=' + (open() ? 'open' : 'shut');
    const diff = modal() ? modal().querySelector('.save-conflict-diff').textContent : '';
    out += ' del=' + (diff.indexOf('- theirs ' + mode) >= 0) + ' add=' + (diff.indexOf('+ mine ' + mode) >= 0);
    out += ' msg=' + (modal()?.querySelector('.save-conflict-message').textContent.length > 0);

    const choice = mode === 'over' ? 'overwrite' : mode;
    modal()?.querySelector('[data-choice="' + choice + '"]').click();
    await sleep(1500);
    out += ' afterdialog=' + (open() ? 'open' : 'shut') + ' editing=' + editing();

    if (mode === 'keep') {
      out += ' editortext=' + editor().value.replace(/ /g, '_');
      // Saving again after seeing their version goes through.
      await save();
      out += ' secondsave=' + (open() ? 'dialog' : 'nodialog') + '/editing:' + editing();
    }
    if (mode === 'theirs') {
      out += ' clip=' + String(window.__clip).replace(/ /g, '_');
      out += ' shown=' + (document.getElementById('viewer-content').textContent.indexOf('theirs theirs') >= 0);
    }
    document.title = 'PROBE' + out;
  } catch (e) {
    document.title = 'PROBE fatal=' + (e && e.message || e);
  }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

# drive <file> <mode>
drive() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=30000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main&file=$1&mode=$2" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "page $1"
    assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"
}

section 'Keep editing'
drive Keep.md keep
assert_contains 'control: a save with nobody else writing shows no dialog' 'control=nodialog/editing:false' "$PROBE"
assert_contains 'a save over a newer version opens the dialog'  'dialog=open'  "$PROBE"
assert_contains "  the diff shows their line as removed"         'del=true'     "$PROBE"
assert_contains "  and mine as added"                            'add=true'     "$PROBE"
assert_contains "  with an explanation"                          'msg=true'     "$PROBE"
assert_contains 'Keep editing closes it and stays in the editor' 'afterdialog=shut editing=true' "$PROBE"
assert_contains '  with my text untouched'                       'editortext=mine_keep' "$PROBE"
assert_contains 'saving again goes through, without a dialog'    'secondsave=nodialog/editing:false' "$PROBE"
assert_eq       '  and wrote my text'                            'mine keep' "$(cat "$WIKI_PAGES/Main/Keep.md")"

section 'Load their version'
drive Theirs.md theirs
assert_contains 'the dialog opened'                              'dialog=open'  "$PROBE"
assert_contains 'loading theirs leaves the editor'               'afterdialog=shut editing=false' "$PROBE"
assert_contains '  having put my text on the clipboard first'    'clip=mine_theirs' "$PROBE"
assert_contains '  and shows their text'                         'shown=true'   "$PROBE"
assert_eq       'their text is what is on disk'                  'theirs theirs' "$(cat "$WIKI_PAGES/Main/Theirs.md")"

section 'Overwrite with mine'
drive Over.md over
assert_contains 'the dialog opened'                              'dialog=open'  "$PROBE"
assert_contains 'overwriting saves and leaves the editor'        'afterdialog=shut editing=false' "$PROBE"
assert_eq       'my text is what is on disk'                     'mine over' "$(cat "$WIKI_PAGES/Main/Over.md")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
