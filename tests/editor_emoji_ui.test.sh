# The editor toolbar's emoji picker.
#
# No HTTP surface at all: the emoji lands in a textarea, and what matters is where (at the
# caret, replacing a selection), that the caret is left after it, and that Ctrl+Z takes it
# back out — the last of which only the browser's native undo stack can show, which is why
# it is inserted with execCommand('insertText') rather than setRangeText.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
fixture_page 'Main/Notes.md' '# Notes'

curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

page_id() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' \
        "$WIKI_PAGES/${2:-Main}/index.json" "$1"
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/editor_emoji_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection', e => {
    document.title = 'PROBE fatalRejection=' + (e.reason && e.reason.message || e.reason); });

setTimeout(async () => {
  let out = '';
  try {
    $('#edit-btn').click();                        await sleep(700);
    const ta = $('#editor-container'), btn = $('#editor-emoji-btn'), picker = $('#editor-emoji-picker');
    out += ' button=' + !!btn + ' items=' + (picker ? picker.children.length : 0);
    out += ' hiddenAtRest=' + picker.classList.contains('hidden');
    // Below its button, not above it as the chat composer's opens.
    btn.click();                                   await sleep(100);
    out += ' opens=' + !picker.classList.contains('hidden')
        + ' below=' + (picker.getBoundingClientRect().top >= btn.getBoundingClientRect().bottom);
    btn.click();                                   await sleep(100);
    out += ' toggles=' + picker.classList.contains('hidden');

    const pick = async (emoji) => {
      btn.click();                                 await sleep(100);
      const item = [...picker.children].find(b => b.textContent === emoji);
      item.dispatchEvent(new MouseEvent('mousedown', { bubbles: true, cancelable: true }));
      item.click();                                await sleep(100);
    };

    // At the caret.
    ta.value = 'ab'; ta.focus(); ta.setSelectionRange(1, 1);
    await pick('🎉');
    out += ' atCaret=' + JSON.stringify(ta.value) + ' caret=' + ta.selectionStart
        + ' closed=' + picker.classList.contains('hidden')
        + ' focus=' + (document.activeElement === ta);
    // Undo removes it, which setRangeText would not have allowed.
    document.execCommand('undo');
    out += ' undo=' + JSON.stringify(ta.value);
    // Replacing a selection.
    ta.value = 'one two'; ta.focus(); ta.setSelectionRange(4, 7);
    await pick('👍');
    out += ' replaced=' + JSON.stringify(ta.value);
    // A click outside closes it.
    btn.click();                                   await sleep(100);
    document.body.click();                         await sleep(100);
    out += ' outsideCloses=' + picker.classList.contains('hidden');
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  document.title = 'PROBE' + out;
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

load() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=25000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "page $1"
}

load Notes.md
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the button and its grid'
assert_contains "the toolbar has the button"         'button=true'        "$PROBE"
assert_contains "  …with the shared 24-emoji grid"   'items=24'           "$PROBE"
assert_contains "  …hidden until asked for"          'hiddenAtRest=true'  "$PROBE"
assert_contains "it opens"                           'opens=true'         "$PROBE"
assert_contains "  …below the button"                'below=true'         "$PROBE"
assert_contains "  …and a second click closes it"    'toggles=true'       "$PROBE"
assert_contains "a click elsewhere closes it"        'outsideCloses=true' "$PROBE"

section 'inserting'
assert_contains "the emoji lands at the caret"       'atCaret="a🎉b"'     "$PROBE"
# 🎉 is two UTF-16 code units, so the caret after it is at 3.
assert_contains "  …the caret is left after it"      'caret=3'            "$PROBE"
assert_contains "  …the picker closes"               'closed=true'        "$PROBE"
assert_contains "  …and the editor keeps the focus"  'focus=true'         "$PROBE"
assert_contains "Ctrl+Z takes it back out"           'undo="ab"'          "$PROBE"
assert_contains "a selection is replaced"            'replaced="one 👍"'  "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
