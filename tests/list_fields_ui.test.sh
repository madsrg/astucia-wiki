# A list's fields, in the browser: List properties as the one place to manage them (the
# toolbar's Add column is gone), Title that can be renamed but not deleted and must be
# filled in, a Choice field, and a Lookup — picked with the type-ahead, shown as titles with
# an "also show" field, and removed with it. Also the injection fix: an item value is shown
# as text, never run as markup. tests/list_lookup.test.sh covers the server side.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Shop
fixture_page 'Shop/Main.md' '# Main'
cat > "$WIKI_PAGES/Shop/Customers.list" <<'JSON'
{"columns":[{"id":"col_1","name":"ItemId","type":"autoincrement"},
            {"id":"col_2","name":"Title","type":"text_single"},
            {"id":"col_3","name":"City","type":"text_single"}],
 "items":[{"id":1,"col_1":1,"col_2":"Acme","col_3":"Oslo"},
          {"id":2,"col_1":2,"col_2":"Beta Corp","col_3":"Bergen"}],
 "nextItemId":3}
JSON
# An old-style list: no `role` on Title — it must be recognised on load.
cat > "$WIKI_PAGES/Shop/Orders.list" <<'JSON'
{"columns":[{"id":"col_1","name":"ItemId","type":"autoincrement","showInListView":true},
            {"id":"col_2","name":"Title","type":"text_single","showInListView":true}],
 "items":[],"nextItemId":1}
JSON
curl -s "$WIKI_URL/api.php?action=list&space=Shop" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/list_fields_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
import { cellParts } from './modules/list/fields.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
const fire = (el, ev) => el.dispatchEvent(new Event(ev, { bubbles: true }));
const setVal = (el, v, ev) => { el.value = v; fire(el, ev || 'input'); };
const lastRow = () => $$('#list-props-columns .list-props-row').pop();
const cols = () => state.currentListData.columns;
const XSS = '<img src=x onerror="window.__xss=1">';

setTimeout(async () => {
  let out = '';
  try {
    $('#file-navigator [data-path="Orders.list"]').click();   await sleep(1500);
    out += ' type=' + state.currentPageType + ' addColBtn=' + !!$('#add-column-btn');

    // ── List properties: Title, and adding two fields ───────────────────────
    $('#list-props-btn').click();                              await sleep(800);
    const titleRow = $('#list-props-columns .list-props-row');
    out += ' propRows=' + $$('#list-props-columns .list-props-row').length
        + ' titleBadge=' + !!titleRow.querySelector('.list-props-title-badge')
        + ' titleDelete=' + !!titleRow.querySelector('.list-props-delete-btn');

    $('#list-props-add-btn').click();                          await sleep(200);
    let r = lastRow();
    setVal(r.querySelector('.list-props-name-input'), 'Status');
    setVal(r.querySelector('.list-props-type-select'), 'choice', 'change');  await sleep(100);
    setVal(r.querySelector('.list-props-choices'), 'Open' + String.fromCharCode(10) + 'Closed');

    $('#list-props-add-btn').click();                          await sleep(200);
    r = lastRow();
    setVal(r.querySelector('.list-props-name-input'), 'Customer');
    setVal(r.querySelector('.list-props-type-select'), 'lookup', 'change');  await sleep(200);
    const listSel = r.querySelector('.list-props-lookup-list');
    out += ' targets=' + [...listSel.options].map(o => o.textContent).join('|');
    const cust = [...listSel.options].find(o => o.textContent === 'Customers');
    setVal(listSel, cust.value, 'change');                     await sleep(1200);
    r = lastRow();
    out += ' displayField=' + r.querySelector('.list-props-lookup-field').value;
    const multi = r.querySelector('.list-props-lookup-multiple'); multi.checked = true; fire(multi, 'change');
    const city = r.querySelector('.list-props-lookup-also[value="col_3"]'); city.checked = true; fire(city, 'change');
    $('#list-props-save-btn').click();                         await sleep(1500);
    out += ' propsClosed=' + $('#list-props-modal').classList.contains('hidden')
        + ' cols=' + cols().map(c => c.name + ':' + c.type).join('|')
        + ' titleRole=' + (cols().find(c => c.id === 'col_2') || {}).role;

    // ── A nameless field is refused, and closing discards the draft ─────────
    const before = cols().length;
    $('#list-props-btn').click();                              await sleep(800);
    $('#list-props-add-btn').click();                          await sleep(200);
    $('#list-props-save-btn').click();                         await sleep(500);
    out += ' namelessOpen=' + !$('#list-props-modal').classList.contains('hidden')
        + ' namelessMarked=' + !!$('#list-props-columns .is-invalid');
    $('#list-props-modal-close-btn').click();                  await sleep(200);
    out += ' discarded=' + (cols().length === before);

    // ── An item: Title required, the lookup picker, no markup run ───────────
    $('#add-item-btn').click();                                await sleep(1200);
    $('#item-modal-save-btn').click();                         await sleep(500);
    out += ' emptyTitleRefused=' + (state.currentListData.items.length === 0 && !$('#item-modal').classList.contains('hidden'));
    const lookupCol = cols().find(c => c.type === 'lookup');
    setVal($('#field-col_2'), XSS);
    const box = $('#field-' + lookupCol.id);
    box.focus(); fire(box, 'focus');                           await sleep(100);
    setVal(box, 'bet');                                        await sleep(100);
    const hits = $$('.lookup-suggest-item').map(e => e.textContent);
    out += ' suggest=' + hits.join('|');
    $('.lookup-suggest-item').dispatchEvent(new MouseEvent('mousedown', { bubbles: true }));  await sleep(100);
    setVal(box, '');                                           await sleep(100);
    $('.lookup-suggest-item').dispatchEvent(new MouseEvent('mousedown', { bubbles: true }));  await sleep(100);
    out += ' chips=' + $$('.lookup-chip').map(c => c.firstChild.textContent).join('|');
    $('#item-modal-save-btn').click();                         await sleep(1500);
    const item = state.currentListData.items[0] || {};
    out += ' stored=' + JSON.stringify(item[lookupCol.id]);

    const headers = $$('#list-items-table th').map(th => th.textContent);
    const tds = $$('#list-items-table tbody tr:first-child td');
    const td = (name) => tds[headers.indexOf(name)];
    const pills = (name) => [...td(name).querySelectorAll('.lookup-value')];
    out += ' pillsCustomer=' + pills('Customer').map(p => p.textContent).join('|')
        + ' pillsCity=' + pills('Customer: City').map(p => p.textContent).join('|')
        + ' cityOutlined=' + td('Customer: City').querySelector('.lookup-values').classList.contains('is-projected')
        // Each looked-up item reads across: its city pill sits at the height of its name pill.
        + ' aligned=' + pills('Customer').every((p, i) =>
              Math.abs(p.getBoundingClientRect().top - pills('Customer: City')[i].getBoundingClientRect().top) < 1)
        + ' stacked=' + (pills('Customer')[1].getBoundingClientRect().top > pills('Customer')[0].getBoundingClientRect().bottom - 1)
        + ' cellTitleLiteral=' + (td('Title').textContent === XSS)
        + ' imgInTable=' + $$('#list-items-table img').length;
    // A gone target item keeps its line in an "also show" column, so the rest stay aligned.
    const lk = cols().find(c => c.type === 'lookup'), pj = cols().find(c => c.type === 'lookup_field');
    const probeItem = { [lk.id]: [2, 99, 1] };
    out += ' partsLookup=' + cellParts(lk, probeItem, cols()).map(p => (p.deleted ? '!' : '') + p.text).join('|')
        + ' partsCity=' + cellParts(pj, probeItem, cols()).map(p => p.text || '_').join('|');

    $('#list-items-table tbody tr').click();                   await sleep(1000);
    out += ' imgInView=' + $$('#item-view-modal-content img').length
        + ' viewPills=' + $$('#item-view-modal-content .lookup-value').map(e => e.textContent).join('|');
    $('#item-view-modal-close-btn').click();                   await sleep(200);

    // ── Rename Title; delete the lookup and its projection ──────────────────
    $('#list-props-btn').click();                              await sleep(800);
    setVal($('#list-props-columns .list-props-row .list-props-name-input'), 'Order');
    const custRow = $$('#list-props-columns .list-props-row').find(rw => rw.querySelector('.list-props-name-input').value === 'Customer');
    custRow.querySelector('.list-props-delete-btn').click();   await sleep(500);
    $('#confirm-modal-ok').click();                            await sleep(300);
    $('#list-props-save-btn').click();                         await sleep(1500);
    const it = state.currentListData.items[0] || {};
    out += ' after=' + cols().map(c => c.name + ':' + c.type).join('|')
        + ' valueDropped=' + !(lookupCol.id in it)
        + ' renamedRole=' + (cols().find(c => c.name === 'Order') || {}).role;
    out += ' xss=' + (window.__xss === 1);
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=90000 \
    --dump-dom "$WIKI_URL/index.php?space=Shop" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "${LIST_UI_DEBUG:-}" ] && echo "$PROBE" >&2
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"
assert_contains "the list opened"                          'type=list'           "$PROBE"

section 'fields live in List properties'
assert_contains "the toolbar's Add column is gone"         'addColBtn=false'     "$PROBE"
assert_contains "an old list shows its one field, Title"   'propRows=1 '         "$PROBE"
assert_contains "  marked as the title"                    'titleBadge=true'     "$PROBE"
assert_contains "  with no delete button"                  'titleDelete=false'   "$PROBE"
assert_contains "the lookup offers the other list, not itself" 'targets=Choose a list…|Customers ' "$PROBE"
assert_contains "  and shows its Title by default"         'displayField=col_2'  "$PROBE"
assert_contains "saving adds the fields, and the projected one after the lookup" \
                'cols=ItemId:autoincrement|Title:text_single|Status:choice|Customer:lookup|Customer: City:lookup_field' "$PROBE"
assert_contains "  and records Title's role"               'titleRole=title'     "$PROBE"
assert_contains "a nameless field is refused"              'namelessOpen=true namelessMarked=true' "$PROBE"
assert_contains "  and closing the dialog discards the draft" 'discarded=true'   "$PROBE"

section 'an item'
assert_contains "Title must be filled in"                  'emptyTitleRefused=true' "$PROBE"
assert_contains "the picker suggests by what you type"     'suggest=Beta Corp '  "$PROBE"
assert_contains "  and takes several values"               'chips=Beta Corp|Acme ' "$PROBE"
assert_contains "the file stores the item ids"             'stored=[2,1]'        "$PROBE"
assert_contains "the table shows one pill per value"       'pillsCustomer=Beta Corp|Acme ' "$PROBE"
assert_contains "  and the projected field, in the same order" 'pillsCity=Bergen|Oslo ' "$PROBE"
assert_contains "  outlined, as the item's details"        'cityOutlined=true'   "$PROBE"
assert_contains "  stacked, one value per line"            'stacked=true'        "$PROBE"
assert_contains "  so each item reads across the row"      'aligned=true'        "$PROBE"
assert_contains "a deleted target item says so"            'partsLookup=Beta Corp|!(deleted #99)|Acme ' "$PROBE"
assert_contains "  and its projection keeps the line blank" 'partsCity=Bergen|_|Oslo ' "$PROBE"
assert_contains "the item view shows the pills too"        'viewPills=Beta Corp|Acme|Bergen|Oslo ' "$PROBE"

section 'values are text, never markup'
assert_contains "the table shows the markup as text"       'cellTitleLiteral=true imgInTable=0' "$PROBE"
assert_contains "the item view builds no element from it"  'imgInView=0'         "$PROBE"
assert_contains "and nothing ran"                          'xss=false'           "$PROBE"

section 'renaming Title, deleting a lookup'
assert_contains "Title renamed keeps its role"             'renamedRole=title'   "$PROBE"
assert_contains "the lookup and its projected field are both gone" \
                'after=ItemId:autoincrement|Order:text_single|Status:choice ' "$PROBE"
assert_contains "  and so is the value it held"            'valueDropped=true'   "$PROBE"

saved=$(cat "$WIKI_PAGES/Shop/Orders.list")
assert_contains     "the file on disk has the rename"      '"name": "Order"' "$saved"
assert_not_contains "  and no lookup left"                 '"lookup"' "$saved"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
