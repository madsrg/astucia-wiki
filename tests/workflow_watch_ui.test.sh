# The workflow failure toast in a browser: a run that fails while the page is open raises a
# sticky toast, and its link opens the run's log.
#
# tests/workflow_watch.test.sh covers what the server reports; this covers that somebody
# actually sees it — the module is wired in, polls as an administrator, says nothing about
# failures from before the page loaded, and the link reaches the log. None of that has an
# HTTP surface.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Docs/a.md' 'Alpha'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

# A failure from before the page loads: history, which must not be announced.
OLD=$(curl -s -X POST "$WIKI_URL/api.php?action=admin_save_workflow" --data-urlencode \
  'workflow={"name":"Old failure","enabled":false,"space":"Main","trigger":{"types":["page_updated"]},"actions":[{"type":"chat","chat":"Gone.chat","text":"x"}]}' \
  | python3 -c 'import json,sys;print(json.load(sys.stdin)["workflow"]["id"])')
curl -s -X POST "$WIKI_URL/api.php?action=admin_run_workflow" -d "id=$OLD&test_space=Main&test_path=Docs/a.md" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/workflow_watch_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const report = (out) => { document.title = 'PROBE' + out; };
const post = async (action, body) => (await fetch('api.php?action=' + action, { method: 'POST', body: new URLSearchParams(body) })).json();

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const titles = () => Array.from(document.querySelectorAll('#toast-stack .sticky-toast-title')).map(e => e.textContent).join('|');

const run = async () => {
  let out = '';
  // The module's first poll has run by now: the old failure is its baseline.
  out += ' before=[' + titles() + ']';

  // A failure while the page is open — Run now with no AI action runs inside the request.
  const saved = await post('admin_save_workflow', { workflow: JSON.stringify({ name: 'Broken', enabled: false, space: 'Main',
      trigger: { types: ['page_updated'] }, actions: [{ type: 'chat', chat: 'Gone.chat', text: 'x' }] }) });
  const ran = await post('admin_run_workflow', { id: saved.workflow.id, test_space: 'Main', test_path: 'Docs/a.md' });
  out += ' ranstate=' + (ran.run ? ran.run.state : JSON.stringify(ran).slice(0, 60));

  // A tab coming back to the foreground polls at once — the same path a push takes.
  document.dispatchEvent(new Event('visibilitychange'));
  await sleep(1500);
  out += ' after=[' + titles() + ']';
  const toast = $('#toast-stack .sticky-toast-error');
  out += ' body=' + (toast && toast.querySelector('.sticky-toast-body') ? toast.querySelector('.sticky-toast-body').textContent.includes('Gone.chat') : false);
  const link = toast && toast.querySelector('.sticky-toast-link');
  out += ' link=[' + (link ? link.textContent : '') + ']';

  // A second poll must not announce it again.
  document.dispatchEvent(new Event('visibilitychange'));
  await sleep(1000);
  out += ' count=' + document.querySelectorAll('#toast-stack .sticky-toast').length;

  if (link) { link.click(); await sleep(1500); }
  const modal = $('#confirm-modal');
  out += ' modal=' + (modal && !modal.classList.contains('hidden') ? 'open' : 'closed');
  out += ' modaltitle=[' + ($('#confirm-modal-title') ? $('#confirm-modal-title').textContent : '') + ']';
  const pre = $('#confirm-modal-message pre');
  out += ' outcome=' + (pre ? pre.textContent.includes('--- Outcome') : false);
  out += ' toastgone=' + (document.querySelectorAll('#toast-stack .sticky-toast').length === 0);
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=30000 \
    --dump-dom "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'a failure from before the page loaded'
assert_contains "is not announced"              'before=[]'          "$PROBE"

section 'a failure while the page is open'
assert_contains "the run really failed (control)" 'ranstate=error'   "$PROBE"
assert_contains "raises a toast naming the workflow" 'after=[Workflow “Broken” failed]' "$PROBE"
assert_contains "  …with the error in it"       'body=true'          "$PROBE"
assert_contains "  …and a link to the log"      'link=[Open the error log]' "$PROBE"
assert_contains "  …once, however often it polls" 'count=1'          "$PROBE"

section 'the link'
assert_contains "opens the dialog"              'modal=open'         "$PROBE"
assert_contains "  …titled with the workflow"   'modaltitle=[Workflow “Broken” — run log]' "$PROBE"
assert_contains "  …showing the run's log"      'outcome=true'       "$PROBE"
assert_contains "  …and puts the toast away"    'toastgone=true'     "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
