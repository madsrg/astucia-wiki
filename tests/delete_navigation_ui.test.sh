# Where you land after deleting a page.
#
# It used to be the space's start page, wherever the deleted page was — so clearing out a
# folder meant navigating back into it after every delete. Now the next page in the same
# folder opens, in the tree's order; an emptied folder is selected the way a click in the
# tree selects it (and listed in the main area when the sidebar is collapsed); only a root
# page with nothing left beside it still falls back to the start page.
#
# A browser suite because all of this is client-side navigation: the delete itself is the
# same request either way.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md'         'Start page'
fixture_page 'Main/zz-root.md'      'Root page'
# Sorts before Main.md, so "the next root page" and "the start page" are different pages.
fixture_page 'Main/Alpha-root.md'   'First at the root'
fixture_page 'Main/Docs/alpha.md'   'A'
fixture_page 'Main/Docs/bravo.md'   'B'
fixture_page 'Main/Docs/Sub/deep.md' 'D'
fixture_page 'Main/Lone/only.md'    'O'
fixture_page 'Main/Shut/last.md'    'L'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/delete_navigation_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

// Open a page the way a reader does: click it in the tree (its folders opened first).
const open = async (path) => {
  const parts = path.split('/');
  for (let i = 1; i < parts.length; i++) {
    const f = $('#file-navigator [data-path="' + parts.slice(0, i).join('/') + '"]');
    const ul = f && f.parentElement.querySelector('ul');
    if (ul && ul.style.display === 'none') { f.click(); await sleep(300); }
  }
  const el = $('#file-navigator [data-path="' + path + '"]');
  if (!el) throw new Error('not in tree: ' + path);
  el.click(); await sleep(1200);
};
const del = async () => {
  $('#delete-btn').click();                     await sleep(400);
  $('#confirm-modal-ok').click();               await sleep(2500);
};
const where = () => state.currentPageType + ':' + state.currentPagePath;
const activeTree = () => {
  const a = $('#file-navigator .file-item.active > .file-item-content');
  return a ? a.dataset.path : 'none';
};

setTimeout(async () => {
  let out = '';
  try {
    await open('Docs/alpha.md'); await del();
    out += ' sibling=' + where() + ' marked=' + activeTree();
    // The subfolder holds a page, but it is not *in* Docs: the last page there goes next
    // to the folder, not into Sub.
    await del();
    out += ' emptied=' + where() + ' marked=' + activeTree();
    out += ' title=' + $('#current-page-title').textContent;

    await open('zz-root.md'); await del();
    out += ' root=' + where();

    await open('Lone/only.md'); await del();
    out += ' lone=' + where();

    // Collapsed sidebar: the emptied folder is listed in the main area.
    $('#sidebar-toggle-btn').click();          await sleep(500);
    await open('Shut/last.md'); await del();
    out += ' collapsed=' + where()
        + ' listing=' + ($('#files-folder-container').classList.contains('hidden') ? 'hidden' : 'shown');
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -sf --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'deleting a page keeps you in its folder'
assert_contains "the next page in the folder opens" 'sibling=md:Docs/bravo.md'  "$PROBE"
assert_contains "  …and is marked in the tree"      'marked=Docs/bravo.md'      "$PROBE"
assert_contains "the last page leaves the folder selected" 'emptied=folder:Docs ' "$PROBE"
assert_contains "  …marked in the tree"             'marked=Docs '              "$PROBE"
assert_contains "  …and named in the header"        'title=Docs'                "$PROBE"
assert_contains "a subfolder's page is not \"next\"" 'emptied=folder:Docs'      "$PROBE"

section 'the space root'
assert_contains "a root page opens the next root page" 'root=md:Alpha-root.md' "$PROBE"
assert_contains "an emptied folder is still a folder"  'lone=folder:Lone'       "$PROBE"

section 'with the sidebar collapsed'
assert_contains "the emptied folder is selected"     'collapsed=folder:Shut'    "$PROBE"
assert_contains "  …and listed in the main area"     'listing=shown'            "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
