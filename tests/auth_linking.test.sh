# One account, both sign-in methods (accounts.php).
#
# The bug this exists for: an email-code user who signed in with SSO by mistake filed an
# access request, and approving it made a second account with a new uid. What has to hold:
# an account can carry `sub` and `otpEmail` together; the admin is shown the duplicate and
# can answer it with a link; and nothing is ever linked on an address match alone — the
# person proves the other method (a code to the *existing* account's address, or a provider
# round trip while signed in), because a request's address may have been typed by whoever
# filed it.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

fixture_start both || exit 1
trap fixture_stop EXIT

fixture_users '{"schema":3,"users":[
  {"uid":1,"sub":"s-admin","name":"Admin","email":"admin@example.com","role":"admin","auth":"oidc"},
  {"uid":2,"name":"Olga","email":"olga@example.com","role":"editor","auth":"otp"},
  {"uid":3,"sub":"s-sam","name":"Sam","email":"sam@example.com","role":"editor","auth":"oidc"},
  {"uid":4,"name":"Tess","email":"tess@example.com","role":"reader","auth":"otp"},
  {"uid":5,"name":"Uma","email":"uma@example.com","role":"editor","auth":"otp"},
  {"uid":6,"sub":"s-legacy","name":"Lee","email":"lee@example.com","role":"editor","auth":"otp"}
]}'

# Mail goes to a file instead of a provider: the codes are read from it, which keeps
# otp_send, otp_verify and the link flow running unmodified. Only the transport is stubbed.
MAIL=$WIKI_ROOT/mail.log
cat >> "$WIKI_APP/config.php" <<CFG
define('MAIL_PROVIDER', 'sendgrid');
define('SENDGRID_API_KEY', 'test');
define('SENDGRID_FROM_EMAIL', 'wiki@example.com');
CFG
python3 - "$WIKI_APP/mailer.php" "$MAIL" <<'PY'
import sys
p, log = sys.argv[1], sys.argv[2]
s = open(p).read()
s = s.replace("function send_email(string $to, string $to_name, string $subject, string $html_body): bool {",
  "function send_email(string $to, string $to_name, string $subject, string $html_body): bool {\n"
  f"    file_put_contents('{log}', json_encode(['to' => $to, 'subject' => $subject, 'body' => $html_body]) . \"\\n\", FILE_APPEND);\n"
  "    return true;", 1)
open(p, 'w').write(s)
PY
# The fixture's readiness ping already compiled mailer.php, and opcache would keep serving
# that copy for a while yet.
printf '<?php if (function_exists("opcache_reset")) opcache_reset(); echo "ok";' > "$WIKI_APP/__test_opcache.php"
curl -s "$WIKI_URL/__test_opcache.php" > /dev/null

# The provider's half of an SSO sign-in. auth.php hands the verified claims to
# wiki_oidc_complete(); this calls it the same way, minus the round trip to a provider.
cat > "$WIKI_APP/__test_oidc.php" <<'SHIM'
<?php
// GENERATED BY tests/auth_linking.test.sh — never part of a release.
require_once __DIR__ . '/config.php';
require_once __DIR__ . '/accounts.php';
require_once __DIR__ . '/remember_me.php';
session_start();
echo wiki_oidc_complete(['sub' => $_GET['sub'] ?? '', 'email' => $_GET['email'] ?? '', 'name' => $_GET['name'] ?? ''], 'idtok');
SHIM

USERS=$WIKI_SYS/users.json
REQS=$WIKI_SYS/user_requests.json
# u <uid> <field> — a field of a user record, '-' when absent
u() { python3 -c "import json,sys;r=[x for x in json.load(open('$USERS'))['users'] if x.get('uid')==$1];print(r[0].get('$2','-') if r else 'none')"; }
people() { python3 -c "import json;print(len([x for x in json.load(open('$USERS'))['users'] if not x.get('is_ai') and not x.get('is_system')]))"; }
req() { python3 -c "import json;r=[x for x in json.load(open('$REQS'))['requests'] if x['sub']=='$1'];print(r[0].get('$2','-') if r else 'none')" 2>/dev/null || echo none; }
# last_code <address> — the code in the newest mail to that address
last_code() { python3 -c "
import json,re
m=[json.loads(l) for l in open('$MAIL') if l.strip()]
m=[x for x in m if x['to']=='$1']
print(re.search(r'>(\d{6})<', m[-1]['body']).group(1) if m else '')"; }
mails_to() { python3 -c "import json;print(len([1 for l in open('$MAIL') if l.strip() and json.loads(l)['to']=='$1']))" 2>/dev/null || echo 0; }
whoami() { get_as "$1" 'index.php' | command grep -o 'data-user-uid="[0-9]*"' | command grep -o '[0-9]*'; }
otp_login() {
    rm -f "$1"
    post_as "$1" 'auth.php?action=otp_send' "email=$2" > /dev/null
    post_as "$1" 'auth.php?action=otp_verify' "code=$(last_code "$2")" > /dev/null
}
# sso <jar> <query> — the provider callback; prints where the browser is sent
sso() { get_as "$1" "__test_oidc.php?$2"; }
location() { curl -s -o /dev/null -w '%{redirect_url}' -b "$1" -c "$1" --max-time 15 "$WIKI_URL/$2"; }

ADM=$WIKI_ROOT/jar-admin
fixture_login "$ADM" "uid=1&sub=s-admin&name=Admin&role=admin"

section "existing accounts keep signing in"
O=$WIKI_ROOT/jar-olga; otp_login "$O" olga@example.com
assert_eq       "a legacy email-code record still signs in"        2 "$(whoami "$O")"
P=$(post_as "$O" 'api.php?action=user_get_preferences' '')
assert_contains "My Preferences opens for an email-code session"   '"success":true' "$P"
assert_contains "and reports the sign-in address"                  '"otpEmail":"olga@example.com"' "$P"
assert_contains "and no SSO"                                       '"sso":false' "$P"
S=$WIKI_ROOT/jar-sam; rm -f "$S"
assert_eq       "an SSO account signs in through the callback"     index.php "$(sso "$S" 'sub=s-sam&email=sam@example.com&name=Sam')"
assert_eq       "as itself"                                        3 "$(whoami "$S")"
L=$WIKI_ROOT/jar-lee; rm -f "$L"
assert_eq       "a legacy OTP record holding a sub is not an SSO account" pending_access.php "$(sso "$L" 'sub=s-legacy&email=lee@example.com&name=Lee')"

section "the accident: an email-code user signs in with SSO"
X=$WIKI_ROOT/jar-olga-sso; rm -f "$X"
assert_eq       "files an access request rather than signing in"  pending_access.php "$(sso "$X" 'sub=s-olga&email=olga@corp.example&name=Olga+K')"
assert_eq       "the request knows its address came from the provider" claim "$(req s-olga email_source)"
python3 - "$REQS" <<'PY'
import json,sys
d=json.load(open(sys.argv[1])); d['requests'][0]['email']='olga@example.com'; json.dump(d,open(sys.argv[1],'w'))
PY
R=$(get_as "$ADM" 'api.php?action=admin_get_user_requests')
assert_contains "the admin sees which account it matches"          '"matches":[{"uid":2,"name":"Olga","auth":"otp","linkable":true}]' "$R"

section "answering it with a link"
assert_contains "linking to an account that has SSO is refused"   'already has single sign-on' "$(post_as "$ADM" 'api.php?action=admin_link_request' 'sub=s-olga&uid=3')"
assert_contains "linking is admin-only"                            'Admin' "$(post_as "$O" 'api.php?action=admin_link_request' 'sub=s-olga&uid=2')"
assert_contains "positive control: the admin can link"             '"success":true' "$(post_as "$ADM" 'api.php?action=admin_link_request' 'sub=s-olga&uid=2')"
assert_eq       "the request waits for the person"                 link "$(req s-olga status)"
assert_eq       "nothing is linked yet"                            - "$(u 2 sub)"
assert_contains "the account's owner is told, at its own address"  'Single sign-on for your account' "$(command grep olga@example.com "$MAIL" | tail -1)"
assert_eq       "the next SSO sign-in asks for a code"             login.php?step=verify "$(sso "$X" 'sub=s-olga&email=olga@corp.example&name=Olga+K')"
assert_contains "the login page says what the code is for"         'login.link-intro' "$(get_as "$X" 'login.php')"
assert_contains "the code went to the existing account"            'Link single sign-on' "$(command grep olga@example.com "$MAIL" | tail -1)"
assert_eq       "not to the request's address"                     0 "$(mails_to olga@corp.example)"
post_as "$X" 'auth.php?action=otp_verify' 'code=000000' > /dev/null
assert_eq       "a wrong code links nothing"                       - "$(u 2 sub)"
CODE=$(last_code olga@example.com)
post_as "$X" 'auth.php?action=otp_verify' "code=$CODE" > /dev/null
assert_eq       "the right code links the identity to the account" s-olga "$(u 2 sub)"
assert_eq       "and signs in as that account"                     2 "$(whoami "$X")"
assert_eq       "no second account was made"                       6 "$(people)"
assert_eq       "the request is gone"                              none "$(req s-olga status)"
assert_eq       "the account now has both"                         both "$(u 2 auth)"
assert_eq       "the email-code address is kept apart"             olga@example.com "$(u 2 otpEmail)"
assert_eq       "email shows the provider's address"               olga@corp.example "$(u 2 email)"
assert_eq       "mail keeps going where it went before"            olga@example.com "$(u 2 notifyEmail)"
X2=$WIKI_ROOT/jar-olga-sso2; rm -f "$X2"
assert_eq       "afterwards SSO signs straight in"                 index.php "$(sso "$X2" 'sub=s-olga&email=olga@corp.example&name=Olga+K')"
assert_eq       "as the same uid"                                  2 "$(whoami "$X2")"
O2=$WIKI_ROOT/jar-olga2; otp_login "$O2" olga@example.com
assert_eq       "and the email code still works"                   2 "$(whoami "$O2")"
assert_eq       "the claim never moved the code address"           olga@example.com "$(u 2 otpEmail)"

section "approving a duplicate is guarded"
python3 - "$REQS" <<'PY'
import json,sys
d=json.load(open(sys.argv[1])); d['requests']+= [{'sub':'s-olga','name':'Olga','email':'x@example.com','status':'pending'},{'sub':'s-new','name':'New','email':'new@example.com','status':'pending'}]
json.dump(d,open(sys.argv[1],'w'))
PY
assert_contains "an identity that already has an account is not approved again" 'already belongs' "$(post_as "$ADM" 'api.php?action=admin_approve_request' 'sub=s-olga&role=editor')"
assert_contains "positive control: a new identity is approved"     '"success":true' "$(post_as "$ADM" 'api.php?action=admin_approve_request' 'sub=s-new&role=editor')"
assert_eq       "as an SSO account"                                oidc "$(u 7 auth)"

section "My Preferences: adding an email code to an SSO account"
assert_contains "GET is refused"                                   'POST required' "$(get_as "$S" 'api.php?action=account_otp_add_send&email=a@example.com')"
assert_contains "another account's address is refused"            'account.err.otp-taken' "$(post_as "$S" 'api.php?action=account_otp_add_send' 'email=TESS@example.com')"
assert_contains "positive control: a free address gets a code"    '"success":true' "$(post_as "$S" 'api.php?action=account_otp_add_send' 'email=sam.code@example.com')"
assert_contains "a second code within seconds is refused"          'account.err.wait' "$(post_as "$S" 'api.php?action=account_otp_add_send' 'email=sam.other@example.com')"
assert_contains "a wrong code is refused"                          'login.err.invalid-code' "$(post_as "$S" 'api.php?action=account_otp_add_verify' 'code=000000')"
assert_eq       "and adds nothing"                                 - "$(u 3 otpEmail)"
assert_contains "the right code adds it"                           '"success":true' "$(post_as "$S" 'api.php?action=account_otp_add_verify' "code=$(last_code sam.code@example.com)")"
assert_eq       "the account has both"                             both "$(u 3 auth)"
S2=$WIKI_ROOT/jar-sam2; otp_login "$S2" sam.code@example.com
assert_eq       "and signs in with the code"                       3 "$(whoami "$S2")"
assert_contains "a code issued to sign in cannot add an address"   'login.err.session-expired' "$(
    J=$WIKI_ROOT/jar-mixed; rm -f "$J"; otp_login "$J" uma@example.com
    post_as "$J" 'auth.php?action=otp_send' 'email=uma@example.com' > /dev/null
    post_as "$J" 'api.php?action=account_otp_add_verify' "code=$(last_code uma@example.com)")"

section "My Preferences: adding SSO to an email-code account"
T=$WIKI_ROOT/jar-tess; otp_login "$T" tess@example.com
assert_eq       "(Tess is signed in)"                               4 "$(whoami "$T")"
START=$(post_as "$T" 'api.php?action=account_sso_link_start' '')
assert_contains "starting hands out a one-time URL"               'auth.php?action=link_sso&n=' "$START"
NONCE=$(printf '%s' "$START" | python3 -c 'import json,sys;print(json.load(sys.stdin)["url"].split("&n=")[1])')
assert_contains "a wrong nonce is refused"                        'account.err.link-expired' "$(location "$T" 'auth.php?action=link_sso&n=nope')"
# The refusal clears the marker, so this is a forged start: no auth.php in between.
post_as "$T" 'api.php?action=account_sso_link_start' '' > /dev/null
sso "$T" 'sub=s-tess&email=tess@corp.example&name=Tess' > /dev/null
assert_eq       "a callback that did not pass auth.php's check links nothing" - "$(u 4 sub)"
otp_login "$T" tess@example.com
START=$(post_as "$T" 'api.php?action=account_sso_link_start' '')
NONCE=$(printf '%s' "$START" | python3 -c 'import json,sys;print(json.load(sys.stdin)["url"].split("&n=")[1])')
# Passes the check, then fails to reach the (fictional) provider — which is as far as a
# test can follow it. The marker it leaves is what the callback honours.
assert_not_contains "the right nonce passes the check"            'link-expired' "$(location "$T" "auth.php?action=link_sso&n=$NONCE")"
assert_contains "the callback links it"                           'account.notice.sso-linked' "$(sso "$T" 'sub=s-tess&email=tess@corp.example&name=Tess')"
assert_eq       "the account has the identity"                     s-tess "$(u 4 sub)"
assert_eq       "Tess is still signed in as herself"               4 "$(whoami "$T")"
U=$WIKI_ROOT/jar-uma; otp_login "$U" uma@example.com
post_as "$U" 'api.php?action=account_sso_link_start' '' > /dev/null
NONCE=$(post_as "$U" 'api.php?action=account_sso_link_start' '' | python3 -c 'import json,sys;print(json.load(sys.stdin)["url"].split("&n=")[1])')
location "$U" "auth.php?action=link_sso&n=$NONCE" > /dev/null
assert_contains "an identity that belongs to another account is refused" 'account.err.sso-taken' "$(sso "$U" 'sub=s-olga&email=x@example.com&name=Uma')"
assert_eq       "and Uma's account is unchanged"                   otp "$(u 5 auth)"
assert_contains "an account that has SSO cannot start another"    'account.err.has-sso' "$(post_as "$T" 'api.php?action=account_sso_link_start' '')"

section "removing a method"
assert_contains "removing SSO from an account with both works"    '"success":true' "$(post_as "$T" 'api.php?action=account_unlink' 'method=sso')"
assert_eq       "the identity is gone"                             - "$(u 4 sub)"
assert_eq       "email shows the login address again"              tess@example.com "$(u 4 email)"
assert_contains "the last method cannot be removed"                'account.err.last-method' "$(post_as "$T" 'api.php?action=account_unlink' 'method=otp')"
assert_eq       "and is still there"                               tess@example.com "$(u 4 otpEmail)"

section "Admin → Users"
LIST=$(get_as "$ADM" 'api.php?action=admin_get_users' | python3 -c 'import json,sys;print(json.dumps(json.load(sys.stdin)["data"]))')
# Effective methods, read the way accounts.php reads a legacy record: saving may write
# `otpEmail` onto a record that only implied it, which is the same account.
methods() { python3 -c "
import json
out=[]
for x in json.load(open('$USERS'))['users']:
    legacy_otp = x.get('auth')=='otp' and 'otpEmail' not in x
    sub = '' if legacy_otp else x.get('sub','')
    otp = x.get('otpEmail', x.get('email','') if (x.get('auth') or ('otp' if not x.get('sub') else 'oidc'))=='otp' else '')
    out.append((x['uid'], sub, otp))
print(json.dumps(out))"; }
BEFORE=$(methods)
post_as "$ADM" 'api.php?action=admin_save_users' "users=$LIST" > /dev/null
assert_eq       "saving the list unchanged changes no sign-in method" "$BEFORE" "$(methods)"
edit() { printf '%s' "$LIST" | python3 -c "
import json,sys
l=json.load(sys.stdin)
for x in l:
    if x['uid']==$1: x.update(json.loads(sys.argv[1]))
print(json.dumps(l))" "$2"; }
assert_contains "an admin cannot give an account an SSO identity" '"success":true' "$(post_as "$ADM" 'api.php?action=admin_save_users' "users=$(edit 5 '{"sub":"s-forged"}')")"
assert_eq       "(it is ignored)"                                  - "$(u 5 sub)"
assert_contains "two accounts with one code address are refused"  'share the login email' "$(post_as "$ADM" 'api.php?action=admin_save_users' "users=$(edit 5 '{"otpEmail":"Olga@example.com"}')")"
assert_contains "removing an account's only method is refused"    'at least one way' "$(post_as "$ADM" 'api.php?action=admin_save_users' "users=$(edit 3 '{"sso":false,"otpEmail":""}')")"
assert_contains "positive control: removing SSO where a code remains" '"success":true' "$(post_as "$ADM" 'api.php?action=admin_save_users' "users=$(edit 2 '{"sso":false}')")"
assert_eq       "leaves an email-code account"                     otp "$(u 2 auth)"
assert_eq       "showing its login address"                        olga@example.com "$(u 2 email)"
assert_contains "the access log records it"                        'ACCOUNT_UNLINKED' "$(cat "$WIKI_ROOT"/logs/*_access.log)"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
