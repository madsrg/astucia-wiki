# Help in a browser (modules/help): the sidebar's ? icon and Alt+H open one dialog with the
# keyboard shortcuts in two groups and a button to the online documentation.
#
# Alt+H works from anywhere — reading, and inside the Markdown editor — and toggles. It
# replaced the editor's Alt+A list, which must be gone, key and markup both. The docs
# button opens astucia.wiki/docs in a new tab, never in this one.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Welcome

Some text.'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/help_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const shown = (el) => !!el && !el.classList.contains('hidden');

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const modal = () => $('#help-modal');
const isOpen = () => shown(modal()) ? 'open' : 'shut';
const altKey = (k, target) => (target || document).dispatchEvent(new KeyboardEvent('keydown',
  { key: k, code: 'Key' + k.toUpperCase(), altKey: true, bubbles: true, cancelable: true }));

const run = async () => {
  let out = '';
  const opened = [];
  window.open = (url, target, feat) => { opened.push(url + '|' + target + '|' + feat); return null; };

  out += ' oldmarkup=' + ($('#hotkey-lightbox') ? 'present' : 'gone');
  click($('#help-btn'));                                      await sleep(300);
  out += ' click=' + isOpen();
  out += ' groups=' + $$('#help-modal .help-group').length;
  out += ' rows=' + $$('#help-modal .help-table tr').length;
  out += ' firstkeys=' + [...$$('#help-modal .help-table tr')[0].querySelectorAll('kbd')].map(k => k.textContent).join('+');
  out += ' kbds=' + $$('#help-modal kbd').length;
  click($('#help-modal [data-act="docs"]'));                  await sleep(100);
  out += ' docs=' + (opened[0] || 'none');
  out += ' still=' + isOpen();
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  await sleep(100);
  out += ' esc=' + isOpen();

  altKey('h');                                                await sleep(200);
  out += ' altH=' + isOpen();
  altKey('h');                                                await sleep(200);
  out += ' altHagain=' + isOpen();

  // Inside the editor: Alt+H opens the dialog there too, and Alt+A no longer does anything.
  click($('#edit-btn'));                                      await sleep(800);
  const ta = $('#editor-container');
  out += ' editing=' + (shown($('.editor-container-wrapper')) ? 'yes' : 'no');
  ta.focus();
  const before = ta.value;
  altKey('a', ta);                                            await sleep(200);
  out += ' altA=' + isOpen() + '/text:' + (ta.value === before ? 'same' : 'changed');
  altKey('h', ta);                                            await sleep(200);
  out += ' editorAltH=' + isOpen() + '/text:' + (ta.value === before ? 'same' : 'changed');
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/index.php?space=Main" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE.*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the dialog'
assert_contains "the old Alt+A list is gone from the page"   'oldmarkup=gone'   "$PROBE"
assert_contains "the ? icon opens Help"                      'click=open'       "$PROBE"
assert_contains "  …with two groups"                         'groups=2 '        "$PROBE"
assert_contains "  …and every shortcut, as rows"             'rows=20 '         "$PROBE"
assert_contains "  …the first saying Alt+H"                  'firstkeys=Alt+H ' "$PROBE"

section 'the online documentation'
assert_contains "opens astucia.wiki/docs in a new tab"       'docs=https://astucia.wiki/docs/|_blank|noopener' "$PROBE"
assert_contains "  …and leaves the dialog where it was"      'still=open'       "$PROBE"
assert_contains "Esc closes it"                              'esc=shut'         "$PROBE"

section 'Alt+H, from anywhere'
assert_contains "while reading it opens Help"                'altH=open'        "$PROBE"
assert_contains "  …and again closes it"                     'altHagain=shut'   "$PROBE"
assert_contains "positive control: the editor is open"      'editing=yes'      "$PROBE"
assert_contains "in the editor, Alt+A no longer does anything" 'altA=shut/text:same' "$PROBE"
assert_contains "  …and Alt+H opens Help, typing nothing"    'editorAltH=open/text:same' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
