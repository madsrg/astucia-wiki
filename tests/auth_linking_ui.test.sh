# Sign-in methods in the browser: My Preferences, Admin → Users and Admin → Requests.
#
# auth_linking.test.sh covers the rules over HTTP; this is the half it cannot see — that
# the section appears for the accounts it should, that its buttons reach the actions, and
# that the admin is shown the duplicate and offered the link. Chrome missing means skip.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start both || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_users '{"schema":3,"users":[
  {"uid":1,"sub":"s-admin","name":"Admin","email":"admin@example.com","role":"admin","auth":"oidc"},
  {"uid":2,"name":"Olga","email":"olga@example.com","role":"editor","auth":"otp"},
  {"uid":3,"sub":"s-sam","name":"Sam","email":"sam@example.com","otpEmail":"sam.code@example.com","role":"editor","auth":"both"}
]}'
printf '%s' '{"requests":[{"sub":"s-olga","name":"Olga K","email":"olga@example.com","email_source":"typed","requested_at":"2026-10-26T10:00:00+00:00","status":"pending"}]}' > "$WIKI_SYS/user_requests.json"
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
# A link is finished by a code in the mail, so linking needs mail; it goes to a file here.
# The server is restarted below, so the stub is what it loads.
cat >> "$WIKI_APP/config.php" <<CFG
define('MAIL_PROVIDER', 'sendgrid');
define('SENDGRID_API_KEY', 'test');
define('SENDGRID_FROM_EMAIL', 'wiki@example.com');
CFG
python3 - "$WIKI_APP/mailer.php" "$WIKI_ROOT/mail.log" <<'PY'
import sys
p, log = sys.argv[1], sys.argv[2]
s = open(p).read()
s = s.replace("function send_email(string $to, string $to_name, string $subject, string $html_body): bool {",
  "function send_email(string $to, string $to_name, string $subject, string $html_body): bool {\n"
  f"    file_put_contents('{log}', $to . ' ' . $subject . \"\\n\", FILE_APPEND);\n"
  "    return true;", 1)
open(p, 'w').write(s)
PY

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/auth_linking_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

# One probe for every visit; what it does depends on who is signed in and on ?probe=.
python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (s) => document.querySelector(s);
const report = (v) => document.documentElement.setAttribute('data-probe', v);
window.addEventListener('error', e => report('fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report('fatal=' + (e.reason && e.reason.message || e.reason)));
const mode = new URLSearchParams(location.search).get('probe') || '';
const rows = () => Array.from(document.querySelectorAll('.pref-signin-row')).map(r =>
    r.dataset.method + ':' + r.querySelector('.pref-signin-detail').textContent.trim() + ':' +
    (r.querySelector('[data-signin-add]') ? 'add' : r.querySelector('[data-signin-remove]') ? 'remove' : 'none')).join('|');
setTimeout(async () => {
  try {
    let out = 'mode=' + mode;
    if (mode === 'notice') {
      // Read before the toast times out, and after the URL has been cleaned.
      out += ' toast=' + $('#toast-message').textContent.trim();
      out += ' url=' + (location.search.includes('account_') ? 'dirty' : 'clean');
      report(out); return;
    }
    if (mode === 'prefs') {
      $('#preferences-btn').click();                              await sleep(1500);
      out += ' shown=' + !$('#pref-signin-group').classList.contains('hidden');
      out += ' rows=' + rows();
      const add = $('[data-signin-add="otp"]');
      if (add) {
        add.click();                                              await sleep(200);
        out += ' form=' + !$('#pref-signin-otp-form').classList.contains('hidden');
      }
      const rm = $('[data-signin-remove="otp"]');
      if (rm) {
        rm.click();                                               await sleep(400);
        out += ' confirm=' + !$('#confirm-modal').classList.contains('hidden');
        $('#confirm-modal-ok').click();                           await sleep(1500);
        out += ' after=' + rows();
      }
      report(out); return;
    }
    if (mode === 'admin') {
      $('#admin-btn').click();                                    await sleep(1500);
      const tr = (name) => Array.from(document.querySelectorAll('#admin-users-table tbody tr'))
          .find(r => r.querySelector('.admin-td-name').textContent.includes(name)
                  || r.querySelector('.admin-td-name input')?.value === name);
      const badges = (name) => Array.from(tr(name).querySelectorAll('.admin-auth-badge')).map(b => b.textContent).join('+');
      out += ' admin=' + badges('Admin') + (tr('Admin').querySelector('.admin-auth-add') ? '/canadd' : '');
      out += ' olga=' + badges('Olga');
      out += ' sam=' + badges('Sam');
      out += ' samotp=' + (tr('Sam').querySelector('.admin-otp-input')?.value || 'none');
      $('.admin-tab[data-tab=requests]').click();                 await sleep(1500);
      const req = document.querySelector('#admin-requests-table tbody tr');
      out += ' match=' + (req.querySelector('.admin-req-match')?.textContent.trim() || 'none');
      out += ' typed=' + !!req.querySelector('.admin-req-match-typed');
      const link = Array.from(req.querySelectorAll('button')).find(b => b.textContent.includes('Olga'));
      out += ' linkbtn=' + (link ? link.textContent.trim() : 'none');
      if (link) {
        link.click();                                             await sleep(400);
        $('#confirm-modal-ok').click();                           await sleep(2000);
        const r2 = document.querySelector('#admin-requests-table tbody tr');
        out += ' status=' + r2.querySelector('.admin-log-badge').textContent.trim();
      }
      report(out); return;
    }
    report(out + ' unknown');
  } catch (e) { report('fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -d "session.cookie_lifetime=3600" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -sf --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

PROFILE="$WIKI_ROOT/chrome-profile"
chrome() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --user-data-dir="$PROFILE" --virtual-time-budget=30000 \
        --dump-dom "$1" 2>/dev/null
}
login() { rm -rf "$PROFILE"; chrome "$WIKI_URL/__test_login.php?$1" > /dev/null; }
probe() {
    chrome "$WIKI_URL/index.php?$1" > "$WIKI_ROOT/dom.html"
    PROBE=$(command grep -o 'data-probe="[^"]*"' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "$1"
    assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"
}
u() { python3 -c "import json;r=[x for x in json.load(open('$WIKI_SYS/users.json'))['users'] if x.get('uid')==$1];print(r[0].get('$2','-'))"; }

section "My Preferences, email-code account"
login "uid=2&name=Olga&role=editor&auth=otp&email=olga@example.com"
probe "probe=prefs"
assert_contains "the section is shown"                         'shown=true' "$PROBE"
assert_contains "SSO can be added, the code address is listed" 'rows=sso:Not set up:add|otp:olga@example.com:none' "$PROBE"

section "My Preferences, SSO account"
login "uid=1&sub=s-admin&name=Admin&role=admin"
probe "probe=prefs"
assert_contains "an email code can be added"                   'otp:Not set up:add' "$PROBE"
assert_contains "and Add opens the address form"               'form=true' "$PROBE"

section "My Preferences, account with both"
login "uid=3&sub=s-sam&name=Sam&role=editor"
probe "probe=prefs"
assert_contains "both can be removed"                          'rows=sso:sam@example.com:remove|otp:sam.code@example.com:remove' "$PROBE"
assert_contains "Remove asks first"                            'confirm=true' "$PROBE"
assert_contains "and then the section redraws without it"      'after=sso:sam@example.com:none|otp:Not set up:add' "$PROBE"
assert_eq       "the account lost its code address"            oidc "$(u 3 auth)"

section "back from the provider"
probe "probe=notice&account_notice=account.notice.sso-linked"
assert_contains "the outcome is shown"                         'toast=Single sign-on added' "$PROBE"
assert_contains "and taken out of the address bar"             'url=clean' "$PROBE"

section "Admin → Users and Requests"
python3 - "$WIKI_SYS/users.json" <<'PY'
import json,sys
d=json.load(open(sys.argv[1]))
for u in d['users']:
    if u['uid']==3: u['otpEmail']='sam.code@example.com'; u['auth']='both'
json.dump(d,open(sys.argv[1],'w'))
PY
login "uid=1&sub=s-admin&name=Admin&role=admin"
probe "probe=admin"
assert_contains "an SSO account shows one badge, and can be given a code" 'admin=SSO/canadd' "$PROBE"
assert_contains "an email-code account shows its badge"        'olga=OTP ' "$PROBE"
assert_contains "an account with both shows both, removable"   'sam=SSO×+OTP×' "$PROBE"
assert_contains "with its code address editable"               'samotp=sam.code@example.com' "$PROBE"
assert_contains "the duplicate request names the account"      'match=Same address as Olga (OTP)' "$PROBE"
assert_contains "and says the address was typed"               'typed=true' "$PROBE"
assert_contains "Link is offered"                              'linkbtn=Link to Olga' "$PROBE"
assert_contains "and linking leaves it waiting for the code"   'status=awaiting code' "$PROBE"
assert_eq       "on the server"                                link "$(python3 -c "import json;print(json.load(open('$WIKI_SYS/user_requests.json'))['requests'][0]['status'])")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
