# Service tokens in the admin panel, now that only a hash is stored: the token is shown once,
# in a dialog, when it is created or regenerated — and never again.
#
# tests/service_tokens.test.sh proves the server keeps no token; this proves the admin is
# actually given it. Everything here is UI: a dialog that never opens, or closes on a stray
# click, would lose every new token while every HTTP assertion stayed green.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
printf '%s' '[{"id":"c1","name":"Test","provider":"openai","api_key":"k"}]' > "$WIKI_SYS/llm_connections.json"
fixture_users '{"schema":3,"users":[]}'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/service_tokens_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const dialog = () => $('.admin-token-once');
const shown = () => (dialog() && $('.admin-token-once-value').value) || '';

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  let out = '';
  click($('#admin-btn'));                                    await sleep(800);
  click($('.admin-group[data-group="ai"]'));                 await sleep(600);
  click($('.admin-tab[data-tab="ai"]'));                     await sleep(1000);

  // Create: the dialog carries the token.
  click($('#admin-ai-add-btn'));                             await sleep(800);
  $('#ai-f-name').value = 'Tokbot';
  const sel = $('#ai-f-connection'); sel.value = 'c1'; sel.dispatchEvent(new Event('change'));
  click($('#ai-f-save-btn'));                                await sleep(1500);
  const first = shown();
  out += ' created=' + (first.startsWith('wk_ai_') ? 'shown' : 'none');
  out += ' warn=' + (($('.admin-token-once-warn')?.textContent || '').includes('Tokbot') ? 'named' : 'unnamed');
  out += ' usage=' + (($('.admin-token-once .admin-ai-token-hint')?.textContent || '').includes('Bearer <token>') ? 'intact' : 'mangled');
  click(dialog());                                           await sleep(200);
  out += ' strayclick=' + (dialog() ? 'kept' : 'closed');
  click($('.admin-token-once-done'));                        await sleep(800);
  out += ' done=' + (dialog() ? 'open' : 'closed');

  // The form shows only the hint now, and no Copy button.
  const row = Array.from(document.querySelectorAll('#admin-ai-list tbody tr')).find(tr => tr.textContent.includes('Tokbot'));
  click(row.querySelector('.btn-secondary'));                await sleep(1200);
  const hint = $('#ai-f-token').textContent.trim();
  out += ' hint=' + (hint === 'wk_ai_' + String.fromCharCode(8230) + first.slice(-4) ? 'matches' : hint);
  out += ' copybtn=' + ($('#ai-f-copy-btn') ? 'present' : 'gone');

  // The instructions get the token filled in, since it was revealed in this session.
  click($('#ai-f-agent-instructions-btn'));                  await sleep(1200);
  out += ' instructions=' + ($('#agent-instructions-text').value.includes(first) ? 'filled' : 'placeholder');
  click($('#agent-instructions-close-btn'));                 await sleep(300);

  // Regenerate: confirm, then a new token in the dialog, and the hint follows it.
  click($('#ai-f-regen-btn'));                               await sleep(500);
  click($('#confirm-modal-ok'));                             await sleep(1500);
  const second = shown();
  out += ' regen=' + (second.startsWith('wk_ai_') && second !== first ? 'new' : 'same');
  click($('.admin-token-once-done'));                        await sleep(300);
  out += ' rehint=' + ($('#ai-f-token').textContent.trim().endsWith(second.slice(-4)) ? 'updated' : 'stale');

  // API accounts work the same way.
  click($('.admin-group[data-group="users"]'));              await sleep(600);
  click($('.admin-tab[data-tab="api"]'));                    await sleep(1000);
  click($('#admin-api-add-btn'));                            await sleep(800);
  $('#api-f-name').value = 'Robot';
  click($('#api-f-save-btn'));                               await sleep(1500);
  const sys = shown();
  out += ' apicreated=' + (sys.startsWith('wk_sys_') ? 'shown' : 'none');
  click($('.admin-token-once-done'));                        await sleep(800);
  const cell = Array.from(document.querySelectorAll('#admin-api-list tbody tr')).find(tr => tr.textContent.includes('Robot'));
  out += ' apilist=' + (cell && cell.textContent.includes(sys.slice(-4)) && !cell.textContent.includes(sys) ? 'hint' : 'other');
  return out;
};

setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'creating an AI user'
assert_contains "the new token is shown in a dialog"   'created=shown'      "$PROBE"
assert_contains "  …naming who it belongs to"          'warn=named'         "$PROBE"
assert_contains "  …with the header shown intact"      'usage=intact'       "$PROBE"
assert_contains "a stray click does not close it"      'strayclick=kept'    "$PROBE"
assert_contains "only the button does"                 'done=closed'        "$PROBE"

section 'the form afterwards'
assert_contains "shows the hint for that token"        'hint=matches'       "$PROBE"
assert_contains "and offers nothing to copy"           'copybtn=gone'       "$PROBE"
assert_contains "instructions get the revealed token"  'instructions=filled' "$PROBE"

section 'regenerating'
assert_contains "shows a new token"                    'regen=new'          "$PROBE"
assert_contains "and the hint follows it"              'rehint=updated'     "$PROBE"

section 'API accounts'
assert_contains "a new account's token is shown"       'apicreated=shown'   "$PROBE"
assert_contains "the list shows only its hint"         'apilist=hint'       "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
