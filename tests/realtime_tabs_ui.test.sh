# One realtime stream per browser, held by the active tab (modules/realtime, rule 4).
#
# Over HTTP/1.1 a browser allows about six connections per host and every open tab held one
# SSE stream, so six tabs hung the wiki in that browser. Two same-origin iframes stand in for
# two tabs here: they share a BroadcastChannel exactly as tabs do. Each frame's EventSource is
# replaced by a fake that records itself and can be fed an event, and each frame's
# document.hidden is under the test's control — so no hub is needed, and "switching tabs"
# is a visibilitychange the test dispatches.
#
# Asserted: a second tab opens no stream of its own and still receives events; switching to
# it moves the stream; the handoff loses no event (the old stream is kept until the new one
# opens) and makes no background tab refetch; a second *visible* tab does not steal the stream; closing
# the holder hands it to a visible tab.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Welcome'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null

# Realtime on, so the ticket says "enabled"; the hub URL points nowhere, so a publish from
# a write cannot reach a real hub on this machine.
python3 - "$WIKI_APP/config.php" <<'PY'
import re, sys
p = sys.argv[1]; s = open(p).read()
s = re.sub(r"define\('ENABLE_REALTIME',[^;]*\);",      "define('ENABLE_REALTIME', true);", s)
s = re.sub(r"define\('MERCURE_JWT_KEY',[^;]*\);",      "define('MERCURE_JWT_KEY', 'test-key-test-key-test-key-test-key');", s)
s = re.sub(r"define\('MERCURE_INTERNAL_URL',[^;]*\);", "define('MERCURE_INTERNAL_URL', 'http://127.0.0.1:9');", s)
open(p, 'w').write(s)
PY

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/realtime_tabs_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')   { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css')  { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg')  { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    if ($e === 'html') { header('Content-Type: text/html');       readfile($f); return true; }
    return false;
}
return false;
R

# In every "tab": a fake EventSource reporting to the harness, and a document.hidden the
# harness sets. Classic script at the top of <head>, so it is in place before any module.
python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
shim = """<head>
<script>
(function () {
  var name = new URLSearchParams(location.search).get('tab') || '?';
  var H = top.__rt;
  window.__hidden = new URLSearchParams(location.search).get('hidden') === '1';
  Object.defineProperty(document, 'hidden', { get: function () { return window.__hidden; } });
  Object.defineProperty(document, 'visibilityState', { get: function () { return window.__hidden ? 'hidden' : 'visible'; } });
  function FakeES(url) {
    var self = this;
    this.url = url; this.readyState = 0; this.tab = name; this.closed = false;
    H.streams.push(this);
    setTimeout(function () {
      if (self.closed) return;
      self.readyState = 1;
      if (self.onopen) self.onopen({});
    }, H.openDelay);
  }
  FakeES.CONNECTING = 0; FakeES.OPEN = 1; FakeES.CLOSED = 2;
  FakeES.prototype.close = function () { this.closed = true; this.readyState = 2; };
  FakeES.prototype.deliver = function (topic) {
    if (this.readyState === 1 && this.onmessage) this.onmessage({ data: JSON.stringify({ topic: topic }) });
  };
  window.EventSource = FakeES;
  document.addEventListener('wiki:realtime', function (e) { H.live[name] = e.detail.live; });
  // Count re-reads: a resync calls every handler, and the file tree's is a `list` call.
  var f = window.fetch;
  window.fetch = function (u) {
    if (String(u).indexOf('action=list&') >= 0 || /action=list$/.test(String(u))) H.lists[name] = (H.lists[name] || 0) + 1;
    return f.apply(this, arguments);
  };
})();
</script>"""
assert s.count('<head>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('<head>', shim, 1))
PY

# The harness: two tabs, and the probe. Reported through document.title. No backslashes in
# here: this lives in a shell heredoc.
cat > "$WIKI_APP/__rt_harness.html" <<'HTML'
<!doctype html><html><head><title>harness</title></head><body>
<script>
window.__rt = { streams: [], live: {}, lists: {}, openDelay: 50 };
const H = window.__rt;
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
// Headless Chrome's virtual clock fast-forwards timers but does not wait for messages
// between frames, so a fixed sleep can end before a BroadcastChannel message is delivered.
// Poll for the expected state in many short steps instead; each one yields to the loop.
const until = async (cond, steps = 300) => { for (let i = 0; i < steps && !cond(); i++) await sleep(20); return cond(); };
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const frames = {};
const open = (name, hidden) => new Promise(res => {
  const f = document.createElement('iframe');
  f.style.width = '900px'; f.style.height = '600px';
  f.src = 'index.php?space=Main&tab=' + name + (hidden ? '&hidden=1' : '');
  f.onload = () => res(f);
  document.body.appendChild(f);
  frames[name] = f;
});
const setHidden = (name, hidden) => {
  const w = frames[name].contentWindow;
  w.__hidden = hidden;
  w.document.dispatchEvent(new Event('visibilitychange'));
};
const openStreams = () => H.streams.filter(s => !s.closed);
const holders = () => openStreams().map(s => s.tab).sort().join('+') || 'none';
const rt = (name) => frames[name].contentWindow.eval("import('./modules/realtime/index.js')");

const run = async () => {
  let out = '';
  await open('A', false);                                   await sleep(2500);
  out += ' first=' + holders();
  await open('B', true);                                    await sleep(2500);
  out += ' second=' + holders() + ' total=' + H.streams.length;
  out += ' Blive=' + H.live.B;

  // An event on A's stream reaches B.
  const mB = await rt('B');
  let gotB = 0; mB.subscribe('wiki/Main/page/X.md', () => gotB++);
  openStreams()[0].deliver('wiki/Main/page/X.md');          await until(() => gotB > 0);
  out += ' relayed=' + gotB;

  // Switch tabs: A goes to the background, B comes forward. The new stream opens slowly,
  // and an event arrives on the old one meanwhile — it must still be delivered.
  H.openDelay = 600;
  const before = { A: H.lists.A || 0, B: H.lists.B || 0 };
  const mA = await rt('A');
  let gotA = 0; mA.subscribe('wiki/Main/page/Y.md', () => gotA++);
  let gotBy = 0; mB.subscribe('wiki/Main/page/Y.md', () => gotBy++);
  const oldA = openStreams().find(s => s.tab === 'A');
  setHidden('A', true); setHidden('B', false);              await sleep(200);
  out += ' during=' + holders();
  // Coming back into view re-reads once (rule 2 — a frozen tab misses channel messages),
  // so count only from here: an event on the old stream while the new one is still opening.
  gotA = 0; gotBy = 0;
  oldA.deliver('wiki/Main/page/Y.md');
  await until(() => holders() === 'B' && gotA > 0 && gotBy > 0);   await sleep(300);
  out += ' after=' + holders();
  out += ' gap=' + gotA + '/' + gotBy;
  out += ' refetch=' + ((H.lists.A || 0) - before.A);
  out += ' Alive=' + H.live.A;
  H.openDelay = 50;

  // A second window beside it: visible too, but B is visible and holds it — no theft.
  setHidden('A', false);                                    await sleep(800);
  out += ' bothVisible=' + holders();

  // Closing the holder hands the stream to a visible tab.
  frames.B.remove();                                        await until(() => holders() === 'A');
  out += ' afterClose=' + holders();
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 500);
</script>
</body></html>
HTML

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && PHP_CLI_SERVER_WORKERS=4 exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/__rt_harness.html" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE.*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'one stream'
assert_contains "the first tab opens the stream"           'first=A '        "$PROBE"
assert_contains "a background tab opens none of its own"   'second=A total=1 ' "$PROBE"
assert_contains "  …and still knows push is live"          'Blive=true'      "$PROBE"
assert_contains "  …and still receives events"             'relayed=1'       "$PROBE"

section 'switching tabs'
assert_contains "the old stream stays until the new opens" 'during=A+B'      "$PROBE"
assert_contains "  …then the active tab holds it alone"    'after=B '        "$PROBE"
assert_contains "no event is lost in the handoff"          'gap=1/1'         "$PROBE"
assert_contains "  …so the background tab refetches nothing" 'refetch=0 '   "$PROBE"
assert_contains "the background tab stays live"            'Alive=true'      "$PROBE"

section 'two visible tabs, and closing one'
assert_contains "a second visible tab does not steal it"   'bothVisible=B '  "$PROBE"
assert_contains "closing the holder hands it on"           'afterClose=A'    "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
