#
# Space settings → Advanced → "Use these settings elsewhere", in the browser.
#
# tests/space_settings_copy.test.sh holds the server side. What it cannot see is the
# dialog: that the defaults line tells the truth and follows a change, that the copy
# preview is re-planned as boxes are ticked and only arms on a plan that changes
# something, that the shared confirm button is handed back, and that the New Space
# dialog really starts from the defaults.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Src; fixture_space Alpha; fixture_space Beta
fixture_page 'Src/Src.md'     'Src start'
fixture_page 'Alpha/Alpha.md' 'Alpha start'
fixture_page 'Beta/Beta.md'   'Beta start'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
api() { curl -s -X POST -d "$2" "$WIKI_URL/api.php?action=$1" > /dev/null; }
api admin_set_space_fm_edit      'space_name=Src&mode=manual'
api admin_set_space_fm_autostamp 'space_name=Src&mode=on'
api admin_set_space_memory       'space_name=Src&memory=1'

rec() {
    python3 -c 'import json,sys
try: d=json.load(open(sys.argv[1]))
except Exception: d={}
print(json.dumps(d.get(sys.argv[2],{}),sort_keys=True,separators=(",",":")))' "$WIKI_SYS/spaces.json" "$1"
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/space_settings_copy_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
const tick = (sel, on) => { const b = $(sel); b.checked = on; b.dispatchEvent(new Event('change', { bubbles: true })); };
const plan = () => [...document.querySelectorAll('#space-copy-preview li')].map(li => li.textContent.split(':')[0]).join(',');

setTimeout(async () => {
  let out = ' start=' + state.currentSpace;
  try {
    $('#space-settings-btn').click();             await sleep(1500);
    $('#space-settings-modal .admin-tab[data-tab="advanced"]').click(); await sleep(200);
    const status = $('#space-defaults-status'), defBtn = $('#space-defaults-btn');
    out += ' statusDiffers=' + /Page metadata: Read-only/.test(status.textContent)
        + ' defEnabled=' + !defBtn.disabled;
    // The Advanced pane gained a section: Close must still be on screen.
    const closeR = $('#space-settings-modal .lightbox-footer .btn').getBoundingClientRect();
    out += ' closeVisible=' + (closeR.bottom <= innerHeight && closeR.top >= 0);
    // The share section comes before merge and delete.
    const titles = [...document.querySelectorAll('#space-settings-modal .space-settings-pane:not(.hidden) .space-settings-title')].map(e => e.textContent);
    out += ' firstSection=' + (titles[0] === 'Use these settings elsewhere');

    defBtn.click();                               await sleep(800);
    out += ' statusSame=' + (status.textContent === 'New spaces start with these settings.')
        + ' defDisabled=' + defBtn.disabled;

    // A change in the Content tab makes the line say so again, without reopening.
    const stamp = $('#space-fm-stamp'); stamp.value = 'off'; stamp.dispatchEvent(new Event('change'));
    await sleep(800);
    out += ' followsChange=' + (/Stamp dates and authors: On/.test(status.textContent) && !defBtn.disabled);
    stamp.value = 'on'; stamp.dispatchEvent(new Event('change'));  await sleep(800);

    $('#space-copy-btn').click();                 await sleep(1200);
    const ok = $('#confirm-modal-ok');
    out += ' planAll=' + plan() + ' okArmed=' + !ok.disabled + ' okLabel=[' + ok.textContent + ']';
    tick('.space-copy-target[value="Beta"]', false);  await sleep(800);
    out += ' planAlpha=' + plan();
    tick('.space-copy-group[value="content"]', false);
    tick('.space-copy-group[value="ai"]', false);     await sleep(500);
    out += ' noGroupArmed=' + !ok.disabled + ' noGroupMsg=[' + $('#space-copy-preview').textContent + ']';
    tick('.space-copy-group[value="content"]', true); await sleep(800);
    out += ' contentArmed=' + !ok.disabled;
    ok.click();                                   await sleep(1500);
    out += ' okReset=' + !ok.disabled;

    $('#space-settings-modal .lightbox-footer .btn').click(); await sleep(300);
    $('.space-switcher-header').click();          await sleep(200);
    $('.space-dropdown-new').click();             await sleep(400);
    out += ' newFm=' + $('#new-space-fm').value + ' newStamp=' + $('#new-space-stamp').value
        + ' newTags=' + $('#new-space-fmtags').value + ' newMem=' + $('#new-space-memory').checked
        + ' newSkills=' + ($('#new-space-skills') ? $('#new-space-skills').checked : 'absent');
    const okR = $('#confirm-modal-ok').getBoundingClientRect();
    out += ' createVisible=' + (okR.bottom <= innerHeight);
    $('#new-space-name').value = 'Made';
    $('#confirm-modal-ok').click();               await sleep(2000);
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php?space=Src" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"
assert_contains "the dialog opened on Src"                  'start=Src'           "$PROBE"

section 'the Advanced tab'
assert_contains "the new section comes before merge and delete" 'firstSection=true' "$PROBE"
assert_contains "Close is still on screen"                  'closeVisible=true'   "$PROBE"

section 'defaults for new Spaces'
assert_contains "the line says the defaults differ, and how" 'statusDiffers=true' "$PROBE"
assert_contains "  and the button is offered"               'defEnabled=true'     "$PROBE"
assert_contains "after making them the defaults it says they match" 'statusSame=true' "$PROBE"
assert_contains "  and the button has nothing left to do"   'defDisabled=true'    "$PROBE"
assert_contains "a change in the Content tab is reflected at once" 'followsChange=true' "$PROBE"

section 'copy to other Spaces'
assert_contains "the preview plans every other Space"       'planAll=Alpha,Beta'  "$PROBE"
assert_contains "  and arms the button"                     'okArmed=true'        "$PROBE"
assert_contains "  which says how many it changes"          'okLabel=[Apply to 2 space(s)]' "$PROBE"
assert_contains "unticking Beta re-plans without it"        'planAlpha=Alpha '    "$PROBE"
assert_contains "no group chosen disarms it"                'noGroupArmed=false'  "$PROBE"
assert_contains "  and says why"                            'noGroupMsg=[Choose what to copy.]' "$PROBE"
assert_contains "Content alone arms it again"               'contentArmed=true'   "$PROBE"
assert_contains "the shared button is handed back enabled"  'okReset=true'        "$PROBE"
assert_eq       "Alpha got the Content settings only"       '{"fm_autostamp":"on","fm_edit":"manual"}' "$(rec Alpha)"
assert_eq       "Beta, unticked, is untouched"              '{}' "$(rec Beta)"

section 'the New Space dialog'
assert_contains "starts from the default metadata mode"     'newFm=manual'        "$PROBE"
assert_contains "  stamping"                                'newStamp=on'         "$PROBE"
assert_contains "  tags in front matter"                    'newTags=off'         "$PROBE"
assert_contains "  memory"                                  'newMem=true'         "$PROBE"
assert_contains "  and offers an admin the skills setting"  'newSkills=false'     "$PROBE"
assert_contains "Create is still on screen"                 'createVisible=true'  "$PROBE"
assert_eq       "the Space it made has the defaults"        '{"fm_autostamp":"on","fm_edit":"manual","memory":true}' "$(rec Made)"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
