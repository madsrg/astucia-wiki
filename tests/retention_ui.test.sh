# Admin → Content → Retention policies in a browser.
#
# tests/retention.test.sh proves what the settings do; this proves the tab can set them.
# It replaced two tabs (Chat Retention, Mentions), so the old ones must be gone and their
# settings still reachable here — a field drawn but never read back on Save is exactly the
# failure nothing over HTTP can see. Also: the "would be deleted" preview follows the number
# as it is typed, and Clean up now asks, then deletes.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
LOGS=$WIKI_ROOT/logs; mkdir -p "$LOGS"
printf 'old\n' > "$LOGS/2020-01-01_access.log"
printf 'new\n' > "$LOGS/$(date +%F)_access.log"

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/retention_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const get = async (a) => (await fetch('api.php?action=' + a)).json();
const report = (out) => { document.title = 'PROBE' + out; };

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  let out = '';
  click($('#admin-btn'));                                     await sleep(800);
  click($('.admin-group[data-group="content"]'));             await sleep(500);
  out += ' oldtabs=' + document.querySelectorAll('.admin-tab[data-tab="chatpolicy"], .admin-tab[data-tab="mentions"]').length;
  const tab = $('.admin-tab[data-tab="retention"]');
  out += ' tab=' + (tab && !tab.classList.contains('hidden') ? 'shown' : 'missing');
  click(tab);                                                 await sleep(1200);
  out += ' chatopts=' + ($('#admin-chat-retention') ? $('#admin-chat-retention').options.length : 0);
  out += ' mention=' + ($('#admin-mention-days') ? $('#admin-mention-days').value : '');
  out += ' logrows=' + document.querySelectorAll('[id^="admin-ret-usage-"]').length;
  out += ' access=' + $('#admin-ret-access_log_days').value;
  out += ' forever=' + ($('#admin-ret-usage-access_log').textContent.includes('Kept forever') ? 'yes' : 'no');

  // The preview follows the number as typed, before anything is saved.
  const acc = $('#admin-ret-access_log_days');
  acc.value = '30'; acc.dispatchEvent(new Event('input'));    await sleep(1000);
  out += ' preview=' + ($('#admin-ret-usage-access_log .admin-retention-warn') ? 'warns' : 'silent');
  out += ' unsaved=' + (await get('admin_retention_settings')).settings.access_log_days;

  // One Save writes all four kinds.
  $('#admin-chat-retention').value = 'count:100';
  $('#admin-mention-days').value = '45';
  $('#admin-ret-workflow_history_days').value = '21';
  click($('#admin-retention-save'));                          await sleep(1500);
  const s = (await get('admin_retention_settings')).settings;
  out += ' saved=' + s.access_log_days + '/' + s.workflow_history_days;
  out += ' chat=' + (await get('admin_chat_retention')).policy;
  out += ' mentions=' + (await get('admin_mention_settings')).days;

  // Clean up now asks first, then deletes.
  click($('#admin-retention-clean'));                         await sleep(1000);
  const modal = $('#confirm-modal');
  out += ' asked=' + (modal && !modal.classList.contains('hidden') ? 'yes' : 'no');
  out += ' askcount=' + (($('#confirm-modal-message').textContent.match(/delete (\\d+) files/) || [])[1] || '?');
  click($('#confirm-modal-ok'));                              await sleep(2000);
  out += ' after=' + (await get('admin_retention_settings')).scan.access_log.files;
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'one tab instead of two'
assert_contains "Chat Retention and Mentions are gone"   'oldtabs=0'   "$PROBE"
assert_contains "Retention Policies is under Content"    'tab=shown'   "$PROBE"
assert_contains "  …with the chat policies"              'chatopts=7'  "$PROBE"
assert_contains "  …the mention window, at its default"  'mention=90'  "$PROBE"
assert_contains "  …a row per log"                       'logrows=5'   "$PROBE"
assert_contains "  …each kept forever to begin with"     'access=0 forever=yes' "$PROBE"

section 'the preview'
assert_contains "a limit shows what it would delete"     'preview=warns' "$PROBE"
assert_contains "  …without saving it"                   'unsaved=0'     "$PROBE"

section 'one Save writes everything'
assert_contains "the log limit and the history window"   'saved=30/21'      "$PROBE"
assert_contains "the chat default"                       'chat=count:100'   "$PROBE"
assert_contains "the mention window"                     'mentions=45'      "$PROBE"

section 'Clean up now'
assert_contains "asks first"                             'asked=yes'   "$PROBE"
assert_contains "  …saying how many files"               'askcount=1'  "$PROBE"
assert_contains "  …then deletes the old one, keeps today's" 'after=1' "$PROBE"
assert_file_missing "the old access log is gone"         "$LOGS/2020-01-01_access.log"
assert_file_exists  "today's is still there"             "$LOGS/$(date +%F)_access.log"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
