# Deleting a Space, in the browser: the typed-name confirmation and where you land.
#
# tests/space_delete.test.sh holds the server side. What it cannot see is the dialog — that
# the Delete button stays dead until the name is typed exactly, that the shared confirm
# dialog is handed back with its button re-enabled for the next caller, and that the open
# space moves to the first remaining one. Also measures the New Space dialog's width.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Alpha; fixture_space Zulu
fixture_page 'Alpha/Alpha.md' 'Alpha start'
fixture_page 'Zulu/Zulu.md'   'Zulu start'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/space_delete_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
const type = (el, v) => { el.value = v; el.dispatchEvent(new Event('input')); };

setTimeout(async () => {
  let out = ' start=' + state.currentSpace;
  try {
    // New Space dialog width.
    $('.space-switcher-header').click();          await sleep(200);
    $('.space-dropdown-new').click();             await sleep(400);
    out += ' newW=' + Math.round($('#confirm-modal .input-modal-content').getBoundingClientRect().width);
    $('#confirm-modal-cancel').click();           await sleep(300);

    $('#space-settings-btn').click();             await sleep(1500);
    $('#space-settings-modal .admin-tab[data-tab="advanced"]').click(); await sleep(200);
    const btns = [...document.querySelectorAll('#space-settings-modal .space-settings-pane:not(.hidden) .btn-danger')];
    const delBtn = btns[btns.length - 1];
    out += ' delEnabled=' + !delBtn.disabled;
    delBtn.click();                               await sleep(500);
    const ok = $('#confirm-modal-ok'), input = $('#space-delete-confirm');
    out += ' armedAtOpen=' + !ok.disabled;
    type(input, 'zulu');  out += ' armedWrongCase=' + !ok.disabled;
    type(input, 'Zul');   out += ' armedPrefix=' + !ok.disabled;
    type(input, 'Zulu');  out += ' armedExact=' + !ok.disabled;
    ok.click();                                   await sleep(3000);
    out += ' now=' + state.currentSpace
        + ' label=' + ($('#space-current-label') || {}).textContent
        + ' listed=' + [...document.querySelectorAll('.space-dropdown-item[data-space]')].map(e => e.dataset.space).join(',')
        + ' url=' + new URL(location.href).searchParams.get('space')
        + ' okReset=' + !ok.disabled
        + ' stored=' + localStorage.getItem('wiki_currentSpace');
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -sf --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php?space=Zulu" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the New Space dialog'
# Rendered width: max-width 640 plus the content-box padding (44). It was 480 (524 rendered)
# until the dialog gained a fourth setting; tests/frontmatter_ui.test.sh checks why.
assert_contains "is wide enough for its four settings" 'newW=684'            "$PROBE"

section 'the typed-name confirmation'
assert_contains "the space opened is the one deleted" 'start=Zulu'      "$PROBE"
assert_contains "Delete is offered"               'delEnabled=true'     "$PROBE"
assert_contains "the button is dead when it opens" 'armedAtOpen=false'  "$PROBE"
assert_contains "  …and on the wrong case"        'armedWrongCase=false' "$PROBE"
assert_contains "  …and on a prefix"              'armedPrefix=false'   "$PROBE"
assert_contains "  …and arms on the exact name"   'armedExact=true'     "$PROBE"
assert_contains "the shared dialog's button is handed back enabled" 'okReset=true' "$PROBE"

section 'afterwards'
assert_contains "the first remaining space is open" 'now=Alpha'         "$PROBE"
assert_contains "  …and named in the switcher"    'label=Alpha'         "$PROBE"
assert_contains "  …and in the URL"               'url=Alpha'           "$PROBE"
assert_contains "  …and remembered"               'stored=Alpha'        "$PROBE"
assert_contains "the deleted one is not listed"   'listed=Alpha '       "$PROBE"
assert_file_missing "it left PAGES_DIR"           "$WIKI_PAGES/Zulu"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
