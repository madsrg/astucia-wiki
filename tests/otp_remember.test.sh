# OTP "Keep me signed in" (remember_me.php).
#
# An email-code user used to need a new code every time the PHP session went — idle
# timeout, GC, a browser restart. The remember cookie rebuilds the session instead. What
# has to hold: it survives losing the session and passing SESSION_TIMEOUT, it is only
# issued when asked for, logout really ends it, and an account that is removed or given
# another login address cannot be signed back into by a token it held before.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

fixture_start otp || exit 1
trap fixture_stop EXIT

fixture_users '{"users":[
  {"uid":1,"name":"Admin","email":"admin@example.com","role":"admin","auth":"otp"},
  {"uid":2,"name":"Olga","email":"olga@example.com","role":"editor","auth":"otp"}
]}'

# The code arrives by email, which the fixture has none of. This shim plants a pending
# code exactly as otp_send does, so otp_verify — the code under test — runs unmodified.
# It also ages a session, to stand in for an hour of idleness.
cat > "$WIKI_APP/__test_otp.php" <<'SHIM'
<?php
// GENERATED BY tests/otp_remember.test.sh — never part of a release.
session_start();
if (isset($_GET['age'])) { $_SESSION['last_activity'] = time() - 999999; echo 'aged'; exit; }
$_SESSION['otp_pending'] = [
    'email' => $_GET['email'], 'code' => password_hash('123456', PASSWORD_DEFAULT),
    'expires' => time() + 600, 'attempts' => 0,
];
echo 'ok';
SHIM

TOKENS=$WIKI_SYS/remember_tokens.json

# otp_login <jar> <email> [remember]
otp_login() {
    rm -f "$1"
    get_as "$1" "__test_otp.php?email=$2" > /dev/null
    local data="code=123456"; [ -n "${3:-}" ] && data="$data&remember=1"
    post_as "$1" "auth.php?action=otp_verify" "$data" > /dev/null
}
# Who index.php thinks is signed in: 0 is anonymous (the template allows anonymous
# reading, so a bare API call succeeding proves nothing).
whoami() { get_as "$1" 'index.php' | command grep -o 'data-user-uid="[0-9]*"' | command grep -o '[0-9]*'; }
has_remember() { command grep -q 'wiki_remember' "$1" 2>/dev/null; }
# Keep only the remember cookie: the browser after its session cookie is gone.
only_remember() { command grep -v 'PHPSESSID' "$1" > "$2"; }

section "issuing"
J=$WIKI_ROOT/jar-plain; otp_login "$J" olga@example.com
assert_eq       "a code login without the box signs in"        2 "$(whoami "$J")"
has_remember "$J" && _fail "no remember cookie unless asked for" || _pass "no remember cookie unless asked for"

J=$WIKI_ROOT/jar-olga; otp_login "$J" olga@example.com remember
has_remember "$J" && _pass "ticking the box sets the cookie" || _fail "ticking the box sets the cookie"
assert_not_contains "only the hash of the validator is stored" "$(command grep wiki_remember "$J" | awk '{print $7}' | cut -d. -f2)" "$(cat "$TOKENS")"
assert_contains "index.php turns the client idle timer off"   'WIKI_SESSION_TIMEOUT = 0;' "$(get_as "$J" 'index.php')"

section "surviving"
B=$WIKI_ROOT/jar-olga-nosession; only_remember "$J" "$B"
C=$WIKI_ROOT/jar-nobody;         only_remember "$WIKI_ROOT/jar-plain" "$C"
assert_eq       "positive control: no cookie, no session → anonymous" 0 "$(whoami "$C")"
assert_eq       "lost session is rebuilt from the cookie"      2 "$(whoami "$B")"
G=$WIKI_ROOT/jar-olga-getfile; only_remember "$J" "$G"
assert_eq       "positive control: getfile.php refuses no session" 401 "$(status_as "$C" 'getfile.php?path=nope.txt')"
assert_eq       "getfile.php also restores (403/404, not 401)" ok "$(s=$(status_as "$G" 'getfile.php?path=nope.txt'); [ "$s" != 401 ] && echo ok || echo "$s")"

get_as "$J" '__test_otp.php?age=1' > /dev/null
assert_contains "an idle-expired session is renewed, not ended" '"success":true' "$(get_as "$J" 'api.php?action=ping')"
P=$WIKI_ROOT/jar-plain; get_as "$P" '__test_otp.php?age=1' > /dev/null
assert_contains "positive control: idle without cookie still expires" 'session_expired' "$(get_as "$P" 'api.php?action=ping')"

B=$WIKI_ROOT/jar-forged; only_remember "$J" "$B"; sed -i 's/\(wiki_remember[[:space:]]*[0-9a-f]*\.\)[0-9a-f]*/\1deadbeef/' "$B"
command grep -q 'deadbeef' "$B" && _pass "(the forgery took)" || _fail "(the forgery took)"
assert_eq       "a forged validator is refused"                0 "$(whoami "$B")"

section "ending"
only_remember "$J" "$WIKI_ROOT/jar-stolen"
get_as "$J" 'auth.php?action=logout' > /dev/null
has_remember "$J" && _fail "logout clears the cookie" || _pass "logout clears the cookie"
assert_eq       "logout revokes the token server-side"         0 "$(whoami "$WIKI_ROOT/jar-stolen")"

J=$WIKI_ROOT/jar-olga2; otp_login "$J" olga@example.com remember
only_remember "$J" "$WIKI_ROOT/jar-olga2-copy"; only_remember "$J" "$WIKI_ROOT/jar-olga2-control"
assert_eq       "positive control: the copied cookie works before the change" 2 "$(whoami "$WIKI_ROOT/jar-olga2-control")"
A=$WIKI_ROOT/jar-admin; otp_login "$A" admin@example.com
post_as "$A" 'api.php?action=admin_save_users' \
  'users=[{"uid":1,"name":"Admin","email":"admin@example.com","role":"admin","auth":"otp"},{"uid":2,"name":"Olga","email":"someone-else@example.com","role":"editor","auth":"otp"}]' > /dev/null
assert_eq       "a changed login address revokes the account's tokens" 0 "$(whoami "$WIKI_ROOT/jar-olga2-copy")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
