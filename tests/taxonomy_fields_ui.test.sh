# Front-matter fields bound to the taxonomy, in the browser: the Metadata panel offers a
# bound field as a dropdown of its branch (a multi-select where it takes several), keeps
# and flags a value from outside it, and turns an added bound field into a dropdown too;
# the admin editor shows the binding on the tree and edits it in the details panel.
#
# tests/taxonomy_fields.test.sh holds the server's rules.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
fixture_page 'Main/Notes.md' '---
department: Ghost
owner: me
---
# Notes'
printf '{"Main":{"fm_edit":"manual"}}' > "$WIKI_SYS/spaces.json"
cat > "$WIKI_PAGES/taxonomy.json" <<'JSON'
{"version":1,"nodes":[
  {"name":"Department","heading":true,"field":"department","children":[{"name":"Finance"},{"name":"HR"}]},
  {"name":"Audience","heading":true,"field":"audience","multiple":true,"children":[{"name":"Staff"},{"name":"Managers"}]},
  {"name":"Review","heading":true,"field":"review"}
]}
JSON
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
page_id() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' \
        "$WIKI_PAGES/${2:-Main}/index.json" "$1"
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/taxonomy_fields_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection', e => {
    document.title = 'PROBE fatalRejection=' + (e.reason && e.reason.message || e.reason); });
const row = (p) => $$('#admin-tax-tree .tax-row').find(r => r.dataset.path === p);

setTimeout(async () => {
  let out = '';
  try {
    $('#frontmatter-badge').click();               await sleep(800);
    const dep = $('.fm-select[data-key=department]');
    out += ' depSelect=' + !!dep
        + ' depOptions=' + (dep ? [...dep.options].map(o => o.textContent).join('|') : '')
        + ' depValue=' + (dep ? dep.value : '')
        + ' ownerText=' + ($('input.fm-input[data-key=owner]') ? 'yes' : 'no');
    // The add row lines up: the field chooser and the value box share a top and a bottom.
    const pr = $('#fm-new-pick').closest('.dd').querySelector('.dd-btn').getBoundingClientRect();
    const vr = $('#fm-new-val').getBoundingClientRect();
    out += ' rowAligned=' + (Math.abs(pr.top - vr.top) < 1 && Math.abs(pr.bottom - vr.bottom) < 1);
    // Dressed as the Space Selector: a box showing the value, a menu of rows.
    const depBtn = $('.dd-btn[data-key=department]');
    out += ' ddLabel=' + JSON.stringify(depBtn.querySelector('.dd-label').textContent);
    depBtn.click();                                await sleep(150);
    out += ' menu=' + $$('.dd-menu .dd-item').map(x => x.textContent).join('|');
    // Escape closes the menu and nothing else.
    document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }));
    await sleep(150);
    out += ' escMenu=' + !$('.dd-menu') + ' dialogStill=' + !$('#confirm-modal').classList.contains('hidden');
    depBtn.click();                                await sleep(150);
    $$('.dd-menu .dd-item').find(x => x.textContent === 'Finance').click(); await sleep(150);
    out += ' picked=' + depBtn.querySelector('.dd-label').textContent + '/' + dep.value;

    // The field chooser: bound fields, then "Other field…".
    const pickBtn = $('#fm-new-pick').closest('.dd').querySelector('.dd-btn');
    out += ' pickLabel=' + JSON.stringify(pickBtn.textContent);
    pickBtn.click();                               await sleep(150);
    out += ' pickMenu=' + $$('.dd-menu .dd-item').map(x => x.textContent).join('|');
    $$('.dd-menu .dd-item').find(x => x.textContent === 'review').click(); await sleep(150);
    out += ' emptyNote=' + !!$('#fm-new-valcell .fm-tax-note.is-empty');
    pickBtn.click();                               await sleep(150);
    $$('.dd-menu .dd-item').find(x => x.textContent.startsWith('Other')).click(); await sleep(150);
    out += ' otherBox=' + !$('#fm-new-key').classList.contains('hidden');
    // A bound field that takes several: its value box is the field's own dropdown at once.
    pickBtn.click();                               await sleep(150);
    $$('.dd-menu .dd-item').find(x => x.textContent === 'audience').click(); await sleep(150);
    const valBtn = $('#fm-new-valcell .dd-btn');
    out += ' valIsDropdown=' + !!valBtn;
    valBtn.click();                                await sleep(150);
    $$('.dd-menu .dd-item').find(x => x.textContent === 'Staff').click(); await sleep(100);
    $$('.dd-menu .dd-item').find(x => x.textContent === 'Managers').click(); await sleep(100);
    out += ' multiStaysOpen=' + !!$('.dd-menu') + ' valLabel=' + JSON.stringify(valBtn.querySelector('.dd-label').textContent);
    document.body.click();                         await sleep(100);
    $('#fm-add-btn').click();                      await sleep(200);
    const aud = $('.fm-select[data-key=audience]');
    out += ' audMulti=' + !!(aud && aud.multiple) + ' audCarried=' + (aud ? [...aud.selectedOptions].map(o => o.value).join('+') : '');
    out += ' pickedGone=' + !$$('#fm-new-pick option').some(o => o.value === 'audience');
    $('#confirm-modal-ok').click();                await sleep(1500);
    out += ' saved=' + JSON.stringify(state.currentPageFrontmatter);

    // Reopen: the value is valid now, so nothing is flagged.
    $('#frontmatter-badge').click();               await sleep(800);
    out += ' flagged=' + $$('#confirm-modal-message .fm-not-in-tax').length
        + ' depAfter=' + $('.fm-select[data-key=department]').value;
    $('#confirm-modal-cancel').click();            await sleep(300);

    // The editor shows and edits the binding.
    $('#admin-btn').click();                       await sleep(800);
    $('.admin-group[data-group=content]').click(); await sleep(200);
    $('.admin-tab[data-tab=taxonomy]').click();    await sleep(1500);
    $('#tax-launch').click();                      await sleep(500);
    out += ' chip=' + ((row('Department').querySelector('.tax-field-chip') || {}).textContent || 'none');
    row('Department/Finance').click();             await sleep(300);
    out += ' valueUse=' + JSON.stringify($$('#admin-tax-details .tax-usage').map(p => p.textContent).join(' / '));
    // Only a folder can be bound, so an item has no field section…
    out += ' itemField=' + ($('#tax-d-field').closest('.form-group').classList.contains('hidden') ? 'hidden' : 'shown');
    out += ' delOff=' + $('#tax-tb-delete').disabled;
    row('Department').click();                     await sleep(300);
    out += ' fieldIn=' + $('#tax-d-field').value;
    // …and a bound folder cannot be turned into an item.
    out += ' itemRadioOff=' + $$('input[name=tax-d-type]').find(r => r.value === 'item').disabled;
    $('#tax-d-field').value = 'dept'; $('#tax-d-field').dispatchEvent(new Event('input'));
    $('#tax-d-save').click();                      await sleep(1500);
    out += ' chipAfter=' + ((row('Department').querySelector('.tax-field-chip') || {}).textContent || 'none');
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  document.title = 'PROBE' + out;
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

load() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=60000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "page $1"
}

load Notes.md
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the Metadata panel'
assert_contains "a bound field is a dropdown"        'depSelect=true'    "$PROBE"
assert_contains "  of its branch, with a value outside it kept and flagged" \
                'depOptions=—|Finance|HR|Ghost (not in the taxonomy)' "$PROBE"
assert_contains "  and still selected"               'depValue=Ghost'    "$PROBE"

section 'dressed as the Space Selector'
assert_contains "the add row's chooser lines up with its value box" 'rowAligned=true' "$PROBE"
assert_contains "the box shows the value, not a hint" 'ddLabel="Ghost (not in the taxonomy)"' "$PROBE"
assert_contains "its menu lists the choices"         'menu=—|Finance|HR|Ghost (not in the taxonomy)' "$PROBE"
assert_contains "Escape closes the menu"             'escMenu=true'      "$PROBE"
assert_contains "  and not the dialog"               'dialogStill=true'  "$PROBE"
assert_contains "a row in the menu sets the value"   'picked=Finance/Finance' "$PROBE"
assert_contains "the field chooser says what it is"  'pickLabel="Choose a field…"' "$PROBE"
assert_contains "  and lists the bound fields the page lacks, then Other" 'pickMenu=audience|review|Other field…' "$PROBE"
assert_contains "a field whose folder is empty says so" 'emptyNote=true' "$PROBE"
assert_contains "Other field… reveals the name box"  'otherBox=true'     "$PROBE"
assert_contains "a bound field's value box is its dropdown at once" 'valIsDropdown=true' "$PROBE"
assert_contains "  which stays open to pick several" 'multiStaysOpen=true' "$PROBE"
assert_contains "  and shows them"                   'valLabel="Staff, Managers"' "$PROBE"
assert_contains "Add carries the chosen values"      'audCarried=Staff+Managers' "$PROBE"
assert_contains "  and the chooser stops offering that field" 'pickedGone=true' "$PROBE"
assert_contains "a field that is not bound stays a text box" 'ownerText=yes' "$PROBE"
assert_contains "an added bound field that takes several is a multi-select" 'audMulti=true' "$PROBE"
assert_contains "saving writes both"                 '"department":"Finance"' "$PROBE"
assert_contains "  the list as a list"               '"audience":["Staff","Managers"]' "$PROBE"
assert_contains "a valid value is not flagged"       'flagged=0'         "$PROBE"
assert_contains "  and reopens selected"             'depAfter=Finance'  "$PROBE"
assert_contains "the file has them"                  'department: Finance' "$(cat "$WIKI_PAGES/Main/Notes.md")"

section 'the editor'
assert_contains "the bound folder shows its field"   'chip=department:'  "$PROBE"
assert_contains "a value shows where it is used"     'Used as department: Finance on 1 page(s).' "$PROBE"
assert_contains "  and cannot be deleted while it is" 'delOff=true'      "$PROBE"
assert_contains "the details panel shows the binding" 'fieldIn=department' "$PROBE"
assert_contains "an item has no field section"       'itemField=hidden' "$PROBE"
assert_contains "a bound folder cannot become an item" 'itemRadioOff=true' "$PROBE"
assert_contains "  and changes it"                   'chipAfter=dept:'   "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
