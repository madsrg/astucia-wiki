# A page whose front matter says `format: html` (modules/page_view isHtmlFormat): its body is
# shown as the HTML it is — indented markup with blank lines in it, which Markdown would turn
# into code blocks, stays markup — and the wiki's Markdown-only tag passes leave it alone,
# while {filename} still applies. It is edited in the classic editor whatever the stored
# preference, which is left as it was; the inline/classic switch is not offered. A page
# generator's Preview shows an HTML template's output as HTML.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
cat > "$WIKI_PAGES/Main/Card.md" <<'EOF'
---
format: html
---
<style>
h1, .file-item-name { color: rgb(200, 0, 0); }
body { background-color: rgb(1, 2, 3); }
@media (min-width: 1px) { .probe-card h2 { color: rgb(0, 128, 0); } }
</style>
<h1>Card title</h1>
<div class="probe-card">

    <h2>Card for {filename}</h2>

    <p>Not a wikilink: [[Main]] and not an include: {include:1}</p>

</div>
EOF
cat > "$WIKI_PAGES/Main/Plain.md" <<'EOF'
<style>.plain-probe { color: rgb(0, 0, 255); }</style>

# Plain

    four spaces make code in Markdown
EOF
cat > "$WIKI_PAGES/Main/People.list" <<'JSON'
{"columns":[{"id":"col_2","name":"Name","type":"text_single","role":"title"},{"id":"col_3","name":"Site","type":"text_single"}],
 "items":[{"id":1,"col_2":"<b>Ann</b>","col_3":"javascript:alert(1)"}],"nextItemId":2}
JSON
# Archived pages, written by hand: one per reason, and one from before reasons were recorded.
printf -- '---\narchived_from: 99998\narchived_row: 4\narchived_reason: row_removed\narchived_list: Customers\n---\n# Row gone\n' > "$WIKI_PAGES/Main/ArchRow.md"
printf -- '---\narchived_from: 99998\narchived_row: 5\narchived_reason: template_gone\n---\n# Template gone\n' > "$WIKI_PAGES/Main/ArchTpl.md"
printf -- '---\narchived_from: 99998\narchived_row: 6\n---\n# Old archive\n' > "$WIKI_PAGES/Main/ArchOld.md"
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
id_of() { python3 -c 'import json,sys;ix=json.load(open(sys.argv[1]));print(next(k for k,v in ix.items() if v["path"]==sys.argv[2]))' "$WIKI_PAGES/Main/index.json" "$1"; }
PEOPLE=$(id_of People.list)
mkdir -p "$WIKI_PAGES/Main/templates"
cat > "$WIKI_PAGES/Main/templates/Person.md" <<EOF
---
format: html
generator_source: $PEOPLE
generator_folder: People
---
<style>h3 { color: rgb(200, 0, 0); }</style>
<div class="probe-person">
  <h3>{{name}}</h3>
  <a class="probe-site" href="{{site}}">site</a>
</div>
EOF
cat > "$WIKI_PAGES/Main/templates/Bad.md" <<EOF
---
format: html
generator_source: $PEOPLE
generator_folder: Bad
---
<p onclick="{{name}}">x</p>
EOF
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
CARD=$(id_of Card.md); PLAIN=$(id_of Plain.md); TPL=$(id_of templates/Person.md); BAD=$(id_of templates/Bad.md)
curl -s -X POST -d "id=$BAD" "$WIKI_URL/api.php?action=generator_render&space=Main" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/html_pages_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

ARCH="$(id_of ArchRow.md),$(id_of ArchTpl.md),$(id_of ArchOld.md)"
python3 - "$WIKI_APP/index.php" "$PLAIN" "$TPL" "$BAD" "$ARCH" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script>window.PLAIN = %s; window.TPL = %s; window.BAD = %s; window.ARCH = [%s]; localStorage.setItem('wiki_editMode', 'inline');</script><script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const shown = (el) => !!el && !el.classList.contains('hidden') && getComputedStyle(el).display !== 'none';
const w = (s) => String(s).trim().replace(/ +/g, '_');
let out = '';
window.addEventListener('error', e => report(out + ' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(out + ' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  const { state } = await import('./modules/core/state.js');
  const vc = $('#viewer-content');
  // The start URL opened Card.md.
  out += ' card=' + (vc.querySelector('.probe-card h2') ? 'html' : 'no');
  out += ' noCode=' + (vc.querySelector('pre, code') ? 'no' : 'yes');
  out += ' filename=' + w((vc.querySelector('.probe-card h2') || {}).textContent || '');
  out += ' tagsLeft=' + (vc.textContent.includes('[[Main]]') && vc.textContent.includes('{include:1}') ? 'yes' : 'no');
  // The page's own <style> reaches the page and nothing else.
  const col = (el) => el ? getComputedStyle(el).color : 'none';
  out += ' pageH1=' + col(vc.querySelector('h1')).replace(/ /g, '');
  out += ' sidebarItem=' + col($('.file-item-name')).replace(/ /g, '');
  out += ' pageBody=' + getComputedStyle(vc).backgroundColor.replace(/ /g, '');
  out += ' windowBody=' + getComputedStyle(document.body).backgroundColor.replace(/ /g, '');
  out += ' mediaRule=' + col(vc.querySelector('.probe-card h2')).replace(/ /g, '');
  out += ' scoped=' + (vc.querySelector('style[data-scoped]') ? 'yes' : 'no');
  out += ' switchHidden=' + (shown($('#editor-mode-group')) ? 'no' : 'yes');
  out += ' modeBefore=' + state.editMode;
  click($('#edit-btn'));                                   await sleep(600);
  // offsetParent, not the element's own class: in inline mode it is the wrapper that is hidden.
  out += ' editor=' + ($('#editor-container').offsetParent !== null ? 'classic' : 'other');
  out += ' modeWhile=' + state.editMode;
  out += ' source=' + ($('#editor-container').value.includes('<div class="probe-card">') ? 'html' : 'no');

  click($('#cancel-btn'));                                 await sleep(600);
  out += ' modeAfter=' + state.editMode + ',' + localStorage.getItem('wiki_editMode');

  const { loadPage } = await import('./modules/page_view/index.js');
  await loadPage('Plain.md', window.PLAIN, []);           await sleep(1200);
  out += ' plain=' + (vc.querySelector('h1') && vc.querySelector('pre code') ? 'markdown' : 'no');
  out += ' plainSwitch=' + (shown($('#editor-mode-group')) ? 'shown' : 'hidden');
  out += ' plainStyleUntouched=' + (vc.querySelector('style') && !vc.querySelector('style[data-scoped]') && vc.querySelector('style').textContent.includes('.plain-probe {') ? 'yes' : 'no');

  await loadPage('templates/Person.md', window.TPL, []);  await sleep(1500);
  out += ' tplShown=' + (vc.querySelector('.probe-person h3') ? 'html' : 'no');
  out += ' tplPlaceholders=' + w((vc.querySelector('.probe-person h3') || {}).textContent || '');
  click($('#generator-banner [data-gen=preview]'));        await sleep(1500);
  const pv = $('.generator-dialog .generator-preview');
  out += ' preview=' + (pv && pv.querySelector('.probe-person') ? 'html' : 'no');
  out += ' previewText=' + (pv && pv.querySelector('.probe-person h3 b') === null && pv.textContent.includes('<b>Ann</b>') ? 'yes' : 'no');
  out += ' previewLink=' + ((pv && pv.querySelector('.probe-site') || {}).getAttribute ? pv.querySelector('.probe-site').getAttribute('href') : 'none');
  out += ' previewWarn=' + ($('.generator-dialog .generator-warning') ? 'yes' : 'no');
  out += ' previewH3=' + getComputedStyle(pv.querySelector('.probe-person h3')).color.replace(/ /g, '');
  out += ' dialogTitle=' + getComputedStyle($('.generator-dialog h3')).color.replace(/ /g, '');
  click($('.generator-dialog [data-gen-close]'));           await sleep(200);
  await loadPage('templates/Bad.md', window.BAD, []);      await sleep(1500);
  out += ' badSays=' + w(($('#generator-banner .generator-status.error') || {}).textContent || 'nothing');

  // An archived page says why: its row went, or its template did — never one for the other.
  const archSays = async (path, id) => {
    await loadPage(path, id, []);                          await sleep(1200);
    click($('#generator-badge'));                          await sleep(200);
    return ($('#generator-banner') || {}).textContent || '';
  };
  const rowText = await archSays('ArchRow.md', window.ARCH[0]);
  out += ' archRow=' + (rowText.includes('deleted from the list "Customers"') ? 'row' : 'other');
  const tplText = await archSays('ArchTpl.md', window.ARCH[1]);
  out += ' archTpl=' + (tplText.includes('template that generated this page has been deleted') && tplText.includes('not affected') && !tplText.includes('row') ? 'template' : 'other');
  const oldText = await archSays('ArchOld.md', window.ARCH[2]);
  out += ' archOld=' + (oldText.includes('no longer updated by it') && !oldText.includes('deleted') ? 'neutral' : 'other');
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(out + ' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>""" % (int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5])
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/index.php?space=Main&pageid=$CARD" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE.*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'an HTML page'
assert_contains "is shown as HTML"                          'card=html '            "$PROBE"
assert_contains "  indented markup is not a code block"     'noCode=yes '           "$PROBE"
assert_contains "  {filename} still applies"                'filename=Card_for_Card ' "$PROBE"
assert_contains "  wiki tags are left as text"              'tagsLeft=yes '         "$PROBE"
assert_contains "  and the inline/classic switch is gone"   'switchHidden=yes '     "$PROBE"

section "an HTML page's own <style>"
assert_contains "styles the page"                           'pageH1=rgb(200,0,0) '  "$PROBE"
assert_contains "  but not the wiki around it"              'sidebarItem=rgb('      "$PROBE"
assert_not_contains "  (the sidebar is not red)"            'sidebarItem=rgb(200,0,0)' "$PROBE"
assert_contains "  its body rule is the page's"             'pageBody=rgb(1,2,3) '  "$PROBE"
assert_not_contains "  not the window's"                    'windowBody=rgb(1,2,3)' "$PROBE"
assert_contains "  an @media rule is scoped too"            'mediaRule=rgb(0,128,0) ' "$PROBE"
assert_contains "  and the block is marked as done"         'scoped=yes '           "$PROBE"
assert_contains "a Markdown page's <style> is left as it was" 'plainStyleUntouched=yes ' "$PROBE"
assert_contains "the Preview's styles reach the preview"    'previewH3=rgb(200,0,0) ' "$PROBE"
assert_not_contains "  not the dialog's own title"          'dialogTitle=rgb(200,0,0)' "$PROBE"

section 'editing it'
assert_contains "the stored preference is inline"           'modeBefore=inline '    "$PROBE"
assert_contains "  but the classic editor opens"            'editor=classic '       "$PROBE"
assert_contains "  for this edit"                           'modeWhile=classic '    "$PROBE"
assert_contains "  on the HTML source"                      'source=html '          "$PROBE"
assert_contains "  and afterwards the preference is as it was" 'modeAfter=inline,inline ' "$PROBE"

section 'a Markdown page, unchanged'
assert_contains "is still Markdown"                         'plain=markdown '       "$PROBE"
assert_contains "  with the switch"                         'plainSwitch=shown '    "$PROBE"

section 'an HTML template'
assert_contains "the template page is shown as HTML"        'tplShown=html '        "$PROBE"
assert_contains "  its placeholders visible as text"        'tplPlaceholders={{name}} ' "$PROBE"
assert_contains "the Preview shows its output as HTML"      'preview=html '         "$PROBE"
assert_contains "  the data as text, not markup"            'previewText=yes '      "$PROBE"
assert_contains "  a javascript: link blocked"              'previewLink=#blocked ' "$PROBE"
assert_contains "  and said so"                             'previewWarn=yes'       "$PROBE"

assert_contains "a refused HTML template says why, in words" 'in_an_event_handler_(on…)' "$PROBE"

section 'an archived page says why'
assert_contains "its row was deleted — naming the list"     'archRow=row '          "$PROBE"
assert_contains "its template was deleted — the list is fine" 'archTpl=template '   "$PROBE"
assert_contains "archived before reasons were kept: neither claimed" 'archOld=neutral' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
