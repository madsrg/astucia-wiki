# AI skills in a browser: Admin → AI → Skills (list, editor, import), the Space settings
# switch, the AI user's Skills setting, and the /skill type-ahead in a chat.
#
# tests/skills.test.sh proves what the server does with a skill; this proves the panels
# can produce one. What it is for is invisible over HTTP — a tab that never loads, a
# field rendered but never read back, a switch that flips on screen and not on the server.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Team.chat' '{"messages":[],"nextMessageId":1,"topic":"T"}'
fixture_users '{"users":[
  {"uid":5,"name":"Bot","role":"editor","is_ai":true,"service_token":"wk_ai_ui",
   "ai_config":{"provider":"openai","api_url":"https://llm.invalid/v1","api_key":"sk-test","model":"gpt-4o"}}
]}'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
CHAT_ID=$(python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(next(k for k,v in d.items() if v["path"]=="Team.chat"))' "$WIKI_PAGES/Main/index.json")

# A zip for the import, served from the app folder so the probe can fetch it into a File.
python3 - "$WIKI_APP/__skills.zip" <<'PY'
import sys, zipfile
z = zipfile.ZipFile(sys.argv[1], 'w')
z.writestr('pack/notes-helper/SKILL.md', '---\nname: notes-helper\ndescription: Tidies meeting notes. Use when asked to clean up notes.\n---\n# Notes\n')
z.writestr('pack/notes-helper/run.sh', 'echo never\n')
z.close()
PY

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/skills_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const api = async (q) => (await fetch('api.php?' + q)).json();

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  let out = '';
  click($('#admin-btn'));                                     await sleep(800);
  click($('.admin-group[data-group="ai"]'));                  await sleep(500);
  const tab = $('.admin-tab[data-tab="skills"]');
  out += ' tab=' + (tab && !tab.classList.contains('hidden') ? 'shown' : 'missing');
  click(tab);                                                 await sleep(1000);
  out += ' empty=' + ($('#admin-skills-list .admin-empty') ? 'yes' : 'no');
  out += ' footer=' + ($('#admin-footer-skills').classList.contains('hidden') ? 'hidden' : 'shown');

  // New: the template is the starting point, the name in it decides the folder.
  click($('#admin-skills-add-btn'));                          await sleep(500);
  const ta = $('#sk-f-content');
  out += ' template=' + (ta && ta.value.includes('name: new-skill') ? 'yes' : 'no');
  out += ' footerhidden=' + ($('#admin-footer-skills').classList.contains('hidden') ? 'yes' : 'no');
  ta.value = '---' + String.fromCharCode(10) + 'name: Bad Name' + String.fromCharCode(10) + '---' + String.fromCharCode(10) + 'x';
  click($('#sk-f-save'));                                     await sleep(800);
  const errs = $('#sk-f-errors').textContent;
  out += ' errs=' + (errs.includes('lowercase') && errs.includes('description') ? 'both' : 'missing:' + errs.slice(0, 40));
  ta.value = '---' + String.fromCharCode(10) + 'name: house-style' + String.fromCharCode(10)
           + 'description: Applies the house style. Use for customer text.' + String.fromCharCode(10) + '---' + String.fromCharCode(10) + '# Style';
  click($('#sk-f-save'));                                     await sleep(1200);
  out += ' rows=' + $$('#admin-skills-list tbody tr').length;
  const wiki = await api('action=admin_skills_list&scope=');
  out += ' stored=' + wiki.skills.map(s => s.name).join('+');

  // Edit reads back what was saved.
  click($('#admin-skills-list .sk-edit'));                    await sleep(800);
  out += ' editback=' + ($('#sk-f-content').value.includes('Applies the house style') ? 'yes' : 'no');
  click($('#sk-f-cancel'));                                   await sleep(400);

  // The house default switch reaches the server.
  click($('#skills-default'));                                await sleep(800);
  out += ' default=' + (await api('action=admin_ai_skills_settings')).enabled;
  click($('#skills-default'));                                await sleep(800);

  // A Space scope with skills off says so.
  const sel = $('#skills-scope');
  sel.value = 'Main'; sel.dispatchEvent(new Event('change'));  await sleep(1000);
  out += ' offnote=' + ($('#admin-skills-list .wf-note-warn') ? 'yes' : 'no');

  // Import a zip into Main.
  click($('#admin-skills-import-btn'));                       await sleep(500);
  click($('input[name="sk-src"][value="zip"]'));              await sleep(100);
  const blob = await (await fetch('__skills.zip')).blob();
  const dt = new DataTransfer();
  dt.items.add(new File([blob], 'pack.zip', { type: 'application/zip' }));
  $('#sk-i-file').files = dt.files;
  click($('#sk-i-scan'));                                     await sleep(1500);
  out += ' found=' + $$('#admin-skills-list tbody tr').length;
  out += ' dropnote=' + ($('#admin-skills-list details') && $('#admin-skills-list details').textContent.includes('run.sh') ? 'yes' : 'no');
  out += ' dest=' + $('#sk-c-dest').value;
  click($('#sk-c-go'));                                       await sleep(1500);
  const main = await api('action=admin_skills_list&scope=Main');
  out += ' imported=' + main.skills.map(s => s.name).join('+');
  out += ' scopeafter=' + $('#skills-scope').value;

  // The AI user's Skills setting is read back on save.
  click($('.admin-tab[data-tab="ai"]'));                      await sleep(1000);
  const edit = $$('#admin-ai-list button').find(b => b.classList.contains('btn-secondary'));
  click(edit);                                                await sleep(800);
  const sk = $('#ai-f-skills');
  out += ' aiselect=' + (sk ? 'yes' : 'no');
  sk.value = 'off';
  click($('#ai-f-save-btn'));                                 await sleep(1500);
  const ais = await api('action=admin_get_ai_users');
  out += ' aisaved=' + ((ais.data || ais.users || []).find(u => u.name === 'Bot') || {}).ai_config?.skills;

  // Close the admin panel; switch skills on for Main through the Space settings dialog.
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }));  await sleep(300);
  $('#admin-modal-close')?.click();                           await sleep(300);
  click($('#space-settings-btn'));                            await sleep(1200);
  click($('.admin-tab[data-tab="ai"]'));                      await sleep(300);
  const boxes = $$('#space-settings-modal .space-settings-switch');
  const skBox = boxes[boxes.length - 1];
  out += ' spacecount=' + ($('#space-settings-modal').textContent.includes('Skills of this space: 1') ? 'yes' : 'no');
  click(skBox);                                               await sleep(1000);
  const ss = await api('action=admin_space_settings');
  out += ' spaceon=' + ss.data.find(s => s.name === 'Main').skills;
  $('#space-settings-modal')?.remove();

  // The /skill type-ahead in a chat offers this space's skills.
  window.location.hash = '';
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=90000 \
    --dump-dom "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the tab'
assert_contains "under AI"                          'tab=shown'          "$PROBE"
assert_contains "empty to begin with"               'empty=yes'          "$PROBE"
assert_contains "with its buttons"                  'footer=shown'       "$PROBE"

section 'the editor'
assert_contains "New starts from the template"      'template=yes'       "$PROBE"
assert_contains "the list's buttons step aside"     'footerhidden=yes'   "$PROBE"
assert_contains "every problem is shown, translated" 'errs=both'         "$PROBE"
assert_contains "saving lists it"                   'rows=1'             "$PROBE"
assert_contains "under the name from the front matter" 'stored=house-style' "$PROBE"
assert_contains "edit reads back what was saved"    'editback=yes'       "$PROBE"
assert_contains "the house default reaches the server" 'default=false'   "$PROBE"
assert_contains "a Space with skills off says so"   'offnote=yes'        "$PROBE"

section 'import'
assert_contains "the zip's skill is offered"        'found=1'            "$PROBE"
assert_contains "with the dropped script named"     'dropnote=yes'       "$PROBE"
assert_contains "into the Space being viewed"       'dest=Main'          "$PROBE"
assert_contains "and lands there"                   'imported=notes-helper' "$PROBE"
assert_contains "and the list follows it"           'scopeafter=Main'    "$PROBE"

section 'elsewhere'
assert_contains "the AI user form has the setting"  'aiselect=yes'       "$PROBE"
assert_contains "and it is saved"                   'aisaved=off'        "$PROBE"
assert_contains "Space settings counts the skills"  'spacecount=yes'     "$PROBE"
assert_contains "and its switch reaches the server" 'spaceon=true'       "$PROBE"

# ── the /skill type-ahead, on a chat page ───────────────────────────────────
python3 - "$WIKI_APP/index.php" <<'PY'
import io, re, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
s = re.sub(r'<script type="module">\nconst sleep.*?</script>\n', '', s, flags=re.S)
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
setTimeout(async () => {
  let out = '';
  try {
    const ta = document.querySelector('.chat-input-area textarea, #chat-input, textarea.chat-textarea');
    out += ' composer=' + (ta ? 'yes' : 'no');
    ta.focus();
    ta.value = '/sk'; ta.selectionStart = ta.selectionEnd = 3;
    ta.dispatchEvent(new InputEvent('input', { inputType: 'insertText' }));  await sleep(600);
    out += ' cmd=' + (document.body.textContent.includes('/skill') ? 'yes' : 'no');
    ta.value = '/skill no'; ta.selectionStart = ta.selectionEnd = 9;
    ta.dispatchEvent(new InputEvent('input', { inputType: 'insertText' }));  await sleep(800);
    out += ' completed=[' + ta.value + ']';
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 5000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY
"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=30000 \
    --dump-dom "$WIKI_URL/index.php?pageid=$CHAT_ID&space=Main" > "$WIKI_ROOT/dom2.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom2.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
section 'the /skill type-ahead'
[ -n "$PROBE" ] || _fail "the chat page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"
assert_contains "the chat composer is there"        'composer=yes'       "$PROBE"
assert_contains "/skill is among the commands"      'cmd=yes'            "$PROBE"
assert_contains "a unique skill name completes"     'completed=[/skill notes-helper ]' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
