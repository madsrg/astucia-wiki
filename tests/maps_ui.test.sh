# Maps in the browser: ```map blocks drawn on a page, and Insert → Map.
#
# Leaflet is replaced by a recorder on `window.L` (modules/maps uses one that is already
# there), so this checks what the renderer *asks* Leaflet for — centre, zoom, layer, marker,
# interaction — without the CDN or any tile server. The address lookup is a stub inside the
# fixture; tests/maps.test.sh covers it on the server.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Main'
fixture_page 'Main/Places.md' '# Places

```map
address: Town <b>Hall</b>
lat: 55.67566
lon: 12.56976
zoom: 16
height: 320
type: satellite
label: City <i>Hall</i>
```

```map
lat: 99
lon: 1
```

```map
lat: 55
lon: 12
interactive: false
marker: false
caption: false
width: 50%
```

Text after the maps.'
curl -s "$WIKI_URL/api.php?action=list&space=Main" > /dev/null

GEOLOG="$WIKI_ROOT/geo.log"
cat > "$WIKI_APP/__geo.php" <<PHP
<?php
file_put_contents('$GEOLOG', (\$_GET['q'] ?? '') . "\n", FILE_APPEND);
header('Content-Type: application/json');
echo json_encode([
  ['lat' => '55.67566', 'lon' => '12.56976', 'display_name' => 'Rådhuspladsen 1, København', 'type' => 'townhall'],
  ['lat' => '56.1572', 'lon' => '10.2107', 'display_name' => 'Aarhus Rådhus', 'type' => 'townhall'],
]);
PHP
sed -i "s/^define('WEB_REQUEST_ALLOW_PRIVATE'.*/define('WEB_REQUEST_ALLOW_PRIVATE', true);/" "$WIKI_APP/config.php"
printf '{"maps":{"enabled":true,"geocoder":"%s/__geo.php","tiles":{}}}\n' "$WIKI_URL" > "$WIKI_SYS/settings.json"

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/maps_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script>
// A recorder standing in for Leaflet: every map, layer and marker the renderer asks for.
window.__maps = [];
window.L = {
  version: 'stub',
  map(el, o) {
    const rec = { el, o, layers: [], markers: [], on: {}, removed: false };
    window.__maps.push(rec);
    return { _rec: rec, on(ev, fn) { rec.on[ev] = fn; }, remove() { rec.removed = true; },
             invalidateSize() {}, scrollWheelZoom: { enable() { rec.wheel = true; }, disable() { rec.wheel = false; } } };
  },
  tileLayer(url, o) { return { addTo(m) { m._rec.layers.push({ url, o }); return this; } }; },
  marker(ll) { return { addTo(m) { const mk = { ll, popup: null }; m._rec.markers.push(mk);
                        return { bindPopup(c) { mk.popup = c; } }; } }; },
};
</script>
<script type="module">
import { state } from './modules/core/state.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
const fire = (el, ev) => el.dispatchEvent(new Event(ev, { bubbles: true }));

setTimeout(async () => {
  let out = '';
  try {
    $('#file-navigator [data-path="Places.md"]').click();      await sleep(2000);
    const figs = $$('#viewer-content figure.wiki-map');
    const m0 = window.__maps[0] || { o: {}, layers: [], markers: [] };
    const m1 = window.__maps[1] || { o: {}, layers: [], markers: [] };
    out += ' figures=' + figs.length + ' maps=' + window.__maps.length
        + ' height=' + (figs[0] && figs[0].querySelector('.wiki-map-canvas').style.height)
        + ' center=' + JSON.stringify(m0.o.center) + ' zoom=' + m0.o.zoom
        + ' wheel=' + m0.o.scrollWheelZoom + ' drag=' + m0.o.dragging
        + ' layer=' + ((m0.layers[0] || {}).url || '').includes('World_Imagery')
        + ' attribution=' + /Esri/.test(((m0.layers[0] || {}).o || {}).attribution || '')
        + ' markers=' + m0.markers.length
        + ' popupIsText=' + (m0.markers[0] && m0.markers[0].popup && m0.markers[0].popup.nodeType === 3)
        + ' popup=[' + (m0.markers[0] && m0.markers[0].popup ? m0.markers[0].popup.textContent : '') + ']'
        + ' caption=[' + (figs[0] && figs[0].querySelector('figcaption') || {}).textContent + ']'
        + ' captionLink=' + ((figs[0] && figs[0].querySelector('figcaption a') || {}).href || '').includes('mlat=55.67566')
        + ' markupInPage=' + $$('#viewer-content figure b, #viewer-content figure i').length
        + ' sourceHidden=' + getComputedStyle($$('#viewer-content pre')[0]).display;
    // The wheel only zooms once the reader has clicked into the map.
    if (m0.on && m0.on.click) m0.on.click();
    out += ' wheelAfterClick=' + m0.wheel;
    const err = $('#viewer-content .wiki-map-error');
    out += ' error=[' + (err ? err.textContent : '') + ']'
        + ' badSourceShown=' + (err && getComputedStyle(err.nextElementSibling).display !== 'none');
    out += ' still: drag=' + m1.o.dragging + ' zoomCtl=' + m1.o.zoomControl + ' marker=' + m1.markers.length
        + ' noCaption=' + !(figs[1] && figs[1].querySelector('figcaption'))
        + ' width=' + (figs[1] && figs[1].style.width);

    // ── Insert → Map ────────────────────────────────────────────────────────
    $('#edit-btn').click();                                     await sleep(1000);
    const ed = $('#editor-container');
    ed.value = 'Intro line.'; ed.setSelectionRange(11, 11); fire(ed, 'input');
    const item = $$('.dropdown-content a').find(a => a.textContent.trim() === 'Map');
    out += ' menuItem=' + !!item;
    item.click();                                               await sleep(800);
    out += ' dialog=' + !!$('#map-insert-modal') + ' insertDisabled=' + $('#map-insert-ok').disabled;
    const before = window.__maps.length;
    $('#map-insert-query').value = 'Town Hall';
    $('#map-insert-find-btn').click();                          await sleep(3000);
    out += ' results=' + $$('#map-insert-results .map-insert-result').map(r => r.textContent).join('|')
        + ' firstChosen=' + $$('#map-insert-results .map-insert-result')[0].classList.contains('active')
        + ' previewDrawn=' + (window.__maps.length > before)
        + ' insertEnabled=' + !$('#map-insert-ok').disabled;
    const type = $('#map-insert-type'); type.value = 'topo'; fire(type, 'change');
    const h = $('#map-insert-height'); h.value = '300'; fire(h, 'change');
    const lbl = $('#map-insert-label'); lbl.value = 'HQ'; fire(lbl, 'input');
    const cap = $('#map-insert-caption'); cap.checked = false; fire(cap, 'change');   await sleep(300);
    out += ' previewTopo=' + (window.__maps[window.__maps.length - 1].layers[0] || {}).url.includes('opentopomap');
    $('#map-insert-ok').click();                                await sleep(500);
    out += ' closed=' + !$('#map-insert-modal');
    window.__ed1 = ed.value;

    // Coordinates are taken as they are — no lookup.
    const looked = (await (await fetch('__geo_count.php')).text()).trim();
    item.click();                                               await sleep(800);
    $('#map-insert-query').value = '48.8584, 2.2945';
    $('#map-insert-query').dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));  await sleep(500);
    out += ' coordRow=[' + ($('#map-insert-results .map-insert-result') || {}).textContent + ']';
    $('#map-insert-ok').click();                                await sleep(500);
    const looked2 = (await (await fetch('__geo_count.php')).text()).trim();
    out += ' noLookupForCoords=' + (looked === looked2);

    // Escape closes the dialog and nothing else.
    item.click();                                               await sleep(800);
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));  await sleep(300);
    out += ' escClosed=' + !$('#map-insert-modal') + ' stillEditing=' + state.isEditing;
    window.__ed2 = ed.value;
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
  document.getElementById('probe-ed').textContent = window.__ed2 || '';
}, 4000);
</script>
<pre id="probe-ed"></pre>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY
cat > "$WIKI_APP/__geo_count.php" <<PHP
<?php echo is_file('$GEOLOG') ? count(file('$GEOLOG')) : 0;
PHP

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
# Several workers: the wiki calls the stub lookup service on this same server.
( cd "$WIKI_APP" && PHP_CLI_SERVER_WORKERS=4 exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=90000 \
    --dump-dom "$WIKI_URL/index.php?space=Main" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
EDITOR=$(python3 -c 'import html,re,sys; m=re.search(r"<pre id=\"probe-ed\">(.*?)</pre>", open(sys.argv[1]).read(), re.S); sys.stdout.write(html.unescape(m.group(1)) if m else "")' "$WIKI_ROOT/dom.html")
[ -n "${MAPS_UI_DEBUG:-}" ] && { echo "$PROBE" >&2; echo "$EDITOR" >&2; }
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'a map block on a page'
assert_contains "two valid blocks become two maps"          'figures=2 maps=2' "$PROBE"
assert_contains "  at the height the block asks for"        'height=320px'      "$PROBE"
assert_contains "  centred on its coordinates, at its zoom" 'center=[55.67566,12.56976] zoom=16' "$PROBE"
assert_contains "  the wheel does not zoom while scrolling past" 'wheel=false drag=true' "$PROBE"
assert_contains "  until the map is clicked"                'wheelAfterClick=true' "$PROBE"
assert_contains "  on the satellite layer, with its attribution" 'layer=true attribution=true' "$PROBE"
assert_contains "  one marker, its label as text"           'markers=1 popupIsText=true popup=[City <i>Hall</i>]' "$PROBE"
assert_contains "  the address under it, as text"           'caption=[Town <b>Hall</b> · Open in OpenStreetMap]' "$PROBE"
assert_contains "  linking to the place"                    'captionLink=true'  "$PROBE"
assert_contains "  and no element made from the block's text" 'markupInPage=0'  "$PROBE"
assert_contains "  its source is kept, hidden"              'sourceHidden=none' "$PROBE"
assert_contains "a block with bad coordinates says why"     'error=[This map needs lat and lon, in decimal degrees.]' "$PROBE"
assert_contains "  and keeps its source on show"            'badSourceShown=true' "$PROBE"
assert_contains "interactive: false is a still picture"     'still: drag=false zoomCtl=false marker=0' "$PROBE"
assert_contains "  caption: false and width: 50% are honoured" 'noCaption=true width=50%' "$PROBE"

section 'Insert → Map'
assert_contains "the Insert menu has Map"                   'menuItem=true'     "$PROBE"
assert_contains "the dialog opens with Insert disabled"     'dialog=true insertDisabled=true' "$PROBE"
assert_contains "Find lists the places"                     'results=Rådhuspladsen 1, København|Aarhus Rådhus ' "$PROBE"
assert_contains "  chooses the first, previews it, arms Insert" 'firstChosen=true previewDrawn=true insertEnabled=true' "$PROBE"
assert_contains "the preview follows the map type"          'previewTopo=true'  "$PROBE"
assert_contains "Insert closes the dialog"                  'closed=true'       "$PROBE"
assert_contains "coordinates need no lookup"                'coordRow=[48.8584, 2.2945] ' "$PROBE"
assert_contains "  and the service is not asked"            'noLookupForCoords=true' "$PROBE"
assert_contains "Escape closes the dialog and leaves the editor alone" 'escClosed=true stillEditing=true' "$PROBE"

block1='```map
address: Rådhuspladsen 1, København
