assert_contains "the editor has the block, as chosen"       "$block1" "$EDITOR"
assert_contains "  after the text at the caret"             "Intro line.

$block1" "$EDITOR"
assert_contains "  and the coordinates one"                 "$block2" "$EDITOR"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
