# The front-matter tag sync notice, in the browser: a page whose block and tags disagree
# says so in each direction, each button settles its own half, Ignore is remembered, and
# none of the file writes makes the open-page watcher reload the page under the reader.
#
# tests/fm_tags_sync.test.sh holds the server side.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
fixture_page 'Main/Notes.md' '---
tags: [imported]
---
# Notes'
fixture_page 'Main/Other.md' '---
tags: [stray]
---
# Other'
printf '{"Main":{"fm_tags_sync":"on"}}' > "$WIKI_SYS/spaces.json"
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
# Notes.md carries a tag the index has and the block does not.
python3 - "$WIKI_PAGES/Main/index.json" <<'PY'
import json,sys
p=sys.argv[1]; ix=json.load(open(p))
for v in ix.values():
    if v.get("path")=="Notes.md": v["tags"]=["Wiki"]
json.dump(ix,open(p,"w"))
PY

page_id() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' \
        "$WIKI_PAGES/${2:-Main}/index.json" "$1"
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/fm_tags_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" "$(page_id Other.md)" "$(page_id Notes.md)" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
import { loadPage } from './modules/page_view/index.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection', e => {
    document.title = 'PROBE fatalRejection=' + (e.reason && e.reason.message || e.reason); });
const lines = () => $$('#tags-fm-notice .tags-fm-line span').map(x => x.textContent).join('|');
const shown = () => !$('#tags-fm-notice').classList.contains('hidden');
const fmTags = () => JSON.stringify((state.currentPageFrontmatter || {}).tags || null);
const btn = (i) => $$('#tags-fm-notice .tags-fm-line button')[i];

setTimeout(async () => {
  let out = '';
  try {
    out += ' sync=' + state.spaceFmTagsSync + ' shown=' + shown() + ' lines=' + lines();
    btn(1).click();                                  await sleep(1500);   // write to front matter
    out += ' afterWrite=' + fmTags() + ' lines2=' + lines();
    btn(0).click();                                  await sleep(1500);   // add to page
    out += ' afterAdd=' + JSON.stringify(state.currentPageTags) + ' shownAfter=' + shown();
    // The watcher polls every 10 s: give it two rounds to misread our own writes.
    await sleep(22000);
    out += ' reloadToast=' + ((($('#toast-message') || {}).textContent || '').includes('reloaded'));
    // Ignore: hidden, and still hidden when the page is opened again.
    const otherId = OTHER_ID;
    await loadPage('Other.md', otherId, []);          await sleep(1200);
    out += ' otherShown=' + shown();
    $('#tags-fm-notice .tags-fm-ignore').click();    await sleep(200);
    out += ' ignored=' + !shown();
    await loadPage('Notes.md', NOTES_ID, []);         await sleep(1000);
    await loadPage('Other.md', otherId, []);          await sleep(1200);
    out += ' stillIgnored=' + !shown() + ' file=' + JSON.stringify((state.currentPageFrontmatter || {}).tags || null);
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  document.title = 'PROBE' + out;
}, 4000);
</script>
</body>"""
probe = probe.replace('OTHER_ID', "'" + sys.argv[2] + "'").replace('NOTES_ID', "'" + sys.argv[3] + "'")
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

load() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=60000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "page $1"
}

load Notes.md
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the notice'
assert_contains "the Space syncs"                  'sync=true'          "$PROBE"
assert_contains "a disagreeing page shows it"      'shown=true'         "$PROBE"
assert_contains "  naming the block's extra tag"   'imported'           "$PROBE"
assert_contains "  and the page's missing one"     'On this page but not in its front matter: Wiki' "$PROBE"

section 'settling it'
assert_contains "Write to front matter adds the page's tag to the block" 'afterWrite=["imported","Wiki"]' "$PROBE"
assert_contains "  and that half of the notice goes" 'lines2=In the front matter but not on this page: imported ' "$PROBE"
assert_contains "Add to page adds the block's tag"  'afterAdd=["Wiki","imported"]' "$PROBE"
assert_contains "  and the notice goes"             'shownAfter=false'  "$PROBE"
assert_contains "the watcher did not reload the page under the reader" 'reloadToast=false' "$PROBE"
assert_contains "the file says so too"              'imported'          "$(cat "$WIKI_PAGES/Main/Notes.md")"
assert_contains "  in its own flow form"            'tags: [imported, Wiki]' "$(cat "$WIKI_PAGES/Main/Notes.md")"

section 'Ignore'
assert_contains "another disagreeing page shows it" 'otherShown=true'   "$PROBE"
assert_contains "Ignore hides it"                  'ignored=true'       "$PROBE"
assert_contains "  and it stays hidden on the next visit" 'stillIgnored=true' "$PROBE"
assert_contains "  without touching the file"      'file=["stray"]'     "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
