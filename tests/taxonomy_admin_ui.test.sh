# Admin → Content → Taxonomy as a tree editor: one toolbar acting on the selection (and
# saying why a button is disabled), folder and item icons, the details panel, inline
# rename, the tree's keyboard model, drag and drop to move, and the dialogs for move,
# merge and delete. Each action is checked by what the server then holds.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
fixture_page 'Main/Notes.md' '# Notes'
cat > "$WIKI_PAGES/taxonomy.json" <<'JSON'
{"version":1,"nodes":[
  {"name":"Department","heading":true,"children":[
     {"name":"Finance","description":"Money matters"},
     {"name":"HR"}]},
  {"name":"Status","heading":true,"children":[{"name":"Draft"},{"name":"Final"}]},
  {"name":"Loose","children":[{"name":"Child"},{"name":"Grouping","heading":true}]}
]}
JSON
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
# Finance is in use, so it cannot be deleted and renaming it asks first.
python3 - "$WIKI_PAGES/Main/index.json" <<'PY'
import json,sys
p=sys.argv[1]; ix=json.load(open(p))
for v in ix.values(): v["tags"]=["Department/Finance"]
json.dump(ix,open(p,"w"))
PY
page_id() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' \
        "$WIKI_PAGES/${2:-Main}/index.json" "$1"
}
paths() {
    python3 -c 'import json,sys
d = json.load(open(sys.argv[1]))
def walk(ns, p):
    for n in ns:
        q = p + "/" + n["name"] if p else n["name"]
        print(q + ("#F" if n.get("heading") else ""))
        walk(n.get("children", []), q)
walk(d.get("nodes", []), "")' "$WIKI_PAGES/taxonomy.json" | tr '\n' ' '
}

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/taxonomy_admin_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { sortNodes, flatten } from './modules/core/taxonomy.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection', e => {
    document.title = 'PROBE fatalRejection=' + (e.reason && e.reason.message || e.reason); });
const row = (p) => $$('#admin-tax-tree .tax-row').find(r => r.dataset.path === p);
const rows = () => $$('#admin-tax-tree .tax-row').map(r => r.dataset.path).join(',');
const sel = () => ($$('#admin-tax-tree .tax-row.is-selected')[0] || {}).dataset?.path || 'none';
const key = (k) => $('#admin-tax-tree').dispatchEvent(new KeyboardEvent('keydown', { key: k, bubbles: true, cancelable: true }));
const ok = async () => { await sleep(300); $('#confirm-modal-ok').click(); await sleep(1500); };
const rename = async (name) => {
  const input = $('#admin-tax-tree .tax-rename');
  if (!input) return 'noinput';
  input.value = name;
  input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
  await sleep(1500);
  return 'ok';
};

setTimeout(async () => {
  let out = '';
  try {
    $('#admin-btn').click();                       await sleep(800);
    $('.admin-group[data-group=content]').click(); await sleep(200);
    $('.admin-tab[data-tab=taxonomy]').click();    await sleep(1500);
    $('#tax-launch').click();                      await sleep(500);
    // Its own lightbox, 80% of the window each way; the mode selector stayed on the tab,
    // at half the width it had.
    const eb = $('.tax-editor-content').getBoundingClientRect();
    out += ' edW=' + (eb.width / window.innerWidth).toFixed(2) + ' edH=' + (eb.height / window.innerHeight).toFixed(2)
        + ' modeW=' + Math.round($('#admin-tax-mode').getBoundingClientRect().width)
        + ' summary=' + JSON.stringify($('.tax-summary').textContent)
        + ' treeFill=' + ($('#admin-tax-tree').getBoundingClientRect().height > window.innerHeight * 0.4);
    // Folders first at every level, then items. In the file Loose holds Child before
    // Grouping; the editor shows the folder first.
    out += ' order=' + rows();
    // The tree is a size more compact than the rest of the dialog.
    const r0 = $('#admin-tax-tree .tax-row');
    out += ' rowH=' + Math.round(r0.getBoundingClientRect().height)
        + ' rowFont=' + Math.round(parseFloat(getComputedStyle(r0.querySelector('.tax-name')).fontSize) * 10) / 10;
    // The rule itself, on names that tell it apart from a plain sort: case, numbers, and a
    // folder whose name sorts after the items.
    out += ' sorted=' + flatten(sortNodes([
        { name: 'q10' }, { name: 'Zeta', heading: true }, { name: 'Q2' }, { name: 'alpha' },
        { name: 'Beta', heading: true, children: [{ name: 'b' }, { name: 'A', heading: true }] }])).map(n => n.path).join(',');

    // Nothing selected: the selection actions are off and say why.
    out += ' moveOff=' + $('#tax-tb-move').disabled + ' delOff=' + $('#tax-tb-delete').disabled
        + ' whyTip=' + JSON.stringify($('#tax-tb-move').title)
        + ' detailsEmpty=' + !!$('#admin-tax-details .tax-details-empty');
    out += ' folders=' + $$('#admin-tax-tree .tax-row.is-folder').length + ' items=' + $$('#admin-tax-tree .tax-row.is-item').length;
    // A folder inside an item, from before that was refused: reported, and marked.
    out += ' misplacedNote=' + JSON.stringify($('.tax-misplaced').classList.contains('hidden') ? '' : $('.tax-misplaced').textContent)
        + ' misplacedRow=' + row('Loose/Grouping').classList.contains('is-misplaced');
    // The folder rule in the editor: no New folder inside an item, no folder radio for an
    // item inside an item, and a folder dragged over an item is not offered the drop.
    row('Loose/Child').click();                    await sleep(200);
    out += ' folderOff=' + $('#tax-tb-folder').disabled + ' folderTip=' + JSON.stringify($('#tax-tb-folder').title)
        + ' radioOff=' + $$('input[name=tax-d-type]').find(r => r.value === 'folder').disabled;
    const dt0 = new DataTransfer();
    row('Status').dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: dt0 }));
    const over = new DragEvent('dragover', { bubbles: true, cancelable: true, dataTransfer: dt0 });
    row('Loose/Child').dispatchEvent(over);
    out += ' dropOffered=' + over.defaultPrevented;
    row('Status').dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: dt0 }));

    // Select an item in use.
    row('Department/Finance').click();             await sleep(200);
    // The panel's labels at the tree's size: the field labels bold, the choices plain.
    const fw = (e) => Math.round(parseFloat(getComputedStyle(e).fontSize) * 10) / 10 + '/' + getComputedStyle(e).fontWeight;
    out += ' labels=' + [...$$('#admin-tax-details .form-group > .form-label')].map(fw).join(',')
        + ' choices=' + [...$$('#admin-tax-details label.tax-type')].map(fw).join(',');
    out += ' sel=' + sel() + ' detailPath=' + $('.tax-details-path').textContent
        + ' detailDesc=' + $('#tax-d-desc').value
        + ' moveOn=' + !$('#tax-tb-move').disabled
        + ' delInUse=' + $('#tax-tb-delete').disabled + ' delTip=' + JSON.stringify($('#tax-tb-delete').title);

    // Keyboard: down to HR, left to its folder, left again collapses it, right opens it.
    key('ArrowDown');                              await sleep(100);
    out += ' kDown=' + sel();
    key('ArrowLeft');                              await sleep(100);
    out += ' kParent=' + sel();
    key('ArrowLeft');                              await sleep(100);
    out += ' kCollapsed=' + !row('Department/HR');
    key('ArrowRight');                             await sleep(100);
    out += ' kExpanded=' + !!row('Department/HR');

    // New folder inside Status, renamed inline.
    row('Status').click();                         await sleep(200);
    $('#tax-tb-folder').click();                   await sleep(1500);
    out += ' renaming=' + (await rename('Archive'));
    out += ' afterFolder=' + sel();
    // New item inside it.
    $('#tax-tb-item').click();                     await sleep(1500);
    out += ' renaming2=' + (await rename('Old'));
    out += ' afterItem=' + sel();
    // With an item selected, New item goes next to it, not under it.
    out += ' itemTip=' + JSON.stringify($('#tax-tb-item').title);
    $('#tax-tb-item').click();                     await sleep(1500);
    out += ' renaming3=' + (await rename('Older'));
    out += ' besideItem=' + sel();
    // …and New folder is offered beside an item whose own parent is a folder.
    row('Department/Finance').click();             await sleep(200);
    out += ' folderBeside=' + !$('#tax-tb-folder').disabled;

    // Details: Loose becomes a folder with a description.
    row('Loose').click();                          await sleep(200);
    $('#tax-d-desc').value = 'Misc'; $('#tax-d-desc').dispatchEvent(new Event('input'));
    $$('input[name=tax-d-type]').find(r => r.value === 'folder').click(); await sleep(50);
    $$('input[name=tax-d-type]').find(r => r.value === 'folder').dispatchEvent(new Event('change'));
    $('#tax-d-save').click();                      await sleep(1500);
    out += ' looseFolder=' + row('Loose').classList.contains('is-folder')
        + ' misplacedGone=' + $('.tax-misplaced').classList.contains('hidden');

    // Drag Draft onto Archive.
    const dt = new DataTransfer();
    row('Status/Draft').dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: dt }));
    row('Status/Archive').dispatchEvent(new DragEvent('dragover', { bubbles: true, cancelable: true, dataTransfer: dt }));
    row('Status/Archive').dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: dt }));
    await sleep(1500);
    out += ' dropped=' + !!row('Status/Archive/Draft');

    // Move HR to the top level with the toolbar.
    row('Department/HR').click();                  await sleep(200);
    $('#tax-tb-move').click();                     await sleep(300);
    $('#tax-f-path').value = '';
    await ok();
    out += ' movedTop=' + !!row('HR');

    // Delete an unused item.
    row('Status/Archive/Old').click();             await sleep(200);
    $('#tax-tb-delete').click();
    await ok();
    out += ' deleted=' + !row('Status/Archive/Old');

    // F2 on an item in use asks before retagging its page.
    row('Department/Finance').click();             await sleep(200);
    key('F2');                                     await sleep(200);
    const input = $('#admin-tax-tree .tax-rename');
    input.value = 'Fin';
    input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
    await sleep(400);
    out += ' askedFirst=' + !$('#confirm-modal').classList.contains('hidden');
    await ok();
    out += ' renamed=' + sel();

    // Merge Final into the renamed item.
    row('Status/Final').click();                   await sleep(200);
    $('#tax-tb-merge').click();                    await sleep(300);
    $('#tax-f-path').value = 'Department/Fin';
    await ok();
    out += ' merged=' + !row('Status/Final') + ' afterMerge=' + sel();
    // Escape closes the editor, and the tab's counts follow what was done in it.
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    await sleep(300);
    out += ' closed=' + !$('#tax-editor-modal') + ' summaryAfter=' + JSON.stringify($('.tax-summary').textContent);
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  document.title = 'PROBE' + out;
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

load() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --virtual-time-budget=60000 \
        --dump-dom "$WIKI_URL/index.php?pageid=$(page_id "$1")&space=Main" \
        > "$WIKI_ROOT/dom.html" 2>/dev/null
    PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
            | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
    [ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" "page $1"
}

load Notes.md
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the editor has its own lightbox'
assert_contains "80% of the window wide"            'edW=0.80'          "$PROBE"
assert_contains "  and high"                        'edH=0.80'          "$PROBE"
assert_contains "  with the tree filling it"        'treeFill=true'     "$PROBE"
assert_contains "the mode selector is half its old 502px" 'modeW=251'   "$PROBE"
assert_contains "the tab says what the tree holds"  'summary="3 folder(s), 6 item(s)"' "$PROBE"

section 'sorted like a file browser'
assert_contains "folders first at every level, then items" \
  'order=Department,Department/Finance,Department/HR,Status,Status/Draft,Status/Final,Loose,Loose/Grouping,Loose/Child ' "$PROBE"
assert_contains "  alphabetical, ignoring case, numbers as numbers" \
  'sorted=Beta,Beta/A,Beta/b,Zeta,alpha,Q2,q10 ' "$PROBE"

section 'compact'
assert_contains "tree rows are 25px (they were 32)" 'rowH=25'   "$PROBE"
assert_contains "  in 13.5px type (it was 14.7)"    'rowFont=13.5' "$PROBE"

section 'one toolbar, acting on the selection'
assert_contains "with nothing selected Move is off" 'moveOff=true'      "$PROBE"
assert_contains "  and Delete"                      'delOff=true'       "$PROBE"
assert_contains "  and the tooltip says why"        'whyTip="Select a folder or item first"' "$PROBE"
assert_contains "the details panel asks for a selection" 'detailsEmpty=true' "$PROBE"
assert_contains "folders and items are told apart"  'folders=3 items=6' "$PROBE"

section 'a folder never goes inside an item'
assert_contains "a folder already inside one is reported" 'misplacedNote="1 folder(s) are inside an item' "$PROBE"
assert_contains "  and marked in the tree"          'misplacedRow=true' "$PROBE"
assert_contains "New folder is off with an item inside an item selected" 'folderOff=true' "$PROBE"
assert_contains "  and says why"                    'folderTip="A folder can only be at the top level' "$PROBE"
assert_contains "the details panel will not make it a folder" 'radioOff=true' "$PROBE"
assert_contains "a folder dragged over an item is not offered the drop" 'dropOffered=false' "$PROBE"

section 'selecting'
assert_contains "a click selects"                   'sel=Department/Finance' "$PROBE"
assert_contains "  the details show its tag"        'detailPath=Department/Finance' "$PROBE"
assert_contains "  and its description"             'detailDesc=Money matters' "$PROBE"
assert_contains "  Move comes on"                   'moveOn=true'       "$PROBE"
assert_contains "  Delete stays off while it is in use" 'delInUse=true' "$PROBE"
assert_contains "  and says how to get rid of it instead" 'merge it into another item instead' "$PROBE"

section 'the details panel matches the tree'
assert_contains "its field labels are bold at 13.5px" 'labels=13.5/700,13.5/700,13.5/700,13.5/700 ' "$PROBE"
assert_contains "  and the choices plain at 13.5px"   'choices=13.5/400,13.5/400,13.5/400 ' "$PROBE"

section 'keyboard'
assert_contains "Down moves to the next row"        'kDown=Department/HR' "$PROBE"
assert_contains "Left on a leaf goes to its parent" 'kParent=Department' "$PROBE"
assert_contains "Left again collapses it"           'kCollapsed=true'   "$PROBE"
assert_contains "Right opens it"                    'kExpanded=true'    "$PROBE"

section 'adding'
assert_contains "New folder opens an inline rename" 'renaming=ok'       "$PROBE"
assert_contains "  and selects the new folder"      'afterFolder=Status/Archive' "$PROBE"
assert_contains "New item goes inside a selected folder" 'afterItem=Status/Archive/Old' "$PROBE"
assert_contains "with an item selected it goes next to it" 'besideItem=Status/Archive/Older' "$PROBE"
assert_contains "  as the tooltip says"             'itemTip="Adds it next to \"Status/Archive/Old\""' "$PROBE"
assert_contains "New folder is offered beside an item in a folder" 'folderBeside=true' "$PROBE"

section 'details, drag and drop, move, delete, rename, merge'
assert_contains "the details panel turns an item into a folder" 'looseFolder=true' "$PROBE"
assert_contains "  which settles the misplaced folder inside it" 'misplacedGone=true' "$PROBE"
assert_contains "a drop moves the node"             'dropped=true'      "$PROBE"
assert_contains "Move to the top level"             'movedTop=true'     "$PROBE"
assert_contains "Delete removes an unused item"     'deleted=true'      "$PROBE"
assert_contains "renaming an item in use asks first" 'askedFirst=true'  "$PROBE"
assert_contains "  and selects it under its new name" 'renamed=Department/Fin' "$PROBE"
assert_contains "Merge folds it into the target"    'merged=true'       "$PROBE"
assert_contains "  and selects the target"          'afterMerge=Department/Fin' "$PROBE"

section 'closing'
assert_contains "Escape closes the editor"          'closed=true'       "$PROBE"
assert_contains "  and the tab's counts follow"     'summaryAfter="5 folder(s), 5 item(s)"' "$PROBE"

section 'what the server holds afterwards'
tree=$(paths)
assert_contains "the new folder"                    'Status/Archive#F ' "$tree"
assert_contains "  and the dropped item in it"      'Status/Archive/Draft ' "$tree"
assert_not_contains "  the deleted item is gone"    'Status/Archive/Old ' "$tree"
assert_contains "Loose is a folder"                 'Loose#F' "$tree"
assert_contains "HR is at the top level"            ' HR ' " $tree"
assert_contains "the page followed the rename"      'Department\/Fin"' "$(cat "$WIKI_PAGES/Main/index.json")"
assert_contains "  and the description was saved"   '"description": "Misc"' "$(cat "$WIKI_PAGES/taxonomy.json")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
