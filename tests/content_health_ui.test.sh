# Content Health in a browser.
#
# tests/content_health.test.sh proves what the report says; this proves the dialog shows
# it: the sidebar button opens it, each tab shows its own list and count, the stale filter
# appears only where it applies, a page name is shown as text rather than parsed as HTML,
# and clicking a row opens that page.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Welcome

See [[Nowhere]] and [[Linked]], both from the start page of this wiki.'
fixture_page 'Main/Linked.md' '# Linked

The start page links here, and it has enough text that it is not a stub.'
fixture_page 'Main/Lonely.md' '# Lonely'
fixture_page 'Main/Bold <em>.md' '# Bold'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/content_health_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const shown = (el) => !!el && !el.classList.contains('hidden');

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const tab = (name) => $('.content-health-tab[data-tab="' + name + '"]');
const titles = () => $$('.content-health-row-title').map(n => n.textContent).join('|');

const run = async () => {
  let out = '';
  click($('#content-health-btn'));                            await sleep(1500);
  out += ' open=' + (shown($('#content-health-modal')) ? 'yes' : 'no');
  out += ' heading=' + $('#content-health-title').textContent.replace(/ /g, '_');
  out += ' counts=' + ['broken', 'stale', 'empty'].map(n => tab(n).querySelector('.content-health-count').textContent).join('/');
  out += ' active=' + $('.content-health-tab.active').dataset.tab;
  out += ' broken=' + titles();
  out += ' detail=' + $('.content-health-row-details li').textContent.replace(/ /g, '_');
  out += ' filter1=' + (shown($('.content-health-stale')) ? 'shown' : 'hidden');

  out += ' tabs=' + $$('.content-health-tab').map(b => b.dataset.tab).join('|');
  click(tab('stale'));                                        await sleep(300);
  out += ' filter2=' + (shown($('.content-health-stale')) ? 'shown' : 'hidden');
  out += ' nostale=' + $('.content-health-list').textContent.replace(/ /g, '_');
  click(tab('empty'));                                        await sleep(300);
  const bold = $('.content-health-row-title');
  out += ' asText=' + (bold && bold.querySelector('em') === null && bold.textContent.includes('<em>') ? 'yes' : 'no');
  out += ' empty=' + titles();

  click($$('.content-health-row').find(a => a.textContent.includes('Lonely')));
  await sleep(1500);
  out += ' closed=' + (shown($('#content-health-modal')) ? 'no' : 'yes');
  out += ' page=' + $('#current-page-title').textContent.trim();

  click($('#content-health-btn'));                            await sleep(1200);
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }));
  await sleep(200);
  out += ' escape=' + (shown($('#content-health-modal')) ? 'stays' : 'closes');
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/index.php?space=Main" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE.*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the dialog'
assert_contains "the sidebar button opens it"          'open=yes'                     "$PROBE"
assert_contains "  …named for the Space"               'heading=Content_Health_—_Main' "$PROBE"
assert_contains "  …with a count on every tab"         'counts=1/0/2'               "$PROBE"
assert_contains "  …starting on broken links"          'active=broken'                "$PROBE"
assert_contains "the broken tab lists the start page"  'broken=Main '                 "$PROBE"
assert_contains "  …and says what is wrong"            'detail=[[Nowhere]]_—_no_page_by_that_name' "$PROBE"

section 'tabs'
assert_contains "three tabs, no orphans"               'tabs=broken|stale|empty '    "$PROBE"
assert_contains "empty lists both, sorted"             'empty=Bold <em>|Lonely '    "$PROBE"
assert_contains "the stale filter is only on Stale"    'filter1=hidden'               "$PROBE"
assert_contains "  …where it shows"                    'filter2=shown'                "$PROBE"
assert_contains "an empty list says so"                'nostale=Nothing_is_stale.'    "$PROBE"
assert_contains "a page name is text, not HTML"        'asText=yes'                   "$PROBE"

section 'navigation'
assert_contains "clicking a row closes the dialog"     'closed=yes'                   "$PROBE"
assert_contains "  …and opens the page"                'page=Lonely'                  "$PROBE"
assert_contains "Escape closes it"                     'escape=closes'                "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
