# A files library in a browser.
#
# tests/files_library.test.sh proves the server side; this proves the pane: a long library
# scrolls (the list used to grow past a clipping wrapper, so it had no scrollbar), a
# subfolder opens on click and its ".." leads back, "New folder" creates one through the
# prompt, and dropping a file on the pane uploads it into the subfolder being shown.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_page 'Main/Main.md' '# Welcome'
LIB="$WIKI_PAGES/Main/Docs"
mkdir -p "$LIB/Reports"; : > "$LIB/.filesfolder"
for i in $(seq 1 80); do printf 'x' > "$LIB/file-$i.txt"; done
printf 'r' > "$LIB/Reports/q1.pdf"
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/files_library_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));
const click = (el) => { if (!el) throw new Error('missing control'); el.click(); };
const report = (out) => { document.title = 'PROBE' + out; };
const shown = (el) => !!el && !el.classList.contains('hidden');

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const rowNames = () => $$('#ff-file-list .ff-simple-item').map(li => li.querySelector('.ff-filename').textContent);

const run = async () => {
  let out = '';
  localStorage.setItem('ff_view', 'simple');
  const ff = await import('./modules/files_folder/index.js');
  await ff.loadFilesFolder('Docs');                           await sleep(500);
  const list = $('#ff-file-list');
  out += ' rows=' + rowNames().length;
  out += ' scrolls=' + (list.scrollHeight > list.clientHeight + 10 && getComputedStyle(list).overflowY === 'auto' ? 'yes' : 'no');
  out += ' fits=' + (list.getBoundingClientRect().bottom <= window.innerHeight + 1 ? 'yes' : 'no');
  out += ' first=' + rowNames()[0];
  out += ' newfolder=' + (shown($('#ff-newfolder-btn')) ? 'shown' : 'hidden');
  const fsvg = $('#ff-file-list .ff-folder-icon svg');
  out += ' foldericon=' + (fsvg ? getComputedStyle(fsvg).stroke.replace(/ /g, '') : 'none');

  click($$('#ff-file-list .ff-simple-item').find(li => li.textContent.includes('Reports')));
  await sleep(800);
  out += ' inside=' + rowNames().join('|');
  out += ' title=' + $('#current-page-title span').textContent.replace(/ /g, '_');

  click($('#ff-newfolder-btn'));                              await sleep(300);
  $('#input-modal-input').value = 'Archive';
  click($('#input-modal-ok'));                                await sleep(1000);
  out += ' afternew=' + rowNames().join('|');

  const dt = new DataTransfer();
  dt.items.add(new File(['dropped'], 'dropped.txt', { type: 'text/plain' }));
  const pane = $('#files-folder-container');
  pane.dispatchEvent(new DragEvent('dragover', { bubbles: true, cancelable: true, dataTransfer: dt }));
  out += ' highlight=' + (pane.classList.contains('drop-target-root') ? 'yes' : 'no');
  pane.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: dt }));
  await sleep(1500);
  out += ' afterdrop=' + rowNames().join('|');

  // ── Marking files and acting on them ──
  const opened = [];
  window.open = (url) => { opened.push(url); return null; };
  const downloads = [];
  const realClick = HTMLAnchorElement.prototype.click;
  HTMLAnchorElement.prototype.click = function () {
    if (this.hasAttribute('download')) downloads.push(this.getAttribute('href')); else realClick.call(this);
  };
  const row = (name) => $$('#ff-file-list .ff-file-row').find(r => r.textContent.includes(name));
  const btnState = () => ['ff-open-btn', 'ff-download-btn', 'ff-delete-sel-btn']
    .map(id => document.getElementById(id).disabled ? '0' : '1').join('');
  out += ' links=' + $$('#ff-file-list a').length;
  out += ' idle=' + btnState();
  click(row('q1.pdf'));                                       await sleep(100);
  out += ' one=' + btnState() + '/' + $('#ff-sel-count').textContent.replace(/ /g, '_');
  out += ' marked=' + (row('q1.pdf').classList.contains('ff-selected') ? 'yes' : 'no');
  out += ' nothingopened=' + opened.length;
  click($('#ff-open-btn'));                                   await sleep(100);
  out += ' openurl=' + (opened[0] || '');
  click(row('dropped.txt'));                                  await sleep(100);
  out += ' two=' + btnState();
  click($('#ff-download-btn'));                               await sleep(800);
  out += ' downloads=' + downloads.map(h => decodeURIComponent(h).split('/').pop()).join('|');
  click(row('dropped.txt'));                                  await sleep(100);
  out += ' unmarked=' + btnState();
  row('dropped.txt').dispatchEvent(new MouseEvent('dblclick', { bubbles: true }));
  await sleep(100);
  out += ' dbl=' + (opened[1] || '').split('%2F').pop();
  click($('#ff-sel-clear'));                                  await sleep(100);
  out += ' cleared=' + btnState();
  click(row('dropped.txt'));                                  await sleep(100);
  click($('#ff-delete-sel-btn'));                             await sleep(300);
  click($('#confirm-modal-ok'));                              await sleep(1200);
  out += ' afterdel=' + rowNames().join('|');

  click($$('#ff-file-list .ff-simple-item').find(li => li.textContent.trim().startsWith('..')));
  await sleep(800);
  out += ' back=' + rowNames()[0];
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/index.php?space=Main" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE.*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'scrolling'
assert_contains "the long library is listed"            'rows=81 '          "$PROBE"
assert_contains "  …and the list scrolls"               'scrolls=yes'       "$PROBE"
assert_contains "  …inside the window"                  'fits=yes'          "$PROBE"

section 'subfolders'
assert_contains "folders come first"                    'first=Reports '    "$PROBE"
assert_contains "New folder is offered"                 'newfolder=shown'   "$PROBE"
assert_contains "folder icons are the darker amber"     'foldericon=rgb(183,121,31)' "$PROBE"
assert_contains "a folder opens, with .. on top"        'inside=..|q1.pdf ' "$PROBE"
assert_contains "  …and the title says where"           'title=Docs_/_Reports' "$PROBE"
assert_contains "New folder creates one there"          'afternew=..|Archive|q1.pdf ' "$PROBE"
assert_contains ".. leads back to the library"          'back=Reports'      "$PROBE"

section 'drag and drop'
assert_contains "a file drag highlights the pane"       'highlight=yes'     "$PROBE"
assert_contains "a drop uploads into the open folder"   'afterdrop=..|Archive|dropped.txt|q1.pdf ' "$PROBE"
assert_contains "  …and it reached the server"         'afterdrop=..|Archive|dropped.txt|q1.pdf ' "$PROBE"

section 'marking files, then choosing the action'
assert_contains "a file is not a link any more"         'links=0 '          "$PROBE"
assert_contains "nothing marked: actions disabled"      'idle=000 '         "$PROBE"
assert_contains "a click marks it and enables all three" 'one=111/1_selected ' "$PROBE"
assert_contains "  …and shows it marked"                'marked=yes'        "$PROBE"
assert_contains "  …without opening anything"           'nothingopened=0'   "$PROBE"
assert_contains "Open opens it inline"                  'openurl=getfile.php?path=Main%2FDocs%2FReports%2Fq1.pdf ' "$PROBE"
assert_contains "two marked: Open off, the rest on"     'two=011 '          "$PROBE"
assert_contains "Download saves both"                   'downloads=q1.pdf&download=1|dropped.txt&download=1 ' "$PROBE"
assert_contains "a second click unmarks"                'unmarked=111 '     "$PROBE"
assert_contains "double-click opens"                    'dbl=dropped.txt'   "$PROBE"
assert_contains "the clear button unmarks everything"   'cleared=000 '      "$PROBE"
assert_contains "Delete removes the marked file"        'afterdel=..|Archive|q1.pdf ' "$PROBE"
assert_file_missing "  …on disk"                        "$WIKI_PAGES/Main/Docs/Reports/dropped.txt"


printf '\n'
exit $(( ASSERT_FAIL > 0 ))
