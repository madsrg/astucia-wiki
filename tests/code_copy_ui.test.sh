# Copy buttons on rendered code blocks, in a real browser.
#
# This feature has no HTTP surface at all: the server sends the same Markdown it always
# did and every button is built from the rendered DOM. So the one way it can fail — no
# button, a button in the wrong place, or a button that copies marked's HTML-escaped text
# instead of what the author typed — is invisible to every other suite here. Same reason
# tests/frontmatter_ui.test.sh exists, and it shares that file's mechanics: a two-line
# router (php -S sends no Content-Type for .js, which blocks ES modules), instrumentation
# that only clicks real controls, and a report read out of document.title.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main

# Three fences and one inline span. The first fence carries the characters marked escapes
# (`&`, `<`, `>`, `"`): reading it back with innerHTML instead of textContent hands the
# clipboard `&amp;lt;` rather than what the author wrote, which is the trap the mermaid
# renderer documents and this pass inherits.
printf '%s' '# Snippets

Run `php -S localhost:8000` to serve it.

