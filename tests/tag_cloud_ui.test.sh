# The tag cloud stays a usable size on a wiki with many tags.
#
# It used to draw every tag in the wiki as a chip, so a few hundred tags made the Tags pane
# a wall. It now shows the most-used TAG_CLOUD_TOP (40) until "Show all" is pressed, and
# typing in the sidebar search box narrows it to the matching tags. All of that happens in
# the DOM over a single get_tag_cloud response, so a browser suite is the only kind that
# can see it.
#
# The fixture has 48 top-level entries: `common` on ten pages, 46 single-page tags, and a
# `Department` branch. `common` must survive the cut (it is picked by count, not by name —
# alphabetically it would be beaten by `aaa-first`), and `zzz-rare-zeta` (last among the
# ties) is reachable only through the filter or Show all.
#
# Nested tags are grouped under their first segment. `Department` spans four pages but five
# tags — P48 has both `Department/Finance` and `Department/Finance/Budget` — so its chip
# saying 4 is the server's distinct-page count, not a sum. P50 spells `department/hr` in
# lower case and must land in the same `HR` chip as P49's `Department/HR`.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT

fixture_space Main
for i in $(seq -w 1 50); do fixture_page "Main/P$i.md" "# P$i"; done

curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null

python3 - "$WIKI_PAGES/Main/index.json" <<'PY'
import json, sys
p = sys.argv[1]
ix = json.load(open(p))
single = ['aaa-first'] + ['t%02d' % i for i in range(1, 45)] + ['zzz-rare-zeta']
nested = {46: ['Department/Finance'],
          47: ['Department/Finance', 'Department/Finance/Budget'],
          48: ['Department/HR'],
          49: ['department/hr']}
for n, (k, v) in enumerate(sorted(ix.items(), key=lambda kv: kv[1]['path'])):
    tags = nested[n] if n in nested else [single[n]]
    if n < 10: tags.append('common')
    v['tags'] = tags
json.dump(ix, open(p, 'w'))
PY

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/tag_cloud_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script, and a parse error would take the whole module down silently.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const cloud = () => document.getElementById('tag-cloud');
const chips = () => Array.from(cloud().querySelectorAll('.tag-cloud-item')).map(c => c.dataset.tag);
const toggle = () => cloud().querySelector('.tag-cloud-toggle');
const empty = () => cloud().querySelector('.tag-cloud-empty') ? 'yes' : 'no';
const has = (tag) => chips().includes(tag) ? 'yes' : 'no';
const chip = (tag) => cloud().querySelector('.tag-cloud-item[data-tag="' + tag + '"]');
const caret = (tag) => chip(tag).querySelector('.tag-cloud-caret');
const kids = () => Array.from(cloud().querySelectorAll('.tag-cloud-children > .tag-cloud-item, .tag-cloud-children > .tag-cloud-group > .tag-cloud-item'))
    .map(c => c.textContent).join(',');
const type = async (text) => {
  const input = document.getElementById('search-query-input');
  input.value = text;
  input.dispatchEvent(new Event('input', { bubbles: true }));
  await sleep(100);
};

window.addEventListener('error', e => { document.title = 'PROBE fatal=' + e.message; });
window.addEventListener('unhandledrejection',
    e => { document.title = 'PROBE fatal=' + (e.reason && e.reason.message || e.reason); });

setTimeout(async () => {
  try {
    let out = ' initial=' + chips().length + ' common=' + has('common')
        + ' zeta=' + has('zzz-rare-zeta') + ' toggle=' + (toggle()?.textContent || 'none');
    toggle().click(); await sleep(100);
    out += ' expanded=' + chips().length + ' zeta2=' + has('zzz-rare-zeta')
        + ' toggle2=' + (toggle()?.textContent || 'none');
    toggle().click(); await sleep(100);
    out += ' collapsed=' + chips().length;
    await type('ZETA');
    out += ' filtered=' + chips().join(',') + ' ftoggle=' + (toggle() ? 'yes' : 'no');
    await type('nomatch');
    out += ' none=' + chips().length + ' empty=' + empty();
    await type('');
    out += ' cleared=' + chips().length;
    // A chip still opens its tag's results.
    cloud().querySelector('.tag-cloud-item[data-tag="common"]').click();
    await sleep(800);
    out += ' results=' + document.querySelectorAll('#viewer-content .sr-card').length;

    // Grouping.
    out += ' dept=' + chip('Department').textContent + ' deptkids=' + (has('Department/HR') + has('Department/Finance'));
    caret('Department').click(); await sleep(100);
    out += ' opened=' + kids();
    out += ' kidtitles=' + Array.from(cloud().querySelectorAll('.tag-cloud-children > .tag-cloud-item')).map(c => c.title).join(',');
    caret('Department/Finance').click(); await sleep(100);
    out += ' opened2=' + kids();
    await type('budget');
    out += ' fbudget=' + chips().join(',');
    const fchip = cloud().querySelector('.tag-cloud-item');
    out += ' fbtext=' + fchip.textContent + '@' + fchip.title;
    await type('zeta');
    out += ' fflat=' + (cloud().querySelector('.tag-cloud-item').title || '-');
    await type('');
    out += ' kept=' + has('Department/Finance/Budget');
    caret('Department').click(); await sleep(100);
    out += ' closed=' + has('Department/HR');
    chip('Department').click();
    await sleep(800);
    out += ' bresults=' + document.querySelectorAll('#viewer-content .sr-card').length + ' ';
    document.title = 'PROBE' + out;
  } catch (e) {
    document.title = 'PROBE fatal=' + (e && e.message || e);
  }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=30000 --dump-dom "$WIKI_URL/index.php?space=Main" \
    > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'collapsed by default'
assert_contains "shows the top 40 of 48"          ' initial=40 '              "$PROBE"
assert_contains "the most-used tag is among them" ' common=yes '              "$PROBE"
assert_contains "a one-page tag can be left out"  ' zeta=no '                 "$PROBE"
assert_contains "offers to show all, with count"  ' toggle=Show all (48) '    "$PROBE"

section 'Show all / Show fewer'
assert_contains "expanding shows every tag"       ' expanded=48 '             "$PROBE"
assert_contains "  including the left-out one"    ' zeta2=yes '               "$PROBE"
assert_contains "  and offers to collapse"        ' toggle2=Show fewer '      "$PROBE"
assert_contains "collapsing goes back to 40"      ' collapsed=40 '            "$PROBE"

section 'typing filters'
assert_contains "case-insensitive, beyond the cut" ' filtered=zzz-rare-zeta '     "$PROBE"
assert_contains "no toggle while filtering"       ' ftoggle=no '              "$PROBE"
assert_contains "no match says so"                ' none=0 empty=yes '        "$PROBE"
assert_contains "clearing restores the top 40"    ' cleared=40 '              "$PROBE"

section 'chips still work'
assert_contains "a chip opens the tagged pages"   ' results=10 '              "$PROBE"

section 'nested tags are grouped'
assert_contains "one chip, counted in distinct pages" ' dept=▸Department (4) ' "$PROBE"
assert_contains "  its children hidden until opened"  ' deptkids=nono '      "$PROBE"
assert_contains "children show the last segment, full path on hover" ' kidtitles=Department/Finance,Department/HR ' "$PROBE"
assert_contains "the caret opens the next level; case variants merge" \
                                                   ' opened=▸Finance (2),HR (2) ' "$PROBE"
assert_contains "a sub-branch opens in turn"       ' opened2=▾Finance (2),Budget (1),HR (2) ' "$PROBE"
assert_contains "filtering is flat, on the full path" ' fbudget=Department/Finance/Budget ' "$PROBE"
assert_contains "  showing the last segment, full path on hover" ' fbtext=Budget (1)@Department/Finance/Budget ' "$PROBE"
assert_contains "  a plain tag gets no tooltip"   ' fflat=- '                "$PROBE"
assert_contains "opened branches survive a filter" ' kept=yes '               "$PROBE"
assert_contains "the caret closes it again"        ' closed=no '              "$PROBE"
assert_contains "a branch lists everything under it" ' bresults=4 '          "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
