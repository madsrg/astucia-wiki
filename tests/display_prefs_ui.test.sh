# My Preferences' two size sliders and the font, in a browser: what the page actually
# computes, which HTTP cannot see (tests/display_prefs.test.sh covers the server half).
#
#   - The interface slider moves the root size; the text slider moves content only, on top
#     of it — the open page and the dialog's sample — and leaves the sidebar alone.
#   - Both are a live preview, so closing without saving must put everything back.
#   - Saving keeps them, and the bundled font is the one actually loaded.
#
# Same mechanics as preferences_avatar_ui.test.sh. Chrome missing means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start otp || exit 1
trap fixture_stop EXIT
fixture_space Main
fixture_users '{"users":[
  {"uid":1,"sub":"s1","name":"Admin","role":"admin","auth":"oidc"},
  {"uid":2,"sub":"s2","name":"Ed","role":"editor","auth":"oidc","email":"ed@example.com"}]}'
printf '# Sizes\n\nSome body text to measure.\n' > "$WIKI_PAGES/Main/Sizes.md"
SETUP=$WIKI_ROOT/setup-jar
fixture_login "$SETUP" "uid=1&sub=s1&name=Admin&role=admin"
get_as "$SETUP" 'api.php?action=list_spaces' > /dev/null
get_as "$SETUP" 'api.php?action=indexfiles&space=Main' > /dev/null
PAGE_ID=$(python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == "Sizes.md"))' "$WIKI_PAGES/Main/index.json")

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/display_prefs_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')    { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css')   { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg')   { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    if ($e === 'woff2') { header('Content-Type: font/woff2');      readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (s) => document.querySelector(s);
const report = (v) => document.documentElement.setAttribute('data-probe', v);
window.addEventListener('error', e => report('fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report('fatal=' + (e.reason && e.reason.message || e.reason)));
const px = (el) => el ? Math.round(parseFloat(getComputedStyle(el).fontSize) * 100) / 100 : 'none';
const sizes = () => 'root:' + px(document.documentElement) + ',page:' + px($('#viewer-content'))
    + ',side:' + px($('#preferences-btn'));
const slide = (id, v) => { const el = $(id); el.value = String(v); el.dispatchEvent(new Event('input', { bubbles: true })); };
setTimeout(async () => {
  try {
    let out = 'start=' + sizes();
    out += ' family=' + getComputedStyle(document.body).fontFamily.split(',')[0].replace(/["']/g, '').trim();

    $('#preferences-btn').click();                              await sleep(1500);
    out += ' shown=' + $('#pref-ui-scale-val').textContent + '/' + $('#pref-text-scale-val').textContent;
    slide('#pref-ui-scale', 120);                               await sleep(100);
    out += ' ui120=' + sizes();
    slide('#pref-text-scale', 80);                              await sleep(100);
    out += ' text80=' + sizes() + ',sample:' + px($('.pref-text-sample'));
    out += ' label=' + $('#pref-text-scale-val').textContent;
    $('[data-font-val="source"]').click();                      await sleep(100);
    out += ' srcfont=' + getComputedStyle(document.body).fontFamily.split(',')[0].replace(/["']/g, '').trim();
    await document.fonts.load('1em "Source Sans 3"');
    out += ' loaded=' + [...document.fonts].some(f => f.family.replace(/["']/g, '') === 'Source Sans 3' && f.status === 'loaded');
    $('[data-scale-reset="text"]').click();                     await sleep(100);
    out += ' reset=' + $('#pref-text-scale').value;

    // Closing without saving: back to what is stored.
    $('#preferences-lightbox-close-btn').click();               await sleep(200);
    out += ' cancelled=' + sizes() + ',font:' + document.documentElement.dataset.font;

    $('#preferences-btn').click();                              await sleep(1500);
    out += ' reopened=' + $('#pref-ui-scale').value + '/' + $('#pref-text-scale').value;
    slide('#pref-ui-scale', 90);
    slide('#pref-text-scale', 85);                              await sleep(100);
    $('#preferences-save-btn').click();                         await sleep(2500);
    out += ' closed=' + $('#preferences-lightbox').classList.contains('hidden');
    out += ' saved=' + sizes();
    report(out);
  } catch (e) { report('fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -d "session.cookie_lifetime=3600" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

PROFILE="$WIKI_ROOT/chrome-profile"
chrome() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --user-data-dir="$PROFILE" --virtual-time-budget=30000 \
        --dump-dom "$1" 2>/dev/null
}
chrome "$WIKI_URL/__test_login.php?uid=2&sub=s2&name=Ed&role=editor" > /dev/null
chrome "$WIKI_URL/index.php?pageid=$PAGE_ID&space=Main" > "$WIKI_ROOT/dom.html"
PROBE=$(grep -o 'data-probe="[^"]*"' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
[ -n "${SHOW_PROBE:-}" ] && printf "%s\n" "$PROBE"
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

# 11pt = 14.67px. The sidebar button is 0.82rem-ish UI; only its ratio to the root matters.
section 'the defaults, and the bundled font'
assert_contains "root at 11pt, the page at 90% of it" 'start=root:14.67,page:13.2' "$PROBE"
assert_contains "the system font by default"        'family=Segoe UI'             "$PROBE"
assert_contains "the sliders open at 100% and 90%"  'shown=100%/90%'              "$PROBE"

section 'interface moves everything; text moves content only'
assert_contains "interface 120%: root and page follow" 'ui120=root:17.6,page:15.84' "$PROBE"
assert_contains "text 80%: the page shrinks, the root stays" 'text80=root:17.6,page:14.08' "$PROBE"
assert_contains "and the dialog's sample with it"   'sample:14.08'                "$PROBE"
assert_contains "the slider says 80%"               'label=80%'                   "$PROBE"
assert_contains "Source Sans puts the bundled font first" 'srcfont=Source Sans 3' "$PROBE"
assert_contains "and it is the font that loaded"    'loaded=true'                 "$PROBE"
assert_contains "Reset goes back to 90"             'reset=90'                    "$PROBE"
# The sidebar is UI: at 120% its size must have grown with the root, then held at 80% text.
SIDE_UI=$(printf '%s' "$PROBE" | grep -o 'ui120=[^ ]*' | grep -o 'side:[0-9.]*' | cut -d: -f2)
SIDE_TX=$(printf '%s' "$PROBE" | grep -o 'text80=[^ ]*' | grep -o 'side:[0-9.]*' | cut -d: -f2)
assert_eq "the sidebar ignores the text size"       "$SIDE_UI" "$SIDE_TX"

section 'closing without saving puts it all back'
assert_contains "sizes back to the defaults"        'cancelled=root:14.67,page:13.2' "$PROBE"
assert_contains "and the font back to sans"         'font:sans'                   "$PROBE"
assert_contains "the sliders reopen at what is stored" 'reopened=100/90'        "$PROBE"

section 'saving keeps them'
assert_contains "the dialog closes"                 'closed=true'                 "$PROBE"
assert_contains "90% interface, 85% text"           'saved=root:13.2,page:11.22'  "$PROBE"
assert_eq "stored" '90/85' "$(python3 -c "import json;u=[u for u in json.load(open('$WIKI_SYS/users.json'))['users'] if u['uid']==2][0];print(f\"{u.get('uiScale')}/{u.get('textScale')}\")")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
