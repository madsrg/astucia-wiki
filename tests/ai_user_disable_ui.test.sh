# Switching an AI user off, as an administrator and as somebody chatting.
#
# tests/ai_user_disable.test.sh holds the server to it on every route; this is the half no
# HTTP request can see: the switch in the AI Users list reaches the server, the # type-ahead
# stops offering the AI, a message that names it is answered in the thread instead of opening
# the "AI is working" modal, and a thread focused on it says so rather than posting a plain
# message that nobody routes.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Main
# No reachable model: nothing here should ever get as far as calling one.
CFG='"ai_config":{"provider":"openai","api_url":"http://127.0.0.1:9/none","api_key":"k","model":"m"}'
fixture_users "{\"users\":[
 {\"uid\":-7,\"name\":\"Bot\",\"role\":\"editor\",\"is_ai\":true,$CFG},
 {\"uid\":-8,\"name\":\"Bot Pro\",\"role\":\"editor\",\"is_ai\":true,$CFG}]}"
fixture_page 'Main/Team.chat' '{"messages":[],"nextMessageId":1,"topic":"Team"}'
curl -s "$WIKI_URL/api.php?action=list_spaces" > /dev/null
curl -s "$WIKI_URL/api.php?action=indexfiles&space=Main" > /dev/null
page_id() { python3 -c 'import json,sys
print(next(k for k,v in json.load(open(sys.argv[1])).items() if v.get("path")==sys.argv[2]))' "$WIKI_PAGES/Main/index.json" "$1"; }

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/ai_user_disable_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# Reported through document.title. No backslashes in here: this lives in a Python heredoc
# inside a shell script.
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const report = (out) => { document.title = 'PROBE' + out; };
const users = async () => (await (await fetch('api.php?action=get_user_list')).json()).data;
const offOnServer = async (name) => ((await users()).find(u => u.name === name) || {}).disabled === true;

window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));

const run = async () => {
  let out = '';
  // ── the switch in Admin → AI Users ──
  $('#admin-btn').click();                                  await sleep(800);
  $('.admin-group[data-group="ai"]').click();               await sleep(1200);
  const row = Array.from(document.querySelectorAll('#admin-ai-list tbody tr'))
    .find(r => r.querySelector('.admin-td-name').textContent.trim() === 'Bot AI');
  const sw = row && row.querySelector('.ai-toggle');
  out += ' switch=' + (sw ? (sw.checked ? 'on' : 'off') : 'missing');
  sw.click();                                               await sleep(1200);
  out += ' server=' + (await offOnServer('Bot') ? 'off' : 'on');
  out += ' dimmed=' + row.classList.contains('ai-row-off');
  $('#admin-lightbox-close-btn').click();                   await sleep(500);

  // ── the composer ──
  const ta = $('#chat-input'), send = $('#chat-send-btn');
  // The type-ahead offers only the AI that would answer.
  ta.focus(); ta.value = '#Bo'; ta.setSelectionRange(3, 3);
  ta.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'insertText', data: 'o' }));
  await sleep(800);
  out += ' typeahead=[' + Array.from(document.querySelectorAll('.chat-mention-item')).map(i => i.textContent).join('|') + ']';
  ta.value = '';
  ta.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'deleteContentBackward' }));
  await sleep(300);

  // Naming it posts the message and says why nobody answers; no waiting modal.
  ta.value = '#Bot are you there?';
  send.click();                                             await sleep(1500);
  const notice = document.querySelector('#chat-messages .chat-bubble-notice');
  out += ' notice=[' + (notice ? notice.textContent : '') + ']';
  out += ' modal=' + (document.getElementById('ai-processing-modal')?.classList.contains('hidden') === false ? 'open' : 'closed');
  // Naming an AI normally focuses the thread on it; a switched-off one must not be focused,
  // or every later plain message would be routed to an AI that will not answer.
  // Read from where focus is kept, not from a chip: the page-chat panel has one too, so
  // the first .chat-focus-chip on the page is not necessarily this thread's.
  const focusMap = JSON.parse(localStorage.getItem('chatFocusAi') || '{}');
  out += ' focus=' + (Object.values(focusMap).filter(Boolean).join(',') || 'none');
  out += ' posted=' + Array.from(document.querySelectorAll('#chat-messages .chat-bubble, #chat-messages [data-id]')).some(el => el.textContent.includes('are you there'));
  return out;
};
setTimeout(async () => {
  try { report(await run()); } catch (e) { report(' fatal=' + (e && e.message || e)); }
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=40000 \
    --dump-dom "$WIKI_URL/index.php?pageid=$(page_id Team.chat)&space=Main" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the switch in Admin → AI Users'
assert_contains "each row has one, on to begin with"   'switch=on'    "$PROBE"
assert_contains "turning it off reaches the server"    'server=off'   "$PROBE"
assert_contains "  …and the row is dimmed"             'dimmed=true'  "$PROBE"

section 'somebody chatting'
assert_contains "the type-ahead offers only the AI that answers" 'typeahead=[#Bot Pro]' "$PROBE"
assert_contains "naming it gets a reply in the thread saying so" 'notice=[AI User Bot is currently disabled.]' "$PROBE"
assert_contains "  …without the waiting modal"         'modal=closed' "$PROBE"
assert_contains "  …and without focusing the thread on it" 'focus=none' "$PROBE"
assert_contains "  …and the message is still posted"   'posted=true'  "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
