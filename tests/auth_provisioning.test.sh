# Automatic access for SSO sign-ins (provisioning.php): rules on the provider's claims.
#
#   - without rules nothing changes: a request, now carrying the claims (minus protocol
#     and token-like fields) so the admin can see what to write rules on;
#   - saving validates: never Admin, a real domain, real Spaces, admins only;
#   - a matching first sign-in gets an account at once, with the rule's role and Spaces,
#     and is signed in; the first matching rule decides; lists (groups) match by member;
#   - email-domain rules: exact domain, never a subdomain or look-alike, and never when the
#     provider says the address is unverified;
#   - what rules must not override: an address matching an existing account (stays a
#     request, for linking), a denied request, an account that already exists;
#   - unmatched = deny turns people away with no request; and the request list previews
#     which rule would admit a pending request;
#   - a hand-edited settings.json cannot make a rule grant Admin.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

fixture_start both || exit 1
trap fixture_stop EXIT
fixture_space Main; fixture_space Docs; fixture_space Secret
fixture_page 'Main/Main.md' '# Welcome'
fixture_users '{"users":[
  {"uid":1,"name":"Admin","sub":"s-admin","email":"admin@example.com","role":"admin","auth":"oidc"},
  {"uid":2,"name":"Olga","otpEmail":"olga@example.com","email":"olga@example.com","role":"editor","auth":"otp"},
  {"uid":3,"name":"Ed","sub":"s-ed","email":"ed@corp.example","role":"editor","auth":"oidc"}
]}'
cat > "$WIKI_APP/__test_oidc.php" <<'SHIM'
<?php
// GENERATED BY tests/auth_provisioning.test.sh — the provider's half of an SSO sign-in.
require_once __DIR__ . '/config.php';
require_once __DIR__ . '/accounts.php';
require_once __DIR__ . '/remember_me.php';
session_start();
$c = json_decode($_GET['claims'] ?? '{}', true) ?: [];
echo wiki_oidc_complete(['sub' => $c['sub'] ?? '', 'email' => $c['email'] ?? '', 'name' => $c['name'] ?? '', 'claims' => $c], 'idtok');
SHIM

USERS=$WIKI_SYS/users.json
REQS=$WIKI_SYS/user_requests.json
ADM=$WIKI_ROOT/jar-admin
fixture_login "$ADM" "uid=1&sub=s-admin&name=Admin&role=admin"
# sso <jar> <claims json> — prints where the browser is sent
sso() { rm -f "$1"; curl -s -b "$1" -c "$1" --max-time 15 -G --data-urlencode "claims=$2" "$WIKI_URL/__test_oidc.php"; }
whoami() { get_as "$1" 'index.php' | command grep -o 'data-user-uid="[0-9]*"' | command grep -o '[0-9]*'; }
user_by_sub() { python3 -c "import json;r=[x for x in json.load(open('$USERS'))['users'] if x.get('sub')=='$1'];print(json.dumps({k:r[0].get(k) for k in ('role','spaces','provisionedBy')}) if r else 'none')"; }
req() { python3 -c "import json;r=[x for x in json.load(open('$REQS'))['requests'] if x['sub']=='$1'];print(r[0].get('$2','-') if r else 'none')" 2>/dev/null || echo none; }
save_rules() { post_as "$ADM" 'api.php?action=admin_save_provisioning' "config=$1"; }
TENANT='72f988bf-0000-4000-8000-000000000001'

section 'without rules, nothing changes'
J=$WIKI_ROOT/j1
assert_eq 'a new identity files a request'                  pending_access.php "$(sso "$J" "{\"sub\":\"s-new1\",\"name\":\"New One\",\"email\":\"n1@corp.example\",\"tid\":\"$TENANT\",\"nonce\":\"xyz\",\"at_hash\":\"abc\",\"exp\":9999999999}")"
CL=$(python3 -c "import json;r=[x for x in json.load(open('$REQS'))['requests'] if x['sub']=='s-new1'];print(json.dumps(r[0].get('claims',{})))")
assert_contains 'carrying the claims, for writing rules'    "\"tid\": \"$TENANT\"" "$CL"
assert_not_contains 'but not the nonce'                     'nonce' "$CL"
assert_not_contains 'nor token hashes or times'             'at_hash' "$CL$(printf '%s' "$CL" | grep -o '"exp"')"

section 'saving validates'
assert_contains 'never Admin'                               'never Admin' "$(save_rules '{"rules":[{"claim":"tid","op":"equals","value":"x","role":"admin"}]}')"
assert_contains 'a domain must be a domain'                 'not a domain' "$(save_rules '{"rules":[{"claim":"email","op":"email_domain","value":"not a domain","role":"reader"}]}')"
assert_contains 'Spaces must exist'                         'no Space' "$(save_rules '{"rules":[{"claim":"tid","op":"equals","value":"x","role":"reader","spaces":["Nope"]}]}')"
fixture_login "$WIKI_ROOT/ed" "uid=3&sub=s-ed&name=Ed&role=editor"
assert_contains 'admins only'                               'Admin' "$(post_as "$WIKI_ROOT/ed" 'api.php?action=admin_save_provisioning' 'config={"rules":[]}')"
R=$(save_rules "{\"rules\":[
  {\"claim\":\"tid\",\"op\":\"equals\",\"value\":\"$TENANT\",\"role\":\"editor\",\"spaces\":[\"Main\",\"Docs\"]},
  {\"claim\":\"groups\",\"op\":\"equals\",\"value\":\"wiki-readers\",\"role\":\"reader\",\"spaces\":null},
  {\"claim\":\"email\",\"op\":\"email_domain\",\"value\":\"@Example.ORG\",\"role\":\"reader\",\"spaces\":null}
],\"unmatched\":\"request\"}")
assert_contains 'positive control: valid rules are saved'   '"success":true' "$R"
assert_contains '…with the domain normalised'               '"value":"example.org"' "$R"

section 'a matching first sign-in gets an account at once'
P=$WIKI_ROOT/p1
assert_eq 'the tenant rule admits'                          index.php "$(sso "$P" "{\"sub\":\"s-tina\",\"name\":\"Tina\",\"email\":\"tina@corp.example\",\"tid\":\"$TENANT\"}")"
assert_eq 'with the rule role and Spaces'                   '{"role": "editor", "spaces": ["Main", "Docs"], "provisionedBy": "rule 1"}' "$(user_by_sub s-tina)"
assert_eq 'and is signed in'                                4 "$(whoami "$P")"
assert_eq 'no request was filed'                            none "$(req s-tina status)"
assert_eq 'the first matching rule decides'                 editor "$(sso "$WIKI_ROOT/p2" "{\"sub\":\"s-two\",\"name\":\"Two\",\"tid\":\"$TENANT\",\"groups\":[\"wiki-readers\"]}" > /dev/null; user_by_sub s-two | python3 -c 'import json,sys;print(json.load(sys.stdin)["role"])')"
assert_eq 'a list claim matches by member'                  reader "$(sso "$WIKI_ROOT/p3" '{"sub":"s-grp","name":"Grp","groups":["staff","wiki-readers"]}' > /dev/null; user_by_sub s-grp | python3 -c 'import json,sys;print(json.load(sys.stdin)["role"])')"
assert_eq 'a request filed before the rule is answered by it' index.php "$(sso "$WIKI_ROOT/p4" "{\"sub\":\"s-new1\",\"name\":\"New One\",\"email\":\"n1@corp.example\",\"tid\":\"$TENANT\"}")"
assert_eq '…and removed'                                    none "$(req s-new1 status)"

section 'email-domain rules'
assert_eq 'the exact domain admits'                         index.php "$(sso "$WIKI_ROOT/d1" '{"sub":"s-d1","name":"D1","email":"d1@example.org"}')"
assert_eq 'a subdomain does not'                            pending_access.php "$(sso "$WIKI_ROOT/d2" '{"sub":"s-d2","name":"D2","email":"d2@mail.example.org"}')"
assert_eq 'nor a look-alike'                                pending_access.php "$(sso "$WIKI_ROOT/d3" '{"sub":"s-d3","name":"D3","email":"d3@notexample.org"}')"
assert_eq 'an unverified address does not'                  pending_access.php "$(sso "$WIKI_ROOT/d4" '{"sub":"s-d4","name":"D4","email":"d4@example.org","email_verified":false}')"
assert_eq 'positive control: a verified one does'           index.php "$(sso "$WIKI_ROOT/d5" '{"sub":"s-d5","name":"D5","email":"d5@example.org","email_verified":true}')"

section 'what rules do not override'
assert_eq 'an address matching an account stays a request'  pending_access.php "$(sso "$WIKI_ROOT/c1" "{\"sub\":\"s-olga\",\"name\":\"Olga K\",\"email\":\"olga@example.com\",\"tid\":\"$TENANT\"}")"
assert_eq '…so the admin can link it, not a second account' none "$(user_by_sub s-olga)"
python3 - "$REQS" <<'PY'
import json, sys
d = json.load(open(sys.argv[1])); d['requests'].append({'sub': 's-den', 'name': 'Den', 'email': 'den@x.example', 'status': 'denied'})
json.dump(d, open(sys.argv[1], 'w'))
PY
sso "$WIKI_ROOT/c2" "{\"sub\":\"s-den\",\"name\":\"Den\",\"tid\":\"$TENANT\"}" > /dev/null
assert_eq 'a denied request stays denied'                   none "$(user_by_sub s-den)"
assert_eq '…and on record'                                  denied "$(req s-den status)"
sso "$WIKI_ROOT/c3" "{\"sub\":\"s-ed\",\"name\":\"Ed\",\"email\":\"ed@corp.example\",\"groups\":[\"wiki-readers\"]}" > /dev/null
assert_eq 'an existing account keeps its role'              editor "$(user_by_sub s-ed | python3 -c 'import json,sys;print(json.load(sys.stdin)["role"])')"

section 'the request list previews the rules'
sso "$WIKI_ROOT/v1" '{"sub":"s-later","name":"Later","email":"later@corp.example","groups":["staff"]}' > /dev/null
save_rules "{\"rules\":[{\"claim\":\"groups\",\"op\":\"equals\",\"value\":\"staff\",\"role\":\"reader\",\"spaces\":null}],\"unmatched\":\"request\"}" > /dev/null
L=$(get_as "$ADM" 'api.php?action=admin_get_user_requests' | python3 -c 'import json,sys;print(json.dumps({r["sub"]:r.get("rule") for r in json.load(sys.stdin)["data"]}))')
assert_contains 'a pending request shows the rule that would admit it' '"s-later": 1' "$L"
assert_contains 'not one whose address matches an account'  '"s-olga": null' "$L"

section 'people who match no rule can be turned away'
save_rules '{"rules":[{"claim":"groups","op":"equals","value":"staff","role":"reader","spaces":null}],"unmatched":"deny"}' > /dev/null
assert_eq 'a new identity that matches nothing is turned away' not_registered.php "$(sso "$WIKI_ROOT/x1" '{"sub":"s-out","name":"Out","email":"out@else.example"}')"
assert_eq '…and no request is made'                         none "$(req s-out status)"
assert_eq 'positive control: a match still gets in'         index.php "$(sso "$WIKI_ROOT/x2" '{"sub":"s-in","name":"In","groups":["staff"]}')"

section 'a hand-edited settings file cannot grant Admin'
python3 - "$WIKI_SYS/settings.json" <<'PY'
import json, sys
p = sys.argv[1]; d = json.load(open(p))
d['sso_provisioning'] = {'rules': [{'claim': 'groups', 'op': 'equals', 'value': 'boss', 'role': 'admin', 'spaces': None}], 'unmatched': 'request'}
json.dump(d, open(p, 'w'))
PY
assert_eq 'the rule is ignored'                              pending_access.php "$(sso "$WIKI_ROOT/h1" '{"sub":"s-boss","name":"Boss","groups":["boss"]}')"
assert_eq 'no account was made'                             none "$(user_by_sub s-boss)"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
