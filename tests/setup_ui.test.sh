# The setup checklist and its LLM provider wizard, in a browser (tests/setup.test.sh covers
# the server's half). On a new wiki the checklist opens by itself; the wizard is driven end to
# end against a stand-in for an OpenAI-style service — a refused key first, which must save
# nothing, then a good one — and "Create an AI user" must land on the AI user form in Admin.
#
# Same mechanics as preferences_avatar_ui.test.sh. Chrome missing means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start otp || exit 1
trap 'fixture_stop; [ -n "${LLM_PID:-}" ] && kill "$LLM_PID" 2>/dev/null; true' EXIT
fixture_space Main
fixture_users '{"users":[{"uid":1,"sub":"s1","name":"Admin","role":"admin","auth":"oidc"}]}'

# ── a stand-in LLM service: /ok answers, /bad refuses the key ────────────────
LLM_DIR=$WIKI_ROOT/llm; mkdir -p "$LLM_DIR"
cat > "$LLM_DIR/router.php" <<'PHP'
<?php
file_put_contents(__DIR__ . '/calls', $_SERVER['REQUEST_URI'] . ' ' . ($_SERVER['HTTP_AUTHORIZATION'] ?? '') . "\n", FILE_APPEND);
header('Content-Type: application/json');
// As SendGrid too (MAIL_API_BASE_URL): a key containing "bad" is refused.
if (strpos($_SERVER['REQUEST_URI'], '/v3/mail/send') === 0) {
    if (strpos($_SERVER['HTTP_AUTHORIZATION'] ?? '', 'bad') !== false) {
        http_response_code(401);
        echo json_encode(['errors' => [['message' => 'The provided authorization grant is invalid']]]);
    } else http_response_code(202);
    return true;
}
if (strpos($_SERVER['REQUEST_URI'], '/bad') === 0) {
    http_response_code(401);
    echo json_encode(['error' => ['message' => 'Incorrect API key provided']]);
} else {
    echo json_encode(['choices' => [['message' => ['content' => 'OK from the stand-in']]]]);
}
return true;
PHP
LLM_PORT=$(python3 -c 'import socket;s=socket.socket();s.bind(("127.0.0.1",0));print(s.getsockname()[1]);s.close()')
( cd "$LLM_DIR" && exec php -S "127.0.0.1:$LLM_PORT" router.php ) > "$LLM_DIR/log" 2>&1 &
LLM_PID=$!
until curl -s --max-time 2 "http://127.0.0.1:$LLM_PORT/ok" >/dev/null 2>&1; do sleep 0.1; done
: > "$LLM_DIR/calls"
printf "\ndefine('MAIL_API_BASE_URL', 'http://127.0.0.1:%s');\n" "$LLM_PORT" >> "$WIKI_APP/config.php"

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/setup_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" "http://127.0.0.1:$LLM_PORT" <<'PY'
import io, sys
p, llm = sys.argv[1], sys.argv[2]
s = io.open(p, encoding='utf-8', newline='').read()
probe = """<script type="module">
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (s) => document.querySelector(s);
const $$ = (s) => [...document.querySelectorAll(s)];
const report = (v) => document.documentElement.setAttribute('data-probe', v);
const until = async (cond, steps = 200) => { for (let i = 0; i < steps && !cond(); i++) await sleep(25); return cond(); };
window.addEventListener('error', e => report('fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report('fatal=' + (e.reason && e.reason.message || e.reason)));
const visible = (sel) => { const n = $(sel); return !!n && !n.closest('.hidden') && n.offsetParent !== null; };
const setVal = (sel, v) => { const n = $(sel); n.value = v; n.dispatchEvent(new Event('input', { bubbles: true })); };
setTimeout(async () => {
  try {
    // A new wiki: it opens by itself.
    let out = 'autoshown=' + await until(() => visible('#setup-modal .setup-row'));
    out += ' rows=' + $$('#setup-modal .setup-row').map(r => r.dataset.item + ':' + r.className.split(' ').find(c => c.startsWith('is-')).slice(3)).join(',');
    out += ' startup=' + $('#setup-startup').checked;

    // LLM provider → its detail → Set it up → the cards.
    $('#setup-modal .setup-row[data-item="llm"]').click();          await sleep(100);
    out += ' detail=' + !!$('#setup-modal .setup-detail-title') + ',more=' + ($('#setup-modal .setup-more')?.getAttribute('href') || '');
    $('#setup-modal [data-act="go"]').click();                        await sleep(100);
    out += ' cards=' + $$('#setup-modal .setup-card').map(c => c.dataset.preset).join(',');

    // Ollama: the address is shown, no key field.
    $('#setup-modal .setup-card[data-preset="ollama"]').click();      await sleep(100);
    out += ' ollama=key:' + !!$('#setup-llm-key') + ',url:' + visible('#setup-llm-url');
    $('#setup-modal [data-act="back"]').click();                      await sleep(100);

    // OpenAI: key field with its link, the address folded away. A refused key saves nothing.
    $('#setup-modal [data-item="llm"]').click();                      await sleep(100);
    $('#setup-modal [data-act="go"]').click();                        await sleep(100);
    $('#setup-modal .setup-card[data-preset="openai"]').click();      await sleep(100);
    out += ' openai=key:' + !!$('#setup-llm-key') + ',link:' + ($('.setup-key-link')?.getAttribute('href') || '') + ',urlHidden:' + !$('#setup-llm-url').closest('details')?.open;
    $('#setup-modal [data-act="llm-save"]').click();                  await sleep(200);
    out += ' nokey=' + ($('.setup-result.is-error') ? 'refused' : 'went-ahead');
    setVal('#setup-llm-key', 'sk-wrong');
    setVal('#setup-llm-url', '__LLM__/bad/v1/chat/completions');
    $('#setup-modal [data-act="llm-save"]').click();
    await until(() => $('.setup-result.is-error') && /401|Incorrect/.test($('.setup-result').textContent));
    out += ' badkey=' + JSON.stringify($('.setup-result').textContent.split('\\n').pop().slice(0, 40));

    // A good one: tested, saved, and the done view with the model's answer.
    setVal('#setup-llm-key', 'sk-good');
    setVal('#setup-llm-url', '__LLM__/ok/v1/chat/completions');
    $('#setup-modal [data-act="llm-save"]').click();
    await until(() => !!$('#setup-modal [data-act="next-ai"]'));
    out += ' done=' + JSON.stringify($('#setup-modal .setup-detail-title')?.textContent || '') + ',reply=' + JSON.stringify($('.setup-reply')?.textContent || '');

    // Create an AI user — the real button: Admin on the AI tab, with the new form open.
    $('#setup-modal [data-act="next-ai"]').click();
    await until(() => !!$('#ai-f-name'));
    out += ' admin=' + !$('#admin-lightbox').classList.contains('hidden')
        + ',tab:' + ($('.admin-tab.active')?.dataset.tab || '') + ',form:' + !!$('#ai-f-name')
        + ',conn:' + JSON.stringify($('#ai-f-connection option:checked')?.textContent || '');
    out += ' setupClosed=' + $('#setup-modal').classList.contains('hidden');
    $('#admin-lightbox-close-btn').click();                           await sleep(100);

    // The sidebar icon opens it again, LLM provider checked now; Show at startup unticked.
    $('#setup-btn').click();
    await until(() => visible('#setup-modal .setup-row'));
    out += ' llmNow=' + $('#setup-modal .setup-row[data-item="llm"]').className.includes('is-done');
    // Still ticked: the first step done must not untick it for the rest.
    out += ' startupKept=' + $('#setup-startup').checked;
    $('#setup-startup').click();                                      await sleep(600);

    // Email: the wizard, a refused key, then a good one.
    $('#setup-modal .setup-row[data-item="email"]').click();          await sleep(100);
    $('#setup-modal [data-act="go"]').click();
    await until(() => $$('#setup-modal .setup-card[data-mail]').length > 0);
    out += ' mailCards=' + $$('#setup-modal .setup-card[data-mail]').map(c => c.dataset.mail).join(',');
    $('#setup-modal .setup-card[data-mail="sendgrid"]').click();      await sleep(100);
    out += ' mailForm=to:' + $('#setup-mail-to').value + ',name:' + $('#setup-mail-name').value
        + ',regions:' + [...$('#setup-mail-region').options].map(o => o.value).join('/') + ',domain:' + !!$('#setup-mail-domain');
    setVal('#setup-mail-key', 'SG.bad');
    setVal('#setup-mail-from', 'wiki@example.com');
    $('#setup-modal [data-act="mail-save"]').click();
    await until(() => $('.setup-result.is-error'));
    out += ' mailBad=' + JSON.stringify($('.setup-result').textContent.split('\\n').pop().slice(0, 90));
    setVal('#setup-mail-key', 'SG.good');
    $('#setup-modal [data-act="mail-save"]').click();
    await until(() => !!$('#setup-modal [data-act="to-list"]'));
    out += ' mailDone=' + JSON.stringify($('#setup-modal .setup-detail-title').textContent);
    $('#setup-modal [data-act="to-list"]').click();                   await sleep(100);
    out += ' mailNow=' + $('#setup-modal .setup-row[data-item="email"]').className.includes('is-done')
        + ':' + JSON.stringify($('#setup-modal .setup-row[data-item="email"] .setup-row-summary').textContent);
    report(out);
  } catch (e) { report('fatal=' + (e && e.message || e)); }
}, 3000);
</script>
</body>""".replace('__LLM__', llm)
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -d "session.cookie_lifetime=3600" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

PROFILE="$WIKI_ROOT/chrome-profile"
chrome() {
    "$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
        --user-data-dir="$PROFILE" --virtual-time-budget=40000 \
        --dump-dom "$1" 2>/dev/null
}
chrome "$WIKI_URL/__test_login.php?uid=1&sub=s1&name=Admin&role=admin" > /dev/null
chrome "$WIKI_URL/index.php" > "$WIKI_ROOT/dom.html"
PROBE=$(grep -o 'data-probe="[^"]*"' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
[ -n "${SHOW_PROBE:-}" ] && printf '%s\n' "$PROBE"
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'a new wiki: the checklist opens by itself'
assert_contains "it opened"                        'autoshown=true' "$PROBE"
assert_contains "seven items, in order, with their states" \
    'rows=llm:todo,ai:todo,email:todo,taxonomy:todo,workflows:todo,cron:warn,auth:done ' "$PROBE"
assert_contains "Show at startup is ticked"         'startup=true' "$PROBE"
assert_contains "an item's detail links to the docs" 'more=https://astucia.wiki/docs/features/ai/#providers' "$PROBE"

section 'the LLM provider wizard'
assert_contains "the service cards, and Custom" 'cards=openai,anthropic,gemini,mistral,openrouter,groq,ollama,custom ' "$PROBE"
assert_contains "Ollama: no key, the address shown" 'ollama=key:false,url:true' "$PROBE"
assert_contains "OpenAI: a key with where to get one, the address folded away" \
    'openai=key:true,link:https://platform.openai.com/api-keys,urlHidden:true' "$PROBE"
assert_contains "no key: refused before any request" 'nokey=refused' "$PROBE"
assert_contains "a refused key: the provider's own error" 'Incorrect API key provided' "$PROBE"
assert_contains "a good one: connected"             'done="OpenAI is connected"' "$PROBE"
assert_contains "showing the model's answer"        'reply="OK from the stand-in"' "$PROBE"
assert_contains "and the checklist turns green"     'llmNow=true' "$PROBE"
assert_contains "with Show at startup still ticked" 'startupKept=true' "$PROBE"

STORED=$(php -r '$c = json_decode(file_get_contents($argv[1]), true); $c = $c["connections"] ?? $c;
    echo count($c), " ", $c[0]["name"] ?? "", " ", $c[0]["provider"] ?? "", " ", $c[0]["api_key"] ?? "";' "$WIKI_SYS/llm_connections.json" 2>/dev/null)
assert_eq "exactly one saved — the refused key was not" '1 OpenAI openai sk-good' "$STORED"
assert_contains "the stand-in saw the key it was given" 'Bearer sk-good' "$(cat "$LLM_DIR/calls")"

section 'into Admin'
assert_contains "Create an AI user: Admin on the AI tab, the form open" 'admin=true,tab:ai,form:true' "$PROBE"
assert_contains "offering the provider just added" 'conn:"OpenAI"' "$PROBE"
assert_contains "the checklist got out of the way"  'setupClosed=true' "$PROBE"
section 'the email wizard'
assert_contains "five services" 'mailCards=sendgrid,mailgun,postmark,brevo,resend ' "$PROBE"
assert_contains "the test goes to the administrator, the sender named after the wiki, SendGrid's regions, no domain" \
    'mailForm=to:test@example.com,name:Astucia Wiki,regions:global/eu,domain:false' "$PROBE"
assert_contains "a refused key: the provider's own error" 'authorization grant is invalid' "$PROBE"
assert_contains "a good one: set up"   'mailDone="Email is set up with SendGrid"' "$PROBE"
assert_contains "and the checklist says so" 'mailNow=true:"Sending through SendGrid"' "$PROBE"
assert_eq "saved, with the good key" 'sendgrid SG.good wiki@example.com' \
    "$(php -r '$d = json_decode(file_get_contents($argv[1]), true); echo $d["provider"], " ", $d["api_key"], " ", $d["from_email"];' "$WIKI_SYS/mail_settings.json")"

assert_eq "Show at startup unticked from the dialog" 'false' \
    "$(php -r '$d = json_decode(file_get_contents($argv[1]), true); echo json_encode($d["users"][0]["setupStartup"] ?? null);' "$WIKI_SYS/users.json")"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
