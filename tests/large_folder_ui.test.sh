# A folder too large for the sidebar, in the browser.
#
# A folder holding more than TREE_FOLDER_CAP (100) pages is drawn in the tree as its
# subfolders plus one "N items — browse…" row, and its pages are listed in the main area,
# 100 to a page, with a name filter and sortable columns. The traps this guards: a page in
# such a folder has no tree row, so its tags must still come from the tree data (they were
# read off the row), the open page must still be marked in the tree, and a small folder
# must be drawn exactly as before.
#
# Chrome is not a test dependency — no chrome means skip, not fail.

set -uo pipefail
cd "$(dirname "$0")"
. lib/assert.sh
. lib/fixture.sh

CHROME=""
for c in google-chrome chromium chromium-browser; do
    command -v "$c" >/dev/null 2>&1 && { CHROME="$c"; break; }
done
if [ -z "$CHROME" ]; then
    printf '  %s\n' "$(_dim 'skipped — no chrome/chromium on PATH')"
    exit 0
fi

fixture_start off || exit 1
trap fixture_stop EXIT
fixture_space Big
fixture_page 'Big/Main.md' '# Main'
mkdir -p "$WIKI_PAGES/Big/Archive/Sub" "$WIKI_PAGES/Big/Small"
for i in $(seq 1 250); do printf '# Note %s\n' "$i" > "$WIKI_PAGES/Big/Archive/Note $i.md"; done
printf '# Deep\n' > "$WIKI_PAGES/Big/Archive/Sub/Deep.md"
for n in One Two Three; do printf '# %s\n' "$n" > "$WIKI_PAGES/Big/Small/$n.md"; done
curl -s "$WIKI_URL/api.php?action=list&space=Big" > /dev/null

id_of() {
    python3 -c 'import json,sys
ix = json.load(open(sys.argv[1]))
print(next(k for k, v in ix.items() if v.get("path") == sys.argv[2]))' "$WIKI_PAGES/Big/index.json" "$1"
}
# Note 7 carries a tag, which loadPage reads through treeEntry() — off a tree row that a
# page in a large folder does not have. Note 42 is saved last, so it is the newest.
curl -s -X POST -d "id=$(id_of 'Archive/Note 7.md')&tags=%5B%22keep-me%22%5D" \
    "$WIKI_URL/api.php?action=update_tags&space=Big" > /dev/null
sleep 1
curl -s -X POST --data-binary '# Note 42, edited' \
    "$WIKI_URL/api.php?action=save&space=Big&file=Archive/Note%2042.md" > /dev/null

cat > "$WIKI_APP/__router.php" <<'R'
<?php
// GENERATED BY tests/large_folder_ui.test.sh — never part of a release.
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
$f = __DIR__ . $p;
if ($p !== '/' && is_file($f)) {
    $e = pathinfo($f, PATHINFO_EXTENSION);
    if ($e === 'js')  { header('Content-Type: text/javascript'); readfile($f); return true; }
    if ($e === 'css') { header('Content-Type: text/css');        readfile($f); return true; }
    if ($e === 'svg') { header('Content-Type: image/svg+xml');   readfile($f); return true; }
    return false;
}
return false;
R

python3 - "$WIKI_APP/index.php" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
# No backslashes in here: this lives in a Python heredoc inside a shell script.
probe = """<script type="module">
import { state } from './modules/core/state.js';
import { treeEntry } from './modules/file_tree/index.js';
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => [...document.querySelectorAll(sel)];
const report = (out) => { document.title = 'PROBE' + out; };
window.addEventListener('error', e => report(' fatal=' + e.message));
window.addEventListener('unhandledrejection', e => report(' fatal=' + (e.reason && e.reason.message || e.reason)));
const node = (p) => $('#file-navigator .file-item-content[data-path="' + p + '"]');
const kids = (p) => { const ul = node(p).parentElement.querySelector(':scope > ul');
                      return ul ? [...ul.children].map(li => li.querySelector('.file-item-content')) : []; };
const label = () => $('#ff-pager-label').textContent;
const rows = () => $$('#ff-file-list .fv-row');
const filter = async (v) => { const b = $('#ff-search-input'); b.value = v; b.dispatchEvent(new Event('input')); await sleep(200); };

setTimeout(async () => {
  let out = ' start=' + state.currentSpace;
  try {
    // Before anything is pinned, a page in the large folder has no row. treeEntry() is how
    // page_chat asks "is there a page beside this .chat" and how the tag strip re-reads tags.
    const te = treeEntry('Archive/Note 7.md');
    out += ' entryTags=' + JSON.stringify(te && te.tags) + ' entryId=' + !!(te && te.id)
        + ' noEntry=' + (treeEntry('Archive/Nope.md') === null);
    const arch = kids('Archive');
    out += ' archRows=' + arch.length
        + ' archTypes=' + arch.map(e => e.dataset.type).join(',')
        + ' moreText=[' + arch[arch.length - 1].textContent.trim() + ']'
        + ' count=' + (node('Archive').querySelector('.tree-count') || {}).textContent
        + ' smallRows=' + kids('Small').length
        + ' smallCount=' + !!node('Small').querySelector('.tree-count');

    node('Archive').click();                                  await sleep(800);
    out += ' listingShown=' + !$('#files-folder-container').classList.contains('hidden')
        + ' rows1=' + rows().length + ' label1=[' + label() + ']'
        + ' prev1=' + $('#ff-pager-prev').disabled;
    $('#ff-pager-next').click();                              await sleep(200);
    out += ' label2=[' + label() + ']';
    $('#ff-pager-next').click();                              await sleep(200);
    out += ' label3=[' + label() + '] next3=' + $('#ff-pager-next').disabled + ' rows3=' + rows().length;

    await filter('note 12');
    out += ' filtRows=' + rows().length + ' pagerHidden=' + $('#ff-pager').classList.contains('hidden');
    await filter('zzz');
    out += ' noMatch=[' + $('#ff-file-list .ff-empty').textContent + ']';
    await filter('');
    out += ' clearedLabel=[' + label() + ']';

    $('#ff-view-detailed').click();                           await sleep(500);
    $('#ff-file-list th[data-sort="modified"]').click();      await sleep(300);
    const names = $$('#ff-file-list tbody .ff-filename').map(e => e.textContent);
    out += ' byModified=' + names.slice(1, 3).join('|')
        + ' arrow=' + /▼/.test($('#ff-file-list th[data-sort="modified"]').textContent);
    $('#ff-file-list th[data-sort="name"]').click();          await sleep(300);
    $('#ff-view-simple').click();                             await sleep(500);

    // Open a page from the listing: the tree pins it, and its tags arrive.
    $('#ff-file-list .fv-row[title="Archive/Note 7.md"]').click(); await sleep(1500);
    const pinned = $('#file-navigator .tree-pinned .file-item-content');
    out += ' opened=' + state.currentPagePath
        + ' pinned=' + (pinned && pinned.dataset.path)
        + ' pinnedActive=' + !!(pinned && pinned.closest('.file-item').classList.contains('active'))
        + ' tags=' + JSON.stringify(state.currentPageTags);
    const browse = $$('#file-browser .browse-item-content').map(e => e.dataset.type + ':' + (e.dataset.path || '').split('/').pop());
    out += ' browse=' + browse.join(',');

    // Another page in the same folder replaces the pin rather than adding a second.
    $('#file-navigator [data-type="bigfolder"][data-path="Archive"]').click(); await sleep(800);
    out += ' moreOpensListing=' + (state.currentPageType === 'folder' && state.currentPagePath === 'Archive');
    $('#ff-file-list .fv-row[title="Archive/Note 9.md"]').click(); await sleep(1500);
    out += ' pins=' + $$('#file-navigator .tree-pinned').length
        + ' pinnedNow=' + ($('#file-navigator .tree-pinned .file-item-content') || { dataset: {} }).dataset.path;
  } catch (e) { out += ' fatal=' + (e && e.message || e); }
  report(out);
}, 4000);
</script>
</body>"""
assert s.count('</body>') == 1
io.open(p, 'w', encoding='utf-8', newline='').write(s.replace('</body>', probe))
PY

PORT="${WIKI_URL##*:}"
kill "$WIKI_PID" 2>/dev/null; wait "$WIKI_PID" 2>/dev/null
( cd "$WIKI_APP" && exec php -d "session.save_path=$WIKI_ROOT/sessions" \
    -S "127.0.0.1:$PORT" __router.php ) > "$WIKI_ROOT/router.log" 2>&1 &
WIKI_PID=$!
i=0
until curl -s --max-time 2 "$WIKI_URL/api.php?action=ping" > /dev/null 2>&1; do
    i=$((i + 1)); [ $i -gt 100 ] && { echo "router did not start" >&2; exit 1; }
    sleep 0.1
done

"$CHROME" --headless=new --disable-gpu --no-sandbox --window-size=1280,900 \
    --virtual-time-budget=60000 \
    --dump-dom "$WIKI_URL/index.php?space=Big" > "$WIKI_ROOT/dom.html" 2>/dev/null
PROBE=$(grep -o '<title>PROBE[^<]*</title>' "$WIKI_ROOT/dom.html" \
        | python3 -c 'import html,sys; sys.stdout.write(html.unescape(sys.stdin.read()))' || true)
[ -n "${LARGE_FOLDER_DEBUG:-}" ] && echo "$PROBE" >&2
[ -n "$PROBE" ] || _fail "the page never reported (probe did not run)" ""
assert_not_contains "the probe ran without throwing" 'fatal' "$PROBE"

section 'the tree'
assert_contains "a large folder shows its subfolder and one browse row, no pages" 'archRows=2 archTypes=folder,bigfolder' "$PROBE"
assert_contains "  the row says how many"                  'moreText=[250 items — browse…]' "$PROBE"
assert_contains "  and so does the folder"                 'count=250 '        "$PROBE"
assert_contains "a small folder is drawn as before"        'smallRows=3 smallCount=false' "$PROBE"

assert_contains "treeEntry() still knows a page that has no row" 'entryTags=["keep-me"] entryId=true' "$PROBE"
assert_contains "  and still says null for one that does not exist" 'noEntry=true' "$PROBE"

section 'the listing'
assert_contains "clicking the folder lists it in the main area" 'listingShown=true' "$PROBE"
assert_contains "  100 to a page, plus the .. row"         'rows1=101 '        "$PROBE"
assert_contains "  and the pager says where you are"       'label1=[1–100 of 251]' "$PROBE"
assert_contains "  with nowhere to go back to"             'prev1=true'        "$PROBE"
assert_contains "Next turns the page"                      'label2=[101–200 of 251]' "$PROBE"
assert_contains "  the last page is partial"               'label3=[201–251 of 251] next3=true rows3=52' "$PROBE"
assert_contains "the filter runs over the whole folder"    'filtRows=12 '      "$PROBE"
assert_contains "  and hides the pager when one page holds the matches" 'pagerHidden=true' "$PROBE"
assert_contains "  and says when nothing matches"          'noMatch=[Nothing in this folder matches.]' "$PROBE"
assert_contains "clearing it lands on the first page"      'clearedLabel=[1–100 of 251]' "$PROBE"
assert_contains "Modified sorts newest first (after folders)" 'byModified=Sub|Note 42' "$PROBE"
assert_contains "  and marks the column"                   'arrow=true'        "$PROBE"

section 'a page in a large folder'
assert_contains "it opens from the listing"                'opened=Archive/Note 7.md' "$PROBE"
assert_contains "  is pinned into the tree"                'pinned=Archive/Note 7.md' "$PROBE"
assert_contains "  and marked as open there"               'pinnedActive=true' "$PROBE"
assert_contains "  and its tags still arrive (no tree row to read them from)" 'tags=["keep-me"]' "$PROBE"
assert_contains "the browse pane: up, subfolder, the open page, browse row" \
                'browse=up:,folder:Sub,file:Note 7.md,bigfolder:Archive' "$PROBE"
assert_contains "the browse row opens the listing"         'moreOpensListing=true' "$PROBE"
assert_contains "the next page opened replaces the pin"    'pins=1 pinnedNow=Archive/Note 9.md' "$PROBE"

printf '\n'
exit $(( ASSERT_FAIL > 0 ))
